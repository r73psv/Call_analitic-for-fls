/**
 * Нормализует резюме так, чтобы оно ВСЕГДА содержало 4 четких блока:
 * 1) Краткая суть обращения (услуга, дата, время, мастер);
 * 2) Краткий пересказ разговора (СТРОГО 2–4 предложения);
 * 3) Вывод (итог диалога, предложения администратора и результат);
 * 4) Разбор работы менеджера с оценкой, конкретными ошибками/недочетами и практическими советами по оптимизации.
 * А также возвращает структурированное резюме из 8 параметров.
 */
export function formatSummaryWithEssence(
  rawSummary: string,
  transcript: string,
  extractedDetails?: EssenceDetails,
  customSalonName?: string,
  operatorScore?: number | null,
  operatorMistakes?: string[] | string | null,
  recommendations?: string[] | string | null,
  operatorComment?: string | null
): {
  formattedSummary: string;
  essence: EssenceDetails;
  structuredSummary: StructuredCallSummary;
  retelling?: string;
  conclusion?: string;
  managerEvaluation?: string;
  mistakes?: string[];
  advice?: string[];
  score?: number | null;
} {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();

  // Звонок не состоялся
  if (
    /разговор не состоялся|звонок не состоялся|диалог отсутствует/i.test(rawSummary) &&
    !transcript.toLowerCase().includes('клиент:')
  ) {
    const structuredSummary = extractStructuredCallSummary(transcript, rawSummary, undefined, salon, 'не применимо');
    return {
      formattedSummary: rawSummary,
      essence: { service: null, date: null, time: null, master: null },
      structuredSummary,
      retelling: '',
      conclusion: rawSummary,
      managerEvaluation: '',
      mistakes: [],
      advice: [],
      score: null,
    };
  }

  // Всегда запускаем надежный парсер, если какое-либо поле в переданных деталях отсутствует или недостоверно
  const fallbackEssence = extractEssenceDetails(transcript, rawSummary, salon);
  const isMeaningful = (v?: string | null) =>
    v &&
    typeof v === 'string' &&
    !v.toLowerCase().includes('не указан') &&
    !v.toLowerCase().includes('не выбран') &&
    !v.toLowerCase().includes('студио') &&
    v.trim().length > 0;

  const hasTimeCorrectionInTranscript = Boolean(
    fallbackEssence.time && transcript && /(?:убираю|отмените|отменить|оставляю|оставьте)/iu.test(transcript)
  );

  const essence: EssenceDetails = {
    service: isMeaningful(extractedDetails?.service) ? extractedDetails!.service : fallbackEssence.service,
    date: isMeaningful(extractedDetails?.date) ? extractedDetails!.date : fallbackEssence.date,
    time:
      hasTimeCorrectionInTranscript && fallbackEssence.time
        ? fallbackEssence.time
        : isMeaningful(extractedDetails?.time)
        ? extractedDetails!.time
        : fallbackEssence.time,
    master: isMasterNameValid(extractedDetails?.master)
      ? normalizeMasterName(extractedDetails!.master!)
      : fallbackEssence.master,
  };

  const serviceStr = essence.service || 'не указана';
  const dateStr = essence.date || 'не указана';
  const timeStr = essence.time || 'не указано';
  const masterStr = essence.master || 'не выбран';
  const essencePrefix = `Суть обращения: услуга — ${serviceStr}, дата — ${dateStr}, время — ${timeStr}, мастер — ${masterStr}.`;

  // 1. Попытка обнаружить блок разбора работы менеджера в исходном тексте
  const managerReviewMatch = rawSummary.match(
    /(?:разбор работы менеджера(?:\s*\([^)]*\))?|оценка и разбор работы менеджера|разбор работы оператора)\s*:\s*([\s\S]*)$/i
  );
  let rawManagerSection = managerReviewMatch ? managerReviewMatch[1].trim() : '';

  // Текст без блока разбора работы менеджера для чистого парсинга пересказа и вывода
  const summaryWithoutManager = rawSummary
    .replace(/(?:разбор работы менеджера(?:\s*\([^)]*\))?|оценка и разбор работы менеджера|разбор работы оператора)\s*:[\s\S]*$/i, '')
    .trim();

  // 2. Попытка извлечь существующие блоки из summaryWithoutManager
  const retellingMatch = summaryWithoutManager.match(
    /(?:пересказ диалога|краткий пересказ(?: разговора)?|пересказ разговора)\s*:\s*([\s\S]*?)(?=(?:вывод\s*:|$))/i
  );
  const conclusionMatch = summaryWithoutManager.match(/вывод\s*:\s*([\s\S]*)$/i);

  let retellingText = retellingMatch ? retellingMatch[1].trim() : '';
  let conclusionText = conclusionMatch ? conclusionMatch[1].trim() : '';

  // Очистка от ошибочного «мастеру Студио», «Меня Вот», «Записались»
  const badMasterRegex =
    /(?:к\s+мастеру\s+(?:Меня\s+Вот|Записались|Студио|Будете)|мастеру\s+(?:Меня\s+Вот|Записались|Студио|Будете)|Меня\s+Вот|к\s+мастеру\s+Студио)/gi;
  if (retellingText) {
    retellingText = retellingText.replace(badMasterRegex, essence.master ? `к мастеру ${essence.master}` : 'в салон');
  }
  if (conclusionText) {
    conclusionText = conclusionText.replace(badMasterRegex, essence.master ? `к мастеру ${essence.master}` : 'в салон');
  }

  // Если модель вернула единый текст без явных блоков пересказа и вывода
  if (!retellingText && !conclusionText) {
    const cleanRaw = summaryWithoutManager
      .replace(/^суть обращения:[^.]*\.?/i, '')
      .trim();

    if (cleanRaw.length > 0) {
      const sentences = cleanRaw.split(/(?<=[.!?])\s+/).filter(s => s.trim().length > 0);
      if (sentences.length >= 3) {
        conclusionText = sentences[sentences.length - 1].trim();
        retellingText = sentences.slice(0, sentences.length - 1).join(' ').trim();
      } else {
        conclusionText = cleanRaw;
      }
    }
  } else if (!retellingText && conclusionText) {
    const preConclusion = summaryWithoutManager
      .replace(/^суть обращения:[^.]*\.?/i, '')
      .replace(/вывод\s*:[\s\S]*$/i, '')
      .trim();
    if (preConclusion.length > 20) {
      retellingText = preConclusion;
    }
  }

  // Если пересказ диалога всё ещё пуст или содержал заглушки — синтезируем строго 2–4 связных предложения
  if (!retellingText || retellingText.includes('к мастеру Студио') || /свободное время\s*\./.test(retellingText)) {
    const isBooking = /запис|соглас|подтвержд/i.test(conclusionText || rawSummary || transcript);
    const isDeclined = /отказ|не удобн|не подход/i.test(conclusionText || rawSummary || transcript);

    const s1 = essence.service
      ? `Клиент позвонил в салон по вопросу записи на услугу «${essence.service}».`
      : `Клиент обратился в салон красоты по вопросам обслуживания и записи.`;

    const dateLabel = essence.date ? ` на ${essence.date}` : '';
    const timeLabel = essence.time ? ` в ${essence.time}` : '';
    const masterLabel = essence.master ? ` к мастеру ${essence.master}` : '';

    const s2 =
      essence.date || essence.time || essence.master
        ? `Администратор поприветствовал клиента и предложил свободное время${dateLabel}${timeLabel}${masterLabel}.`
        : `Администратор предоставил подробную консультацию по графику и условиям визита.`;

    const s3 = isBooking
      ? `Клиент согласовал предложенные условия и выбрал удобное для себя время.`
      : isDeclined
      ? `Клиент не смог подтвердить визит из-за неподходящего расписания или изменения планов.`
      : `Стороны обсудили детали визита и стоимость процедур.`;

    const s4 = isBooking
      ? `Сотрудник зафиксировал бронирование в расписании и завершил разговор на доброжелательной ноте.`
      : `Администратор вежливо ответил на все вопросы и предложил обращаться при необходимости.`;

    retellingText = `${s1} ${s2} ${s3} ${s4}`;
  }

  if (!conclusionText || conclusionText.includes('к мастеру Студио')) {
    const isBooking = /запис|соглас|подтвержд/i.test(rawSummary || transcript);
    const dateLabel = essence.date ? ` на ${essence.date}` : '';
    const timeLabel = essence.time ? ` в ${essence.time}` : '';
    const masterLabel = essence.master ? ` к мастеру ${essence.master}` : '';
    conclusionText = isBooking
      ? `Администратор согласовал запись${masterLabel}${dateLabel}${timeLabel}. Запись успешно подтверждена.`
      : `Администратор вежливо проконсультировал клиента по регламенту салона «${salon}».`;
  }

  // Очистка от возможных дублей заголовков
  retellingText = retellingText.replace(/^(?:пересказ диалога|краткий пересказ(?: разговора)?):\s*/i, '').trim();
  conclusionText = conclusionText.replace(/^вывод:\s*/i, '').trim();

  // 3. Формирование и извлечение 4-го блока: Разбор работы менеджера (оценка, ошибки, советы)
  let resolvedScore: number | null = null;
  if (typeof operatorScore === 'number' && !isNaN(operatorScore)) {
    resolvedScore = operatorScore;
  } else {
    const scoreInSummaryMatch = rawSummary.match(/оценка\s*(\d{1,2})\s*\/\s*10/i);
    if (scoreInSummaryMatch) {
      resolvedScore = parseInt(scoreInSummaryMatch[1], 10);
    } else {
      resolvedScore = 8;
    }
  }

  // Извлечение ошибок
  let mistakesList: string[] = [];
  if (Array.isArray(operatorMistakes) && operatorMistakes.length > 0) {
    mistakesList = operatorMistakes.map(m => String(m).trim()).filter(Boolean);
  } else if (typeof operatorMistakes === 'string' && operatorMistakes.trim().length > 0) {
    mistakesList = [operatorMistakes.trim()];
  } else if (rawManagerSection) {
    const mistakesSubMatch = rawManagerSection.match(
      /(?:ошибки и недочеты|ошибки|недочеты)\s*:\s*([\s\S]*?)(?=(?:советы по оптимизации|советы|рекомендации)\s*:|$)/i
    );
    if (mistakesSubMatch) {
      const rawText = mistakesSubMatch[1].trim();
      const splitItems = rawText
        .split(/(?:^|\n)\s*[-•*0-9.)]+\s*/g)
        .map(s => s.trim().replace(/^;\s*/, ''))
        .filter(s => s.length > 3);
      if (splitItems.length > 0) {
        mistakesList = splitItems;
      } else if (rawText) {
        mistakesList = [rawText];
      }
    }
  }

  // Если список ошибок всё ещё пуст
  if (mistakesList.length === 0) {
    if (resolvedScore === 10) {
      mistakesList = ['Грубых ошибок не допущено, регламент соблюден в полном объеме.'];
    } else if (operatorComment && /ошибк|недочет|пассивн|не предлож|не уточн/i.test(operatorComment)) {
      mistakesList = [operatorComment.trim()];
    } else {
      const isDeclined = /отказ|не удобн|не подход/i.test(conclusionText || rawSummary || transcript);
      const isDispute = /отмен|жалоб|претензи|недоволен/i.test(transcript);
      if (isDeclined) {
        mistakesList = [
          'Администратор не предложил альтернативные дни/слоты после первичного отказа клиента',
          'Не предложена запись в лист ожидания салона',
        ];
      } else if (isDispute) {
        mistakesList = [
          'Недостаточно оперативная отработка спорного момента',
          'Не зафиксированы четкие сроки разрешения претензии клиента',
        ];
      } else if (resolvedScore < 10) {
        mistakesList = [
          'Не предложены сопутствующие услуги салона (допродажа)',
          'Не оговорён регламент предварительного напоминания о визите накануне',
        ];
      }
    }
  }

  // Извлечение советов по оптимизации
  let adviceList: string[] = [];
  if (Array.isArray(recommendations) && recommendations.length > 0) {
    adviceList = recommendations.map(r => String(r).trim()).filter(Boolean);
  } else if (typeof recommendations === 'string' && recommendations.trim().length > 0) {
    adviceList = [recommendations.trim()];
  } else if (rawManagerSection) {
    const adviceSubMatch = rawManagerSection.match(
      /(?:советы по оптимизации|советы|рекомендации)\s*:\s*([\s\S]*)$/i
    );
    if (adviceSubMatch) {
      const rawText = adviceSubMatch[1].trim();
      const splitItems = rawText
        .split(/(?:^|\n)\s*[-•*0-9.)]+\s*/g)
        .map(s => s.trim().replace(/^;\s*/, ''))
        .filter(s => s.length > 3);
      if (splitItems.length > 0) {
        adviceList = splitItems;
      } else if (rawText) {
        adviceList = [rawText];
      }
    }
  }

  if (adviceList.length === 0) {
    const isDeclined = /отказ|не удобн|не подход/i.test(conclusionText || rawSummary || transcript);
    if (isDeclined) {
      adviceList = [
        'Предлагать вилку минимум из 2 вариантов времени или другие свободные дни',
        'Предлагать занесение в лист ожидания при занятости желаемого слота',
      ];
    } else {
      adviceList = [
        'Предлагать клиентам дополнительные услуги (снятие, уход, покрытие)',
        'Напоминать о подтверждении записи за 24 часа до визита',
      ];
    }
  }

  const mistakesFormatted = mistakesList.join('; ');
  const adviceFormatted = adviceList.join('; ');
  const managerEvaluationBlock = `Разбор работы менеджера (оценка ${resolvedScore}/10):\n- Ошибки и недочеты: ${mistakesFormatted}\n- Советы по оптимизации: ${adviceFormatted}`;

  const formattedSummary = `${essencePrefix} Пересказ диалога: ${retellingText} Вывод: ${conclusionText}\n${managerEvaluationBlock}`;

  const structuredSummary = extractStructuredCallSummary(
    transcript,
    rawSummary,
    {
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master
    },
    salon
  );

  return {
    formattedSummary,
    essence,
    structuredSummary,
    retelling: retellingText,
    conclusion: conclusionText,
    managerEvaluation: managerEvaluationBlock,
    mistakes: mistakesList,
    advice: adviceList,
    score: resolvedScore,
  };
}

/**
 * Разбирает ответ модели, опираясь на явные поля (is_conversation, call_outcome, booking_status),
 * а не на хрупкий поиск ключевых слов. Возвращает согласованный AnalysisResult.
 */
function parseGigaChatJson(text: string, customSalonName?: string, originalTranscript?: string): AnalysisResult {
  const salon = customSalonName || process.env.SALON_NAME || 'Fashion Look Studio';
  // Убираем markdown-обёртки, если они есть
  let clean = text.trim();
  if (clean.startsWith('```json')) {
    clean = clean.replace(/^```json\s*/, '').replace(/\s*```$/, '');
  } else if (clean.startsWith('```')) {
    clean = clean.replace(/^```\s*/, '').replace(/\s*```$/, '');
  }

  const jsonMatch = clean.match(/\{[\s\S]*\}/);
  if (jsonMatch) {
    clean = jsonMatch[0];
  }

  const parsed = JSON.parse(clean);

  const formattedTranscript =
    typeof parsed.formatted_transcript === 'string' && parsed.formatted_transcript.trim().length > 0
      ? parsed.formatted_transcript.trim()
      : undefined;

  const rawOutcome = String(parsed.key_facts?.call_outcome || '').toLowerCase().trim();
  const rawBooking = String(parsed.booking_status || parsed.key_facts?.booking_status || '').toLowerCase().trim();

  // Признак реального диалога: в стенограмме присутствуют обе роли.
  const transcriptHasBothRoles =
    !!formattedTranscript &&
    /менеджер\s*:/i.test(formattedTranscript) &&
    /клиент\s*:/i.test(formattedTranscript);

  // --- Определяем, состоялся ли разговор (главный переключатель) ---
  let isConversation: boolean;
  if (typeof parsed.is_conversation === 'boolean') {
    isConversation = parsed.is_conversation;
  } else if (rawOutcome === 'не состоялся' || rawOutcome === 'автоответчик' || rawBooking === 'не применимо') {
    isConversation = false;
  } else if (rawOutcome || rawBooking) {
    isConversation = true;
  } else {
    isConversation = transcriptHasBothRoles;
  }

  // Явные маркеры провала перекрывают вердикт, но ТОЛЬКО если в стенограмме нет обеих ролей.
  const combinedText = `${formattedTranscript || ''} ${parsed.transcript_summary || ''} ${parsed.summary || ''}`.toLowerCase();
  const explicitFailure =
    /разговор не состоялся|звонок не состоялся|автоответчик|автоинформатор|голосовая почта|оставьте сообщение|после сигнала|абонент временно недоступен|абонент занят|все операторы заняты/.test(combinedText);
  if (explicitFailure && !transcriptHasBothRoles) {
    isConversation = false;
  }

  // --- Ветка «разговор не состоялся» ---
  if (!isConversation) {
    const failedEval = extractCallEvaluation('', '', null, null, [], [], salon);
    return {
      transcript_summary: 'Разговор не состоялся: диалог отсутствует (тишина, гудки, сброс, автоответчик или автоинформатор).',
      booking_status: 'не применимо',
      formatted_transcript: formattedTranscript || 'Разговор не состоялся (диалог отсутствует)',
      evaluation: failedEval,
      criteria_scores: failedEval.criteria,
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: null,
        service: null,
        date: null,
        time: null,
        master: null,
        evaluation: failedEval,
        criteria_scores: failedEval.criteria,
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: 'Разговор не состоялся (диалог отсутствует).',
      recommendations: `Повторить попытку дозвона клиенту в рабочее время салона «${salon}».`,
    };
  }

  // --- Ветка «разговор состоялся»: нормализация полей ---
  let bookingStatus = rawBooking;
  if (!['согласие', 'отказ', 'консультация'].includes(bookingStatus)) {
    if (bookingStatus.includes('соглас') || rawOutcome === 'запись') {
      bookingStatus = 'согласие';
    } else if (bookingStatus.includes('отказ') || rawOutcome === 'отказ') {
      bookingStatus = 'отказ';
    } else {
      bookingStatus = 'консультация';
    }
  }

  const validOutcomes = ['запись', 'отказ', 'консультация', 'перезвон', 'отмена'];
  let outcome = validOutcomes.includes(rawOutcome) ? rawOutcome : 'консультация';
  if (bookingStatus === 'согласие') {
    outcome = 'запись';
  } else if (bookingStatus === 'отказ' && outcome !== 'отмена') {
    outcome = 'отказ';
  }

  let score: number | null = null;
  if (typeof parsed.operator_score === 'number' && !isNaN(parsed.operator_score)) {
    score = Math.max(1, Math.min(10, Math.round(parsed.operator_score)));
  }
  // Модель забыла оценку, но разговор реальный — ставим нейтральную 7, чтобы не было null.
  if (score === null) {
    score = 7;
  }

  // Извлечение конкретных ошибок оператора из json ответа модели
  let rawMistakes: string[] = [];
  if (Array.isArray(parsed.operator_mistakes)) {
    rawMistakes = parsed.operator_mistakes.map((m: any) => String(m).trim()).filter(Boolean);
  } else if (typeof parsed.operator_mistakes === 'string' && parsed.operator_mistakes.trim().length > 0) {
    rawMistakes = [parsed.operator_mistakes.trim()];
  }

  const rawSummary =
    parsed.transcript_summary || parsed.summary || 'Краткое содержание диалога с результатом обращения.';

  // Извлекаем суть обращения: услуга, дата, время, мастер
  const parsedKeyFacts = parsed.key_facts || {};
  const fullTranscript = originalTranscript || formattedTranscript || '';
  const extracted = extractEssenceDetails(fullTranscript, rawSummary, salon);

  const isMeaningful = (v: any) =>
    v &&
    typeof v === 'string' &&
    !v.toLowerCase().includes('не указан') &&
    !v.toLowerCase().includes('не выбран') &&
    !v.toLowerCase().includes('студио') &&
    v.trim().length > 0;

  const rawMaster = parsedKeyFacts.master || parsed.master;

  const service =
    (isMeaningful(parsedKeyFacts.service) ? parsedKeyFacts.service : null) ||
    (isMeaningful(parsed.service) ? parsed.service : null) ||
    extracted.service;

  const date =
    (isMeaningful(parsedKeyFacts.date) ? parsedKeyFacts.date : null) ||
    (isMeaningful(parsed.date) ? parsed.date : null) ||
    extracted.date;

  const rawTime =
    (isMeaningful(parsedKeyFacts.time) ? parsedKeyFacts.time : null) ||
    (isMeaningful(parsed.time) ? parsed.time : null) ||
    extracted.time;
  const time = rawTime
    ? rawTime.replace(
        /\b([012]?\d)\s+([0-5]\d|0\s+0)\b/gi,
        (_: any, h: string, m: string) =>
          `${h.padStart(2, '0')}:${m.replace(/\s+/g, '') === '0' || m.replace(/\s+/g, '') === '00' ? '00' : m}`
      )
    : null;

  const master =
    (isMasterNameValid(rawMaster) ? normalizeMasterName(rawMaster) : null) ||
    extracted.master;

  const comment =
    parsed.operator_comment && parsed.operator_comment.trim().length > 0
      ? parsed.operator_comment
      : `Администратор обработал обращение по регламенту салона «${salon}».`;
  const recommendations = parsed.recommendations || `Соблюдать стандарты сервиса салона «${salon}».`;

  const { formattedSummary, essence, structuredSummary, mistakes, advice } = formatSummaryWithEssence(
    rawSummary,
    fullTranscript,
    {
      service: service || null,
      date: date || null,
      time: time || null,
      master: master || null,
    },
    salon,
    score,
    rawMistakes,
    recommendations,
    comment
  );

  const finalMistakes = rawMistakes.length > 0 ? rawMistakes : (mistakes && mistakes.length > 0 ? mistakes : []);

  const modelStruct = parsed.structured_summary || {};
  const finalStructuredSummary: StructuredCallSummary = {
    call_purpose: modelStruct.call_purpose || structuredSummary.call_purpose,
    requested_service: modelStruct.requested_service || structuredSummary.requested_service,
    offered_master: isMasterNameValid(modelStruct.offered_master) ? normalizeMasterName(modelStruct.offered_master)! : structuredSummary.offered_master,
    offered_price: modelStruct.offered_price || structuredSummary.offered_price,
    offered_date_time: modelStruct.offered_date_time || structuredSummary.offered_date_time,
    booking_status_text: modelStruct.booking_status_text || structuredSummary.booking_status_text,
    unbooked_reason: modelStruct.unbooked_reason || structuredSummary.unbooked_reason,
    manager_next_steps: Array.isArray(modelStruct.manager_next_steps) && modelStruct.manager_next_steps.length > 0
      ? modelStruct.manager_next_steps
      : structuredSummary.manager_next_steps,
  };

  // Оценка звонка по 10 критериям
  const rawCriteria = Array.isArray(parsed.criteria_scores)
    ? parsed.criteria_scores
    : (Array.isArray(parsed.evaluation?.criteria) ? parsed.evaluation.criteria : []);

  const parsedEvalObj = rawCriteria.length >= 5 ? buildCallEvaluation(rawCriteria) : null;
  const evaluation: CallEvaluation = extractCallEvaluation(
    fullTranscript,
    formattedSummary,
    parsedEvalObj,
    score,
    finalMistakes,
    Array.isArray(advice) ? advice : [advice].filter(Boolean),
    salon
  );

  // Итоговый балл оператора синхронизируется со средним баллом по применимым критериям
  if (evaluation.overall_score !== null && !isNaN(evaluation.overall_score)) {
    score = Math.max(1, Math.min(10, Math.round(evaluation.overall_score)));
  }

  const result: AnalysisResult = {
    transcript_summary: formattedSummary,
    booking_status: bookingStatus,
    formatted_transcript: formattedTranscript,
    structured_summary: finalStructuredSummary,
    evaluation,
    criteria_scores: evaluation.criteria,
    key_facts: {
      is_dispute: Boolean(parsed.key_facts?.is_dispute),
      dispute_reason: parsed.key_facts?.dispute_reason || null,
      tone_client: parsed.key_facts?.tone_client || 'нейтральный',
      tone_manager: parsed.key_facts?.tone_manager || 'нейтральный',
      call_outcome: outcome,
      booking_status: bookingStatus,
      client_issue: parsed.key_facts?.client_issue || (essence.service ? `Запись на ${essence.service}` : `Обращение в салон «${salon}»`),
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master,
      call_purpose: finalStructuredSummary.call_purpose,
      requested_service: finalStructuredSummary.requested_service,
      offered_master: finalStructuredSummary.offered_master,
      offered_price: finalStructuredSummary.offered_price,
      offered_date_time: finalStructuredSummary.offered_date_time,
      is_booked_text: finalStructuredSummary.booking_status_text,
      unbooked_reason: finalStructuredSummary.unbooked_reason,
      manager_next_steps: finalStructuredSummary.manager_next_steps,
      structured_summary: finalStructuredSummary,
      evaluation,
      criteria_scores: evaluation.criteria,
    },
    operator_score: score,
    operator_mistakes: finalMistakes,
    operator_comment: comment,
    recommendations: advice && advice.length > 0 ? advice : recommendations,
  };

  // Программная проверка согласованности — только логируем расхождения.
  const check = validateResult(result);
  if (!check.valid) {
    console.warn(`[GigaChat] Обнаружены несоответствия в ответе модели: ${check.errors.join('; ')}`);
  }

  return result;
}


function generateLocalFallbackAnalysis(
  transcript: string,
  model: GigaChatModel,
  callDurationSeconds?: number,
  customSalonName?: string
): AnalysisResult {
  const salon = customSalonName || process.env.SALON_NAME || 'Fashion Look Studio';
  const clean = (transcript || '').trim();
  const lower = clean.toLowerCase();

  // 1. Жёсткий предохранитель: звонки менее 10 секунд
  if (callDurationSeconds !== undefined && callDurationSeconds < 10) {
    const failedEval = extractCallEvaluation('', '', null, null, [], [], salon);
    return {
      transcript_summary: `Разговор не состоялся: длительность вызова ${callDurationSeconds} сек (менее 10 секунд), диалог между оператором и клиентом отсутствует.`,
      booking_status: 'не применимо',
      formatted_transcript: clean || 'Разговор не состоялся (диалог отсутствует)',
      evaluation: failedEval,
      criteria_scores: failedEval.criteria,
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: 'Звонок менее 10 секунд / диалог отсутствует',
        service: null,
        date: null,
        time: null,
        master: null,
        evaluation: failedEval,
        criteria_scores: failedEval.criteria,
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: `Оценка не выставляется: разговор не состоялся (длительность ${callDurationSeconds} сек менее 10 секунд).`,
      recommendations: `Повторить попытку дозвона клиенту в рабочее время салона «${salon}».`,
    };
  }

  // 2. Пустой транскрипт или заглушка (ожидание STT)
  const isPlaceholderOrEmpty =
    !clean ||
    lower.includes('стенограмма ожидает') ||
    lower.includes('запись разговора и стенограмма отсутствуют') ||
    lower.includes('разговор не состоялся');

  if (isPlaceholderOrEmpty) {
    const durLabel = callDurationSeconds !== undefined ? ` (длительность ${callDurationSeconds} сек.)` : '';
    const failedEval = extractCallEvaluation('', '', null, null, [], [], salon);
    return {
      transcript_summary: `Разговор не состоялся: аудиозапись${durLabel} не содержит разборчивой речи (зафиксированы только гудки/тишина или сброс линии).`,
      booking_status: 'не применимо',
      formatted_transcript: clean || `Аудиозапись${durLabel} не содержит разборчивой речи.`,
      evaluation: failedEval,
      criteria_scores: failedEval.criteria,
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: 'Отсутствует разборчивая речь в аудиозаписи',
        service: null,
        date: null,
        time: null,
        master: null,
        evaluation: failedEval,
        criteria_scores: failedEval.criteria,
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: `Оценка не выставляется: аудиозапись${durLabel} не содержит разборчивого диалога оператора и клиента.`,
      recommendations: 'Проверить качество связи или повторить вызов.',
    };
  }

  // 3. Чистый автоответчик/голосовая почта — ТОЛЬКО если реального диалога нет
  const hasDialogue =
    (lower.includes('клиент:') && (lower.includes('менеджер:') || lower.includes('администратор:'))) ||
    clean.split('\n').filter(l => l.trim().length > 0).length >= 2;

  const isPureAuto =
    !hasDialogue &&
    (lower.includes('оставьте сообщение после сигнала') ||
      lower.includes('вас приветствует автоответчик') ||
      lower.includes('абонент временно недоступен') ||
      lower.includes('голосовая почта') ||
      lower.includes('автоинформатор'));

  if (isPureAuto) {
    const failedEval = extractCallEvaluation('', '', null, null, [], [], salon);
    return {
      transcript_summary: 'Разговор не состоялся: сработал автоответчик или голосовая почта. Запись не оформлена.',
      booking_status: 'не применимо',
      formatted_transcript: clean,
      evaluation: failedEval,
      criteria_scores: failedEval.criteria,
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: 'Звонок не состоялся / автоответчик',
        service: null,
        date: null,
        time: null,
        master: null,
        evaluation: failedEval,
        criteria_scores: failedEval.criteria,
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: 'Разговор не состоялся: зафиксирован автоответчик (оценка не выставляется).',
      recommendations: `Повторить звонок клиенту в рабочие часы салона «${salon}».`,
    };
  }

  // 4. Реальный разговор с речью (от 10 секунд и больше)
  const isDispute =
    lower.includes('отмен') || lower.includes('жалоб') || lower.includes('претензи') ||
    lower.includes('недоволен') || lower.includes('издеваетесь');
  const isDeclined =
    lower.includes('не будет в городе') || lower.includes('не смогу') || lower.includes('не получается') ||
    lower.includes('неудобно') || lower.includes('не подходит') || lower.includes('отказ');

  const isBooking =
    !isDeclined &&
    (lower.includes('записали') || lower.includes('записала') || lower.includes('записал') ||
      lower.includes('записываю') || lower.includes('записан') || lower.includes('записана') || lower.includes('записаны') ||
      lower.includes('запишите') || lower.includes('запись оформлена') || lower.includes('запись подтверждена') ||
      lower.includes('до встречи') || lower.includes('ждем вас') || lower.includes('ждём вас') ||
      lower.includes('ждем') || lower.includes('ждём') || lower.includes('жду вас') || lower.includes('будем ждать') ||
      lower.includes('договорились') || lower.includes('согласна') || lower.includes('согласен') ||
      lower.includes('буду к') || lower.includes('буду в') || lower.includes('приду в') || lower.includes('приду к') ||
      lower.includes('подходит время') || lower.includes('подходит этот день') || lower.includes('подтверждаю запись'));

  const outcome = isBooking ? 'запись' : (isDeclined ? 'отказ' : (isDispute ? 'перезвон' : 'консультация'));
  const bookingStatus = isBooking ? 'согласие' : (isDeclined ? 'отказ' : 'консультация');

  const cleanSnippet = clean.replace(/^(клиент:|менеджер:|администратор:)\s*/gim, '').trim().slice(0, 160);

  // Извлекаем суть обращения (услуга, дата, время, мастер)
  const essence = extractEssenceDetails(clean, undefined, salon);
  const masterLabel = essence.master ? ` к мастеру ${essence.master}` : '';
  const dateLabel = essence.date ? ` на ${essence.date}` : '';
  const timeLabel = essence.time ? ` в ${essence.time}` : '';

  let conclusionText = '';
  if (isBooking) {
    conclusionText = `Администратор согласовал запись${masterLabel}${dateLabel}${timeLabel}. Запись успешно подтверждена.`;
  } else if (isDeclined) {
    conclusionText = `Администратор предложил варианты визита${dateLabel}${timeLabel}, но клиент отказался из-за неудобного времени или отъезда.`;
  } else if (isDispute) {
    conclusionText = `Зафиксировано обращение с вопросом/претензией по обслуживанию. Достигнута договоренность о повторном контакте/перезвоне.`;
  } else {
    conclusionText = `Администратор вежливо проконсультировал клиента по регламенту салона «${salon}» («${cleanSnippet}»).`;
  }

  let score = hasDialogue ? (isDispute ? 7 : (isDeclined ? 6 : (isBooking ? 9 : 8))) : 7;

  // Формируем детальный список ошибок и рекомендаций для снижения оценки
  const mistakes: string[] = [];
  const recommendationsList: string[] = [];

  if (isDeclined) {
    mistakes.push('Администратор предложил только один временной слот без альтернативных вариантов');
    mistakes.push('При отказе клиента не предложены другие свободные дни или лист ожидания салона');
    mistakes.push('Пассивное завершение звонка без попытки удержать контакт клиента');
    recommendationsList.push('Всегда предлагать вилку времени минимум из двух слотов («Суббота 12:00 или воскресенье 16:00»)');
    recommendationsList.push('При отказе предлагать альтернативные даты или внесение в лист ожидания');
    recommendationsList.push('Удерживать инициативу в диалоге до конца, не отпуская клиента без договоренности');
  } else if (isDispute) {
    mistakes.push('Недостаточно оперативное переключение в режим активного слушания при претензии');
    mistakes.push('Не зафиксированы точные сроки обратной связи руководства по разрешению проблемы');
    recommendationsList.push('Следовать протоколу урегулирования претензий: принести извинения от лица салона и зафиксировать срок решения');
    recommendationsList.push('Согласовать время контрольного звонка управляющего');
  } else if (isBooking) {
    mistakes.push('Не предложены сопутствующие процедуры (дизайн, спа-уход, снятие покрытия)');
    mistakes.push('Не проговорено напоминание о подтверждении брони накануне визита');
    recommendationsList.push('Осуществлять ненавязчивую допродажу сопутствующих услуг к основной процедуре');
    recommendationsList.push('Информировать клиента об отправке смс-напоминания накануне визита');
  } else {
    mistakes.push('Не выявлена потребность звонящего в записи на услуги салона');
    mistakes.push('Сухой справочный ответ без встречной инициативы по подбору удобного слота');
    recommendationsList.push('После ответа на вопрос о ценах или графике сразу предлагать свободные окна для записи');
    recommendationsList.push('Спрашивать имя клиента для занесения в базу CRM');
  }

  const comment = hasDialogue
    ? (isDispute
        ? 'Администратор принял претензию/отмену, соблюдая вежливый тон, однако не зафиксировал сроки обратной связи.'
        : isDeclined
        ? 'Снижение оценки вызвано пассивной позицией при отказе клиента и отсутствием предложений альтернативных дат.'
        : isBooking
        ? `Администратор успешно оформил запись, но упустил возможность предложить сопутствующие услуги салона «${salon}».`
        : `Администратор предоставил базовую консультацию по регламенту «${salon}», не проявив активности в оформлении записи.`)
    : 'Краткий обмен репликами. Полноценная оценка регламента не выставляется.';

  const { formattedSummary, structuredSummary } = formatSummaryWithEssence(
    conclusionText,
    clean,
    essence,
    salon,
    score,
    mistakes,
    recommendationsList,
    comment
  );

  const evaluation: CallEvaluation = extractCallEvaluation(
    clean,
    formattedSummary,
    null,
    score,
    mistakes,
    recommendationsList,
    salon
  );

  if (evaluation.overall_score !== null && !isNaN(evaluation.overall_score)) {
    score = Math.max(1, Math.min(10, Math.round(evaluation.overall_score)));
  }

  return {
    transcript_summary: formattedSummary,
    booking_status: bookingStatus,
    formatted_transcript: transcript,
    structured_summary: structuredSummary,
    evaluation,
    criteria_scores: evaluation.criteria,
    key_facts: {
      is_dispute: isDispute,
      dispute_reason: isDispute ? 'Претензия или отмена записи' : null,
      tone_client: isDispute ? 'негативный' : 'нейтральный',
      tone_manager: 'позитивный',
      call_outcome: outcome,
      booking_status: bookingStatus,
      client_issue: isDispute ? 'Вопрос по обслуживанию' : (essence.service ? `Запись на ${essence.service}` : 'Консультация / обращение в салон'),
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master,
      call_purpose: structuredSummary.call_purpose,
      requested_service: structuredSummary.requested_service,
      offered_master: structuredSummary.offered_master,
      offered_price: structuredSummary.offered_price,
      offered_date_time: structuredSummary.offered_date_time,
      is_booked_text: structuredSummary.booking_status_text,
      unbooked_reason: structuredSummary.unbooked_reason,
      manager_next_steps: structuredSummary.manager_next_steps,
      structured_summary: structuredSummary,
      evaluation,
      criteria_scores: evaluation.criteria,
    },
    operator_score: score,
    operator_mistakes: mistakes,
    operator_comment: comment,
    recommendations: recommendationsList,
  };
}

/**
 * Локальный генератор следующих шагов (Next Steps) для администратора
 */
export function generateLocalNextSteps(call: CallRecord, customSalonName?: string): string[] {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();
  const rawStatus = (call.booking_status || call.key_facts?.booking_status || '').toLowerCase().trim();
  const outcome = (call.key_facts?.call_outcome || '').toLowerCase().trim();
  const isBooking = rawStatus === 'согласие' || rawStatus.includes('соглас') || outcome === 'запись';
  const isDeclined = rawStatus === 'отказ' || rawStatus.includes('отказ') || outcome === 'отказ';
  const isDispute = Boolean(call.key_facts?.is_dispute);

  const kf: Partial<KeyFacts> = call.key_facts || {};
  const service = kf.service || 'услугу';
  const date = kf.date || null;
  const time = kf.time || null;
  const master = kf.master || null;
  const clientName = call.client_name ? `клиента ${call.client_name}` : 'клиента';

  const steps: string[] = [];

  if (isBooking) {
    const bookingDetails = [
      service !== 'услугу' ? `услуга: «${service}»` : null,
      date ? `дата: ${date}` : null,
      time ? `время: ${time}` : null,
      master ? `мастер: ${master}` : null,
    ].filter(Boolean).join(', ');

    steps.push(`Внести подтвержденную запись ${clientName} в CRM Yclients (${bookingDetails || 'согласованные слоты'}).`);
    steps.push(`Отправить ${clientName} подтверждение бронирования и адрес студии в WhatsApp/SMS.`);
    if (master) {
      steps.push(`Проверить график мастера ${master} и подготовить рабочее место/расходные материалы.`);
    } else {
      steps.push(`Назначить квалифицированного специалиста на процедуру «${service}» в расписании салона «${salon}».`);
    }
    steps.push(`Установить автоматическое напоминание за 24 часа до визита для подтверждения явки.`);
  } else if (isDispute) {
    steps.push(`Зафиксировать обращение в журнале претензий и передать управляющему салона «${salon}».`);
    steps.push(`Поднять историю предыдущих визитов ${clientName} и подготовить фактуру (${kf.dispute_reason || 'вопрос по качеству сервиса'}).`);
    steps.push(`Согласовать с управляющим вариант сервисной компенсации или скидки для сохранения лояльности.`);
    steps.push(`Связаться с клиентом в течение 2 часов для предоставления персонального решения.`);
  } else if (isDeclined) {
    steps.push(`Отметить в CRM причину отказа клиента (не подошло время / отъезд / высокая стоимость).`);
    steps.push(`Добавить контакт ${clientName} в базу потенциальных клиентов с тегом «Интересовался: ${service}».`);
    steps.push(`Запланировать отправку персонального спецпредложения через 10-14 дней от салона «${salon}».`);
  } else {
    // Консультация / справочное обращение
    steps.push(`Создать карточку ${clientName} в CRM Yclients с пометкой интересующей услуги («${service}»).`);
    steps.push(`Направить клиенту в мессенджер прайс-лист, фото портфолио работ и ссылку на онлайн-запись в салон «${salon}».`);
    if (master) {
      steps.push(`Уточнить ближайшие свободные окна у мастера ${master} и предложить клиенту.`);
    }
    steps.push(`Поставить напоминание администратору: контрольный звонок через 48 часов, если запись не будет оформлена.`);
  }

  // Отработка обещаний администратора
  if (Array.isArray(kf.promises) && kf.promises.length > 0) {
    kf.promises.forEach(p => {
      if (p && typeof p === 'string' && p.trim()) {
        steps.push(`Выполнить зафиксированное обещание: ${p.trim()}`);
      }
    });
  }

  return steps;
}

/**
 * Интеллектуальная генерация Next Steps (следующих шагов) по итогам звонка для администратора
 */
export async function generateNextStepsWithAI(
  call: CallRecord,
  customSalonName?: string
): Promise<{ steps: string[]; items: NextStepItem[] }> {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();

  // Если GigaChat не настроен или транскрипт слишком короткий — используем локальный генератор
  if (!isGigaChatConfigured() || !call.transcript || call.transcript.length < 15) {
    const fallbackSteps = generateLocalNextSteps(call, salon);
    const items: NextStepItem[] = fallbackSteps.map((text, idx) => ({
      id: `step-${Date.now()}-${idx + 1}`,
      text,
      completed: false,
    }));
    return { steps: fallbackSteps, items };
  }

  const prompt = `Ты — старший управляющий и координатор клиентского сервиса салона красоты «${salon}».
Твоя задача — составить четкий, практичный список задач (Next Steps / Следующие шаги) для дежурного администратора салона по итогам телефонного разговора.

ДАННЫЕ ЗВОНКА:
- Статус записи: ${call.booking_status || call.key_facts?.booking_status || 'консультация'}
- Суть обращения: ${call.key_facts?.client_issue || 'консультация'}
- Услуга: ${call.key_facts?.service || 'не указана'}
- Желаемая дата: ${call.key_facts?.date || 'не указана'}
- Желаемое время: ${call.key_facts?.time || 'не указано'}
- Мастер: ${call.key_facts?.master || 'не указан'}
- Обещания клиенту: ${(call.key_facts?.promises || []).join('; ') || 'нет'}
- Конфликт/спор: ${call.key_facts?.is_dispute ? 'ДА: ' + (call.key_facts?.dispute_reason || '') : 'НЕТ'}
- Резюме диалога: ${call.summary || 'нет'}

СТЕНОГРАММА ДИАЛОГА:
${call.transcript}

ТРЕБОВАНИЯ К NEXT STEPS:
1. Составь от 3 до 5 конкретных шагов для администратора салона.
2. Каждый шаг должен начинаться с глагола в неопределенной форме (Внести, Отправить, Позвонить, Проверить, Подготовить, Согласовать).
3. Шаги должны учитывать специфику работы салона красоты (CRM Yclients, мессенджеры WhatsApp/Telegram, напоминания, расходники, график мастеров).
4. Обязательно учти договоренности и обещания, зафиксированные в диалоге.
5. Верни результат СТРОГО в формате JSON-массива строк, без пояснительного текста до и после:
["действие 1", "действие 2", "действие 3"]`;

  try {
    const token = await getGigaChatToken();
    const model = (call.model_used && call.model_used.startsWith('GigaChat') ? call.model_used : 'GigaChat:Lite') as GigaChatModel;

    const response = await gigaChatQueue.enqueue(async () => {
      const res = await axios.post(
        'https://gigachat.devices.sberbank.ru/api/v1/chat/completions',
        {
          model: model,
          messages: [
            { role: 'system', content: `Ты — старший управляющий салона «${salon}». Отвечай ТОЛЬКО валидным JSON-массивом строк.` },
            { role: 'user', content: prompt }
          ],
          temperature: 0.2,
          max_tokens: 1000
        },
        {
          headers: {
            'Content-Type': 'application/json',
            Authorization: `Bearer ${token}`
          },
          httpsAgent,
          timeout: 25000
        }
      );
      return res.data;
    }, 'Генерация Next Steps');

    const content = response.choices?.[0]?.message?.content || '';
    const cleanJson = content.replace(/```(?:json)?/gi, '').replace(/```/g, '').trim();
    const parsed = JSON.parse(cleanJson);

    if (Array.isArray(parsed) && parsed.length > 0) {
      const steps: string[] = parsed
        .map((s: any) => String(s).trim())
        .filter((s: string) => s.length > 0);

      const items: NextStepItem[] = steps.map((text, idx) => ({
        id: `step-${Date.now()}-${idx + 1}`,
        text,
        completed: false,
      }));

      return { steps, items };
    }
  } catch (err: any) {
    console.warn(`[GigaChat NextSteps] Сбой онлайн-генерации: ${err.message}. Переход на резервный генератор.`);
  }

  // Резервный расчет
  const fallbackSteps = generateLocalNextSteps(call, salon);
  const items: NextStepItem[] = fallbackSteps.map((text, idx) => ({
    id: `step-${Date.now()}-${idx + 1}`,
    text,
    completed: false,
  }));
  return { steps: fallbackSteps, items };
}

