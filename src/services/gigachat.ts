/**
 * Формирует фактологический пересказ (2–4 предложения для коротких звонков, 5–7 для длинных многоэтапных)
 * и вывод строго по полному содержанию диалога, без обрезанных цитат и шаблонных фантазий.
 */
export function buildContextGroundedSummary(
  ctx: CallContextClassification,
  essence: EssenceDetails,
  salon: string
): { retelling: string; conclusion: string } {
  const { managerText, clientText, fullText } = splitSpeakerLines(ctx.cleanTranscript);
  const transcript = ctx.cleanTranscript || '';

  const dateLabel = essence.date ? ` на ${essence.date}` : '';
  const timeLabel = essence.time ? ` в ${essence.time}` : '';
  const masterLabel = essence.master ? ` к мастеру ${essence.master}` : '';

  const priceMatch = transcript.match(/(?:по\s+стоимости|стоимост[ьи]|стоит|цена)\s*(?:от\s+)?(\d{3,5})\s*(?:руб|р(?![а-яё])|₽)/iu);
  const priceLabel = priceMatch ? `${Number(priceMatch[1]).toLocaleString('ru-RU')} ₽` : null;
  const prepayMatch = transcript.match(/предоплат[а-яё]*[^.\n]{0,40}?(?:50%|\d+%)[^.\n]{0,40}?(\d{3,5})?/iu);
  const hasOzonPrepay = /озон\s*банк/iu.test(transcript);

  if (ctx.category === 'non_client') {
    const topicNote = ctx.nonClientTopic || 'организационный / партнёрский вопрос';
    const hasWhatsapp = /ватсап|whatsapp/iu.test(transcript);
    const hasName = transcript.match(/мо[её]\s+имя\s+([А-ЯЁ][а-яё]+)/iu);
    const callerLabel = hasName ? `Звонящий (${hasName[1]})` : 'Звонящий';
    return {
      retelling: `Входящий звонок носил нецелевой (организационно-партнёрский) характер и не был связан с записью на услуги салона. ${callerLabel} обратился по вопросу: ${topicNote}. Администратор вежливо выслушала собеседника${hasWhatsapp ? ' и подтвердила, что сообщение в мессенджере будет обязательно прочитано' : ''}, поблагодарила за звонок и корректно завершила диалог.`,
      conclusion: `Нецелевой / партнёрский звонок (${topicNote}). Запись на услуги салона не требовалась; администратор вежливо принял информацию к сведению.`
    };
  }

  if (ctx.category === 'late_or_visit_update') {
    const delayStr = ctx.lateMinutes ? ` примерно на ${ctx.lateMinutes}` : '';
    const targetTimeStr = essence.time ? ` (ориентировочно к ${essence.time})` : '';
    return {
      retelling: `Клиент позвонил в салон «${salon}», чтобы заранее предупредить об опоздании на свой предстоящий визит${delayStr}${targetTimeStr}. Администратор доброжелательно отреагировала и подтвердила, что в салоне гостя обязательно дождутся. Собеседник поблагодарил сотрудника, после чего стороны вежливо завершили разговор.`,
      conclusion: `Действующая запись клиента сохраняется: гость предупредил об опоздании${delayStr}, администратор подтвердил ожидание.`
    };
  }

  if (ctx.category === 'refusal_unavailable_service') {
    const reqService = essence.service ? `услуга «${essence.service}»` : 'интересующая его процедура';
    const hasConsultOffer = /консультац/i.test(transcript);
    const hasAltChem = /химическ[а-яё]*\s+завивк/iu.test(transcript);
    return {
      retelling: `Клиент позвонил в салон «${salon}» с вопросом о возможности выполнения услуги «${essence.service || 'запрошенной процедуры'}». Администратор пояснила, что данная техника в салоне не представлена, ${hasAltChem ? 'рассказала о доступной химической завивке' : 'предложила альтернативный вариант'}${hasConsultOffer ? ' и предложила записаться на предварительную консультацию к мастеру' : ''}. Гость уточнил, что ищет именно ${reqService}, и вежливо отказался от предложенной альтернативы.`,
      conclusion: `Запись не состоялась: запрашиваемая услуга в салоне отсутствует, а от предложенной альтернативы${hasConsultOffer ? ' и консультации' : ''} клиент отказался.`
    };
  }

  if (ctx.category === 'dispute') {
    return {
      retelling: `Клиент обратился в салон «${salon}» со спорным вопросом или замечанием по качеству обслуживания. Администратор выслушал обращение и дал обратную связь в рамках регламента салона. Стороны обсудили возможные пути решения и зафиксировали дальнейший порядок урегулирования вопроса.`,
      conclusion: `Зафиксировано обращение с претензией или вопросом по качеству сервиса. Требуется контроль со стороны управляющего.`
    };
  }

  if (ctx.category === 'confirmed_booking') {
    const sentences: string[] = [];
    const introNameMatch = transcript.match(/меня\s+зовут\s+([А-ЯЁ][а-яё]+)/iu);
    const hasPastLookup = /(?:напомнить|что\s+за\s+мастер|была\s+\d|укладывал[аи])/iu.test(transcript);
    const hasCompanionHandoff = /(?:передам[^.\n]{0,20}трубк|трубк[^.\n]{0,20}передам|спрошу\s+подруг)/iu.test(transcript);
    const pastDateMatch = transcript.match(/(\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря))\s+я\s+у\s+вас/iu);

    // 1. Начало разговора и исходный запрос
    if (hasPastLookup) {
      const callerPrefix = introNameMatch ? `Клиентка ${introNameMatch[1]}` : 'Клиентка';
      const pastDateNote = pastDateMatch ? ` (${pastDateMatch[1]})` : '';
      sentences.push(
        `${callerPrefix} позвонила в салон «${salon}», чтобы уточнить имя мастера, который делал укладку ей и её подруге во время прошлого визита${pastDateNote}.`
      );
    } else {
      sentences.push(
        essence.service
          ? `Клиент обратился в салон «${salon}» по вопросу записи на услугу «${essence.service}»${masterLabel}.`
          : `Клиент позвонил в салон «${salon}» для оформления или подтверждения записи.`
      );
    }

    // 2. Справка по мастерам / услугам (если звучала)
    const hasSpecializationInfo = /специализирует/iu.test(transcript);
    if (hasPastLookup || hasSpecializationInfo) {
      if (essence.master && hasSpecializationInfo) {
        sentences.push(
          `Администратор проверила историю посещений, назвала работавших специалистов и уточнила, что мастер ${essence.master} специализируется на стрижках и окрашиваниях.`
        );
      } else if (essence.master) {
        sentences.push(
          `Администратор проверила информацию в системе и подтвердила, что мастер ${essence.master} продолжает работать в салоне.`
        );
      }
    }

    // 3. Передача трубки спутнику (если была)
    if (hasCompanionHandoff) {
      const companionNameMatch = transcript.match(/([А-ЯЁ][а-яё]+),?\s+верно,?\s*да\??/iu);
      const companionStr = companionNameMatch ? ` по имени ${companionNameMatch[1]}` : '';
      sentences.push(
        `Узнав о возможности онлайн-записи или подбора окошка через администратора, звонящая передала трубку подруге${companionStr} для выбора времени и оформления визита.`
      );
    }

    // 4. Подбор дат, занятость и предложенные окна времени
    const windowMatch = transcript.match(/с\s+(\d{1,2}[:.\s]\d{2})\s+до\s+(\d{1,2}[:.\s]\d{2})/iu);
    const hasWeekendUnavailable = /не\s+работает/iu.test(transcript);
    if (hasWeekendUnavailable || windowMatch || /предложить/iu.test(managerText || transcript)) {
      const normWindow = windowMatch
        ? ` (вечернее окно с ${windowMatch[1].replace(/\s+/g, ':')} до ${windowMatch[2].replace(/\s+/g, ':')})`
        : '';
      if (hasWeekendUnavailable) {
        sentences.push(
          `Гостья уточнила наличие мест на выходные или начало недели, на что администратор сообщила о выходных днях мастера и предложила ближайшую свободную дату${dateLabel}${normWindow}.`
        );
      } else if (essence.date || windowMatch) {
        sentences.push(
          `Администратор проверила расписание и предложила доступные варианты времени визита${dateLabel}${normWindow}.`
        );
      }
    }

    // 5. Подтверждение услуги, стоимости и контактов
    const hasPhoneCollected = /(?:продиктую|номер телефона|960|9\d{2})/iu.test(transcript);
    if (priceLabel || prepayMatch || hasPhoneCollected) {
      const details: string[] = [];
      if (essence.service) details.push(`услугу «${essence.service}»`);
      if (priceLabel) details.push(`стоимость ${priceLabel}`);
      if (prepayMatch || hasOzonPrepay) details.push('условие внесения 50% предоплаты для бронирования');
      if (hasPhoneCollected) details.push('контактный номер телефона для фиксации записи');
      if (details.length > 0) {
        const joined =
          details.length === 1
            ? details[0]
            : `${details.slice(0, -1).join(', ')} и ${details[details.length - 1]}`;
        sentences.push(`Стороны подтвердили ${joined}.`);
      }
    }

    // 6. Финальное подтверждение записи
    sentences.push(
      `В результате запись${essence.service ? ` на услугу «${essence.service}»` : ''}${masterLabel}${dateLabel}${timeLabel} была успешно согласована и подтверждена.`
    );

    return {
      retelling: sentences.join(' '),
      conclusion: `Администратор согласовал запись${essence.service ? ` на услугу «${essence.service}»` : ''}${masterLabel}${dateLabel}${timeLabel}${priceLabel ? ` (стоимость — ${priceLabel})` : ''}. Запись успешно подтверждена.`
    };
  }

  if (ctx.category === 'declined') {
    const s1 = essence.service
      ? `Клиент позвонил в салон «${salon}» по вопросу записи на услугу «${essence.service}»${masterLabel}.`
      : `Клиент обратился в салон «${salon}» по поводу подбора визита.`;
    const s2 = `Администратор проверил расписание и озвучил доступные условия${dateLabel}${timeLabel}, однако предложенный вариант клиенту не подошёл.`;
    const s3 = `Стороны вежливо завершили разговор без оформления записи.`;
    return {
      retelling: `${s1} ${s2} ${s3}`,
      conclusion: `Запись не состоялась: клиент отказался от предложенного варианта${dateLabel}${timeLabel}.`
    };
  }

  if (ctx.category === 'reschedule_or_cancel') {
    return {
      retelling: `Клиент позвонил в салон «${salon}» для уточнения или корректировки существующей записи${dateLabel}${timeLabel}${masterLabel}. Администратор проверил расписание, уточнил занятость более ранних или смежных слотов и проинформировал гостя по доступным условиям. По итогам диалога стороны зафиксировали актуальный статус бронирования.`,
      conclusion: `Проведена проверка и актуализация действующей записи${masterLabel}${dateLabel}${timeLabel}.`
    };
  }

  // Консультация / справочное обращение без сырых обрывков текста
  const consultTopic = essence.service ? ` по услуге «${essence.service}»` : '';
  const hasScheduleQ = /до\s+скольки|работаете|график/iu.test(clientText || transcript);
  return {
    retelling: `Клиент обратился в салон «${salon}» за справочной информацией${consultTopic}${hasScheduleQ ? ' (режим работы салона)' : ''}. Администратор предоставил необходимые пояснения по заданному вопросу. Запись на конкретную дату и время в ходе этого разговора не оформлялась.`,
    conclusion: `Проведена справочная консультация по запросу клиента без фиксации записи на визит.`
  };
}

/**
 * Нормализует резюме так, чтобы оно ВСЕГДА содержало 4 четких блока:
 * 1) Краткая суть обращения (услуга, дата, время, мастер);
 * 2) Краткий пересказ разговора (СТРОГО 2–4 предложения);
 * 3) Вывод (итог диалога, предложения администратора и результат);
 * 4) Разбор работы менеджера с оценкой, конкретными ошибками/недочетами и практическими советами по оптимизации.
 * А также возвращает структурированное резюме из 8 параметров.
 */
export function formatSummaryWithEssence(
  rawSummary: string,
  transcript: string,
  extractedDetails?: EssenceDetails,
  customSalonName?: string,
  operatorScore?: number | null,
  operatorMistakes?: string[] | string | null,
  recommendations?: string[] | string | null,
  operatorComment?: string | null,
  callEvaluation?: CallEvaluation | null,
  callTimestamp?: string
): {
  formattedSummary: string;
  essence: EssenceDetails;
  structuredSummary: StructuredCallSummary;
  retelling?: string;
  conclusion?: string;
  managerEvaluation?: string;
  mistakes?: string[];
  advice?: string[];
  score?: number | null;
} {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();

  const ctx = classifyCallContext(transcript, rawSummary);
  const cleanTranscript = ctx.cleanTranscript;

  // Звонок не состоялся
  if (ctx.category === 'not_happened') {
    const structuredSummary = extractStructuredCallSummary(transcript, rawSummary, undefined, salon, 'не применимо');
    return {
      formattedSummary: rawSummary,
      essence: { service: null, date: null, time: null, master: null },
      structuredSummary,
      retelling: '',
      conclusion: rawSummary,
      managerEvaluation: '',
      mistakes: [],
      advice: [],
      score: null,
    };
  }

  // Всегда запускаем надежный парсер, если какое-либо поле в переданных деталях отсутствует или недостоверно
  const fallbackEssence = extractEssenceDetails(cleanTranscript, rawSummary, salon);
  const isMeaningful = (v?: string | null) =>
    v &&
    typeof v === 'string' &&
    !v.toLowerCase().includes('не указан') &&
    !v.toLowerCase().includes('не выбран') &&
    !v.toLowerCase().includes('студио') &&
    v.trim().length > 0;

  const hasTimeCorrectionInTranscript = Boolean(
    fallbackEssence.time && cleanTranscript && /(?:убираю|отмените|отменить|оставляю|оставьте)/iu.test(cleanTranscript)
  );
  const hasExplicitSingleBookingOverride = Boolean(
    fallbackEssence.service && /(?:необходимо|нужно)\s+будет\s+только\s+[а-яё]+/iu.test(cleanTranscript)
  );
  const hasPastVsConfirmedDateMismatch = Boolean(
    fallbackEssence.date &&
    extractedDetails?.date &&
    extractedDetails.date.toLowerCase() !== fallbackEssence.date.toLowerCase() &&
    ctx.isConfirmedBooking
  );

  const essence: EssenceDetails = {
    service:
      hasExplicitSingleBookingOverride && fallbackEssence.service
        ? fallbackEssence.service
        : isMeaningful(extractedDetails?.service)
        ? extractedDetails!.service
        : fallbackEssence.service,
    date:
      hasPastVsConfirmedDateMismatch && fallbackEssence.date
        ? fallbackEssence.date
        : isMeaningful(extractedDetails?.date)
        ? extractedDetails!.date
        : fallbackEssence.date,
    time:
      (hasTimeCorrectionInTranscript || hasPastVsConfirmedDateMismatch) && fallbackEssence.time
        ? fallbackEssence.time
        : isMeaningful(extractedDetails?.time)
        ? extractedDetails!.time
        : fallbackEssence.time,
    master: isMasterNameValid(extractedDetails?.master)
      ? normalizeMasterName(extractedDetails!.master!)
      : fallbackEssence.master,
  };

  const serviceStr = ctx.isNonClient
    ? 'не применимо (организационный звонок)'
    : ctx.isLateWarning
    ? (essence.service || 'предупреждение об опоздании')
    : (essence.service || 'не указана');
  const dateStr = essence.date || 'не указана';
  const timeStr = essence.time || 'не указано';
  const masterStr = essence.master || 'не выбран';
  const essencePrefix = `Суть обращения: услуга — ${serviceStr}, дата — ${dateStr}, время — ${timeStr}, мастер — ${masterStr}.`;

  // 1. Попытка обнаружить блок разбора работы менеджера в исходном тексте
  const managerReviewMatch = rawSummary.match(
    /(?:разбор работы менеджера(?:\s*\([^)]*\))?|оценка и разбор работы менеджера|разбор работы оператора)\s*:\s*([\s\S]*)$/i
  );
  let rawManagerSection = managerReviewMatch ? managerReviewMatch[1].trim() : '';

  // Текст без блока разбора работы менеджера для чистого парсинга пересказа и вывода
  const summaryWithoutManager = rawSummary
    .replace(/(?:разбор работы менеджера(?:\s*\([^)]*\))?|оценка и разбор работы менеджера|разбор работы оператора)\s*:[\s\S]*$/i, '')
    .trim();

  // 2. Попытка извлечь существующие блоки из summaryWithoutManager
  const retellingMatch = summaryWithoutManager.match(
    /(?:пересказ диалога|краткий пересказ(?: разговора)?|пересказ разговора)\s*:\s*([\s\S]*?)(?=(?:вывод\s*:|$))/i
  );
  const conclusionMatch = summaryWithoutManager.match(/вывод\s*:\s*([\s\S]*)$/i);

  let retellingText = retellingMatch ? retellingMatch[1].trim() : '';
  let conclusionText = conclusionMatch ? conclusionMatch[1].trim() : '';

  // Очистка от ошибочного «мастеру Студио», «Меня Вот», «Записались»
  const badMasterRegex =
    /(?:к\s+мастеру\s+(?:Меня\s+Вот|Записались|Студио|Будете)|мастеру\s+(?:Меня\s+Вот|Записались|Студио|Будете)|Меня\s+Вот|к\s+мастеру\s+Студио)/gi;
  if (retellingText) {
    retellingText = retellingText.replace(badMasterRegex, essence.master ? `к мастеру ${essence.master}` : 'в салон');
  }
  if (conclusionText) {
    conclusionText = conclusionText.replace(badMasterRegex, essence.master ? `к мастеру ${essence.master}` : 'в салон');
  }

  // Если модель вернула единый текст без явных блоков пересказа и вывода
  if (!retellingText && !conclusionText) {
    const cleanRaw = summaryWithoutManager
      .replace(/^суть обращения:[^.]*\.?/i, '')
      .trim();

    if (cleanRaw.length > 0) {
      const sentences = cleanRaw.split(/(?<=[.!?])\s+/).filter(s => s.trim().length > 0);
      if (sentences.length >= 3) {
        conclusionText = sentences[sentences.length - 1].trim();
        retellingText = sentences.slice(0, sentences.length - 1).join(' ').trim();
      } else {
        conclusionText = cleanRaw;
      }
    }
  } else if (!retellingText && conclusionText) {
    const preConclusion = summaryWithoutManager
      .replace(/^суть обращения:[^.]*\.?/i, '')
      .replace(/вывод\s*:[\s\S]*$/i, '')
      .trim();
    if (preConclusion.length > 20) {
      retellingText = preConclusion;
    }
  }

  // Определяем, нужно ли пересобрать пересказ/вывод строго по стенограмме:
  // срабатывает при пустых полях, обрывках цитат («...»), старых шаблонах или при противоречии фактическому исходу звонка
  const isLegacyCannedRetelling = /Клиент обратился в салон красоты по вопросам обслуживания и записи\.\s*Администратор предоставил подробную консультацию по графику/i.test(retellingText);
  const isTruncatedSnippetRetelling =
    /«[^»]{60,}»/.test(retellingText) ||
    /\(\s*«[^»]{25,}»\s*\)/.test(retellingText);
  const isContradictoryBookingConclusion =
    !ctx.isConfirmedBooking &&
    !ctx.isRescheduleOrCheck &&
    /администратор согласовал запись|запись успешно подтверждена/i.test(`${retellingText} ${conclusionText}`);
  const isMissedConfirmedBooking =
    ctx.isConfirmedBooking &&
    /не оформлял|не состоял|без фиксации записи|справочн/i.test(`${retellingText} ${conclusionText}`);

  const grounded = buildContextGroundedSummary(ctx, essence, salon);

  if (
    !retellingText ||
    retellingText.includes('к мастеру Студио') ||
    /свободное время\s*\./.test(retellingText) ||
    isLegacyCannedRetelling ||
    isTruncatedSnippetRetelling ||
    isContradictoryBookingConclusion ||
    isMissedConfirmedBooking
  ) {
    retellingText = grounded.retelling;
  }

  if (
    !conclusionText ||
    conclusionText.includes('к мастеру Студио') ||
    isLegacyCannedRetelling ||
    isTruncatedSnippetRetelling ||
    isContradictoryBookingConclusion ||
    isMissedConfirmedBooking
  ) {
    conclusionText = grounded.conclusion;
  }

  // Очистка от возможных дублей заголовков
  retellingText = retellingText.replace(/^(?:пересказ диалога|краткий пересказ(?: разговора)?):\s*/i, '').trim();
  conclusionText = conclusionText.replace(/^вывод:\s*/i, '').trim();

  // 3. Формирование и извлечение 4-го блока: Разбор работы менеджера (оценка, ошибки, советы)
  let resolvedScore: number | null = null;
  if (typeof operatorScore === 'number' && !isNaN(operatorScore)) {
    resolvedScore = operatorScore;
  } else {
    const scoreInSummaryMatch = rawSummary.match(/оценка\s*(\d{1,2})\s*\/\s*10/i);
    if (scoreInSummaryMatch) {
      resolvedScore = parseInt(scoreInSummaryMatch[1], 10);
    } else {
      resolvedScore = 8;
    }
  }

  // Извлечение ошибок
  let mistakesList: string[] = [];
  if (Array.isArray(operatorMistakes) && operatorMistakes.length > 0) {
    mistakesList = operatorMistakes.map(m => String(m).trim()).filter(Boolean);
  } else if (typeof operatorMistakes === 'string' && operatorMistakes.trim().length > 0) {
    mistakesList = [operatorMistakes.trim()];
  } else if (rawManagerSection) {
    const mistakesSubMatch = rawManagerSection.match(
      /(?:ошибки и недочеты|ошибки|недочеты)\s*:\s*([\s\S]*?)(?=(?:советы по оптимизации|советы|рекомендации)\s*:|$)/i
    );
    if (mistakesSubMatch) {
      const rawText = mistakesSubMatch[1].trim();
      const splitItems = rawText
        .split(/(?:^|\n)\s*[-•*0-9.)]+\s*/g)
        .map(s => s.trim().replace(/^;\s*/, ''))
        .filter(s => s.length > 3);
      if (splitItems.length > 0) {
        mistakesList = splitItems;
      } else if (rawText) {
        mistakesList = [rawText];
      }
    }
  }

  // Извлечение советов по оптимизации
  let adviceList: string[] = [];
  if (Array.isArray(recommendations) && recommendations.length > 0) {
    adviceList = recommendations.map(r => String(r).trim()).filter(Boolean);
  } else if (typeof recommendations === 'string' && recommendations.trim().length > 0) {
    adviceList = [recommendations.trim()];
  } else if (rawManagerSection) {
    const adviceSubMatch = rawManagerSection.match(
      /(?:советы по оптимизации|советы|рекомендации)\s*:\s*([\s\S]*)$/i
    );
    if (adviceSubMatch) {
      const rawText = adviceSubMatch[1].trim();
      const splitItems = rawText
        .split(/(?:^|\n)\s*[-•*0-9.)]+\s*/g)
        .map(s => s.trim().replace(/^;\s*/, ''))
        .filter(s => s.length > 3);
      if (splitItems.length > 0) {
        adviceList = splitItems;
      } else if (rawText) {
        adviceList = [rawText];
      }
    }
  }

  // 4. Синхронизация ошибок и советов с оценкой по 10 критериям
  const evalForHarmonization = callEvaluation || extractCallEvaluation(
    transcript,
    conclusionText || rawSummary,
    null,
    resolvedScore,
    mistakesList,
    adviceList,
    salon
  );

  if (evalForHarmonization.overall_score !== null && !isNaN(evalForHarmonization.overall_score)) {
    resolvedScore = evalForHarmonization.overall_score;
  }

  const harmonized = harmonizeMistakesAndEvaluation(
    mistakesList,
    adviceList,
    evalForHarmonization,
    transcript,
    callTimestamp,
    essence.date
  );
  mistakesList = harmonized.mistakes;
  adviceList = harmonized.advice;

  const mistakesFormatted = mistakesList.length > 0 ? mistakesList.join('; ') : 'не выявлены';
  const adviceFormatted = adviceList.length > 0 ? adviceList.join('; ') : 'не требуются';
  const managerEvaluationBlock = `Разбор работы менеджера (оценка ${resolvedScore}/10):\n- Ошибки и недочеты: ${mistakesFormatted}\n- Советы по оптимизации: ${adviceFormatted}`;

  const formattedSummary = `${essencePrefix} Пересказ диалога: ${retellingText} Вывод: ${conclusionText}\n${managerEvaluationBlock}`;

  const derivedStatus = ctx.isConfirmedBooking
    ? 'согласие'
    : (ctx.isDeclined ? 'отказ' : 'консультация');

  const structuredSummary = extractStructuredCallSummary(
    transcript,
    conclusionText || rawSummary,
    {
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master
    },
    salon,
    derivedStatus
  );

  return {
    formattedSummary,
    essence,
    structuredSummary,
    retelling: retellingText,
    conclusion: conclusionText,
    managerEvaluation: managerEvaluationBlock,
    mistakes: mistakesList,
    advice: adviceList,
    score: resolvedScore,
  };
}

function mapAuditCriterionId(rawNameOrId: string): string | undefined {
  const raw = String(rawNameOrId || '').trim();
  if (!raw) return undefined;
  const normalizedId = normalizeCriterionId(raw);
  const s = normalizedId.toLowerCase();
  const exact = EVALUATION_CRITERIA_DEFINITIONS.find(
    d => d.id === normalizedId || d.id === s || d.name.toLowerCase() === s
  );
  if (exact) return exact.id;
  if (s.includes('приветств')) return 'greeting_intro';
  if (s.includes('потребност') || s.includes('выявлен')) return 'needs_identification';
  if (s.includes('презентация услуги') || (s.includes('услуг') && s.includes('мастер'))) return 'service_presentation';
  if (s.includes('стоимост') || s.includes('цен')) return 'price_presentation';
  if (s.includes('возражен')) return 'objections';
  if (s.includes('дополнительн') || s.includes('допродаж')) return 'upsell';
  if (s.includes('параллельн')) return 'parallel_booking';
  if (s.includes('альтернатив')) return 'alternatives';
  if (s.includes('закрыт')) return 'closing';
  if (s.includes('коммуникац') || s.includes('завершен')) return 'communication';
  return undefined;
}

function cleanFactValue(val: unknown): string | null {
  if (val === null || val === undefined) return null;
  const s = String(val).trim();
  if (!s) return null;
  const low = s.toLowerCase();
  if (
    low === 'null' ||
    low === 'не озвучено' ||
    low === 'не указана' ||
    low === 'не указан' ||
    low === 'не указано' ||
    low === 'не выбран' ||
    low === 'не выбрана' ||
    low === 'не применимо' ||
    low === 'отсутствует'
  ) {
    return null;
  }
  return s;
}

/**
 * Программный препроцессинг типичных дефектов JSON, возвращаемого GigaChat:
 * 1) десятичные запятые в числах после «:» («8,3», «5,9») -> точки («8.3», «5.9»);
 * 2) экранирование неэкранированных двойных кавычек внутри строковых значений;
 * 3) удаление хвостовых запятых перед «}» и «]»;
 * 4) экранирование сырых переводов строк внутри строковых значений.
 */
export function preprocessMalformedJson(rawJson: string): { fixed: string; appliedFixes: string[] } {
  const input = rawJson || '';
  const fixes = new Set<string>();

  type ContainerFrame = { type: '{' | '['; expectKey: boolean };
  const stack: ContainerFrame[] = [];
  const out: string[] = [];

  const isWs = (ch: string) => ch === ' ' || ch === '\t' || ch === '\n' || ch === '\r';
  const skipWs = (idx: number): number => {
    let k = idx;
    while (k < input.length && isWs(input[k])) k++;
    return k;
  };
  const topContainer = (): ContainerFrame | undefined =>
    stack.length > 0 ? stack[stack.length - 1] : undefined;

  // Проверяем, начинается ли после запятой внутри объекта похожее на следующий ключ "key":
  const looksLikeObjectKeyAfterComma = (startIdx: number): boolean => {
    if (input[startIdx] !== '"') return false;
    let j = startIdx + 1;
    let len = 0;
    while (j < input.length && len < 160) {
      const ch = input[j];
      if (ch === '\\') {
        j += 2;
        len += 2;
        continue;
      }
      if (ch === '\n' || ch === '\r') return false;
      if (ch === '"') {
        const afterQuote = skipWs(j + 1);
        return input[afterQuote] === ':';
      }
      j++;
      len++;
    }
    return false;
  };

  const looksLikeArrayValueStart = (startIdx: number): boolean => {
    const ch = input[startIdx];
    if (!ch) return false;
    if (ch === '"' || ch === '{' || ch === '[' || ch === ']' || ch === '-' || (ch >= '0' && ch <= '9')) {
      return true;
    }
    const rest = input.slice(startIdx);
    return /^(?:true|false|null)(?=[\s,\]]|$)/.test(rest);
  };

  let inString = false;
  let isCurrentStringKey = false;
  let lastSignificantOutsideChar = '';

  let i = 0;
  while (i < input.length) {
    const ch = input[i];

    if (inString) {
      if (ch === '\\') {
        out.push(ch);
        if (i + 1 < input.length) {
          out.push(input[i + 1]);
          i += 2;
        } else {
          i += 1;
        }
        continue;
      }
      if (ch === '\r') {
        if (input[i + 1] !== '\n') {
          out.push('\\n');
          fixes.add('переводы строк в строках → \\n');
        }
        i++;
        continue;
      }
      if (ch === '\n') {
        out.push('\\n');
        fixes.add('переводы строк в строках → \\n');
        i++;
        continue;
      }
      if (ch === '"') {
        const nextIdx = skipWs(i + 1);
        const nextCh = nextIdx < input.length ? input[nextIdx] : '';
        const top = topContainer();
        let isValidClosing = false;

        if (nextIdx >= input.length) {
          isValidClosing = true;
        } else if (isCurrentStringKey) {
          isValidClosing = nextCh === ':';
        } else if (top?.type === '{') {
          if (nextCh === '}') {
            isValidClosing = true;
          } else if (nextCh === ',') {
            const afterComma = skipWs(nextIdx + 1);
            const afterCh = input[afterComma];
            if (afterCh === '}' || looksLikeObjectKeyAfterComma(afterComma)) {
              isValidClosing = true;
            }
          }
        } else if (top?.type === '[') {
          if (nextCh === ']') {
            isValidClosing = true;
          } else if (nextCh === ',') {
            const afterComma = skipWs(nextIdx + 1);
            if (looksLikeArrayValueStart(afterComma)) {
              isValidClosing = true;
            }
          }
        } else {
          isValidClosing = true;
        }

        if (isValidClosing) {
          inString = false;
          isCurrentStringKey = false;
          out.push('"');
          lastSignificantOutsideChar = '"';
        } else {
          out.push('\\"');
          fixes.add('экранирование незаэкранированных кавычек внутри строк');
        }
        i++;
        continue;
      }

      out.push(ch);
      i++;
      continue;
    }

    // Вне строки
    if (ch === '"') {
      const top = topContainer();
      inString = true;
      isCurrentStringKey = Boolean(top?.type === '{' && top.expectKey);
      out.push('"');
      i++;
      continue;
    }

    if (ch === '{') {
      stack.push({ type: '{', expectKey: true });
      out.push('{');
      lastSignificantOutsideChar = '{';
      i++;
      continue;
    }

    if (ch === '}') {
      if (stack.length > 0) stack.pop();
      out.push('}');
      lastSignificantOutsideChar = '}';
      i++;
      continue;
    }

    if (ch === '[') {
      stack.push({ type: '[', expectKey: false });
      out.push('[');
      lastSignificantOutsideChar = '[';
      i++;
      continue;
    }

    if (ch === ']') {
      if (stack.length > 0) stack.pop();
      out.push(']');
      lastSignificantOutsideChar = ']';
      i++;
      continue;
    }

    if (ch === ':') {
      const top = topContainer();
      if (top && top.type === '{') top.expectKey = false;
      out.push(':');
      lastSignificantOutsideChar = ':';
      i++;
      continue;
    }

    if (ch === ',') {
      const nextIdx = skipWs(i + 1);
      const nextCh = input[nextIdx];
      if (nextCh === '}' || nextCh === ']') {
        fixes.add('удаление хвостовых запятых');
        i++;
        continue;
      }
      const top = topContainer();
      if (top && top.type === '{') top.expectKey = true;
      out.push(',');
      lastSignificantOutsideChar = ',';
      i++;
      continue;
    }

    // Десятичная запятая в числовом значении после ':' (например, "overall_score": 8,3 или "score": 5,9)
    if (lastSignificantOutsideChar === ':' && (ch === '-' || (ch >= '0' && ch <= '9'))) {
      const numSlice = input.slice(i);
      const decMatch = numSlice.match(/^(-?\d+),(\d+)(?=\s*[,}\]])/);
      if (decMatch) {
        out.push(`${decMatch[1]}.${decMatch[2]}`);
        fixes.add(`десятичная запятая → точка (${decMatch[1]},${decMatch[2]} → ${decMatch[1]}.${decMatch[2]})`);
        lastSignificantOutsideChar = decMatch[2].slice(-1);
        i += decMatch[0].length;
        continue;
      }
    }

    if (!isWs(ch)) {
      lastSignificantOutsideChar = ch;
    }
    out.push(ch);
    i++;
  }

  return { fixed: out.join(''), appliedFixes: Array.from(fixes) };
}

function extractJsonErrorPosition(errorMessage: string, text: string): number {
  const posMatch = errorMessage.match(/at position (\d+)/i);
  if (posMatch) {
    const pos = parseInt(posMatch[1], 10);
    if (!Number.isNaN(pos)) return Math.max(0, Math.min(text.length, pos));
  }
  const lineColMatch = errorMessage.match(/line\s+(\d+)\s+column\s+(\d+)/i);
  if (lineColMatch) {
    const targetLine = parseInt(lineColMatch[1], 10);
    const targetCol = parseInt(lineColMatch[2], 10);
    const lines = text.split('\n');
    let offset = 0;
    for (let l = 0; l < Math.min(targetLine - 1, lines.length); l++) {
      offset += lines[l].length + 1;
    }
    return Math.max(0, Math.min(text.length, offset + Math.max(0, targetCol - 1)));
  }
  return 0;
}

export function parseJsonWithDiagnostics(text: string): any {
  let clean = (text || '')
    .replace(/```json\s*/gi, '')
    .replace(/```\s*/g, '')
    .trim();

  const jsonMatch = clean.match(/\{[\s\S]*\}/);
  if (jsonMatch) {
    clean = jsonMatch[0];
  }

  const { fixed, appliedFixes } = preprocessMalformedJson(clean);
  if (appliedFixes.length > 0) {
    console.warn(`[GigaChat JSON-FIX] Применены правки перед JSON.parse: ${appliedFixes.join('; ')}`);
  }

  try {
    return JSON.parse(fixed);
  } catch (err: any) {
    const errMsg = err?.message || String(err);
    const pos = extractJsonErrorPosition(errMsg, fixed);
    const first100 = fixed.slice(0, 100).replace(/\r?\n/g, '\\n');
    const start = Math.max(0, pos - 200);
    const end = Math.min(fixed.length, pos + 200);
    const snippet = `${fixed.slice(start, pos)}<<<ERROR_POS_${pos}>>>${fixed.slice(pos, end)}`;
    console.error(
      `[GigaChat JSON-ERR] ${errMsg} | позиция=${pos} | first100="${first100}" | фрагмент(±200)="${snippet}"`
    );
    const enriched: any = err instanceof Error ? err : new Error(errMsg);
    enriched.isJsonFormatError = true;
    enriched.jsonErrorPos = pos;
    enriched.jsonErrorSnippet = snippet;
    enriched.jsonErrorMessage = errMsg;
    enriched.jsonFirst100 = first100;
    throw enriched;
  }
}

/**
 * Разбирает ответ модели (поддерживает как новую 4-этапную схему { facts, booking_status, summary, audit },
 * так и совместимую плоскую схему), программно проверяет цитаты и возвращает согласованный AnalysisResult.
 */
export function parseGigaChatJson(
  text: string,
  customSalonName?: string,
  originalTranscript?: string,
  callTimestamp?: string
): AnalysisResult {
  const salon = customSalonName || process.env.SALON_NAME || 'Fashion Look Studio';
  const parsed = parseJsonWithDiagnostics(text);

  const rawFormattedTranscript =
    typeof parsed.formatted_transcript === 'string' && parsed.formatted_transcript.trim().length > 0
      ? parsed.formatted_transcript.trim()
      : undefined;

  const baseTranscriptForRoles = originalTranscript || rawFormattedTranscript || '';
  const origHasLiveDialogue = hasSubstantiveLiveDialogue(originalTranscript);
  const formattedTranscript =
    rawFormattedTranscript === 'Разговор не состоялся (диалог отсутствует)' && !origHasLiveDialogue
      ? rawFormattedTranscript
      : refineTranscriptRoles(baseTranscriptForRoles || rawFormattedTranscript || '');

  const rawOutcome = String(parsed.key_facts?.call_outcome || '').toLowerCase().trim();
  const rawBooking = String(parsed.booking_status || parsed.facts?.booking_status || parsed.key_facts?.booking_status || '').toLowerCase().trim();

  // Классификация контекста по очищенной от IVR стенограмме (защита от галлюцинаций модели)
  const dialogueCtx = classifyCallContext(formattedTranscript || originalTranscript || '');

  // Признак реального диалога: в стенограмме присутствуют обе роли ИЛИ 2+ содержательные реплики сторон.
  const transcriptHasBothRoles =
    !!formattedTranscript &&
    /менеджер\s*:/i.test(formattedTranscript) &&
    /клиент\s*:/i.test(formattedTranscript);
  const liveDialoguePresent = hasSubstantiveLiveDialogue(formattedTranscript || originalTranscript || '');

  // --- Определяем, состоялся ли разговор (главный переключатель) ---
  let isConversation: boolean;
  if (liveDialoguePresent || (dialogueCtx.category !== 'not_happened' && transcriptHasBothRoles)) {
    isConversation = true;
  } else if (typeof parsed.is_conversation === 'boolean') {
    isConversation = parsed.is_conversation;
  } else if (rawOutcome === 'не состоялся' || rawOutcome === 'автоответчик' || rawBooking === 'не применимо') {
    isConversation = false;
  } else if (rawOutcome || rawBooking) {
    isConversation = true;
  } else {
    isConversation = transcriptHasBothRoles;
  }

  // Явные маркеры провала перекрывают вердикт, но ТОЛЬКО если в стенограмме нет живого диалога.
  const isClassAShortNoTopic = Boolean(
    isShortNoTopicCall(originalTranscript) || isShortNoTopicCall(formattedTranscript)
  );
  const callDidNotReachManager = Boolean(
    isCallWithoutLiveManager(originalTranscript) ||
      isCallWithoutLiveManager(formattedTranscript) ||
      isClassAShortNoTopic
  );
  const summaryTextForCheck =
    typeof parsed.summary === 'string'
      ? parsed.summary
      : String(parsed.summary?.short_summary || parsed.summary?.booking_done || '');
  const combinedText = `${stripIvrFromTranscript(formattedTranscript || '')} ${parsed.transcript_summary || ''} ${summaryTextForCheck}`.toLowerCase();
  const explicitFailure =
    /разговор не состоялся|звонок не состоялся|автоответчик|автоинформатор|голосовая почта|оставьте сообщение|после сигнала|абонент временно недоступен|абонент занят|все операторы заняты/.test(combinedText);
  if ((explicitFailure && !transcriptHasBothRoles && !liveDialoguePresent) || callDidNotReachManager) {
    isConversation = false;
  }

  const modelClaimedNotHappened =
    parsed.is_conversation === false ||
    /не\s*состоял|автоответчик/i.test(rawOutcome) ||
    rawBooking === 'не применимо' ||
    rawBooking === 'не состоялся / короткий вызов';

  if (liveDialoguePresent && !callDidNotReachManager && modelClaimedNotHappened) {
    console.warn('[GigaChat Repair] Стенограмма содержит живой диалог — вердикт модели «не состоялся» переопределён.');
    isConversation = true;
  }

  // --- Ветка «разговор не состоялся» (обнуляем аудит ТОЛЬКО если нет живого диалога в стенограмме) ---
  if (!isConversation) {
    const rawAuditScore =
      parsed.audit?.overall_score !== undefined
        ? parsed.audit.overall_score
        : parsed.operator_score !== undefined
        ? parsed.operator_score
        : null;
    const rawAuditCriteria = Array.isArray(parsed.audit?.criteria)
      ? parsed.audit.criteria
      : Array.isArray(parsed.criteria_scores)
      ? parsed.criteria_scores
      : [];
    const rawAuditMistakes = Array.isArray(parsed.audit?.mistakes)
      ? parsed.audit.mistakes
      : Array.isArray(parsed.operator_mistakes)
      ? parsed.operator_mistakes
      : [];

    if (
      (rawAuditScore !== null && rawAuditScore !== undefined) ||
      rawAuditCriteria.length > 0 ||
      rawAuditMistakes.length > 0
    ) {
      console.warn(
        `[GigaChat Repair] Аудит обнулён: звонок не состоялся (была модельная ошибка operator_score${
          rawAuditScore !== null && rawAuditScore !== undefined ? `: ${rawAuditScore}` : ''
        }).`
      );
    }

    const modelSummaryObj = parsed.summary && typeof parsed.summary === 'object' ? parsed.summary : null;
    const modelShortSummary =
      (typeof modelSummaryObj?.short_summary === 'string' && modelSummaryObj.short_summary.trim()) ||
      (typeof parsed.summary === 'string' && parsed.summary.trim()) ||
      (typeof parsed.transcript_summary === 'string' && parsed.transcript_summary.trim()) ||
      '';
    const modelGoal =
      (typeof modelSummaryObj?.goal === 'string' && modelSummaryObj.goal.trim()) ||
      'Разговор не состоялся';
    const modelBookingDone =
      (typeof modelSummaryObj?.booking_done === 'string' && modelSummaryObj.booking_done.trim()) ||
      (isClassAShortNoTopic ? 'Не состоялся / короткий вызов' : 'Разговор не состоялся (диалог отсутствует)');
    const modelReason =
      (typeof modelSummaryObj?.reason_if_not === 'string' && modelSummaryObj.reason_if_not.trim()) ||
      (isClassAShortNoTopic ? 'Короткий вызов без содержательного диалога' : 'Диалог отсутствует');

    const emptyEval: CallEvaluation = {
      overall_score: null,
      max_score: 10,
      applicable_count: 0,
      total_criteria_count: 10,
      criteria: [],
      summary_verdict: 'Звонок не состоялся: оценка качества оператора не производится.',
    };
    const nextStepText = `Повторить попытку дозвона клиенту в рабочее время салона «${salon}».`;
    const notHappenedStruct: StructuredCallSummary = {
      call_purpose: isGreetingOnlyQuote(modelGoal) ? 'не озвучено' : modelGoal,
      requested_service: 'не озвучено',
      offered_master: 'не озвучено',
      offered_price: 'не озвучено',
      offered_date_time: 'не озвучено',
      booking_status_text: modelBookingDone,
      unbooked_reason: modelReason,
      manager_next_steps: [nextStepText],
    };

    const summarySrc: 'model' | 'template' = modelShortSummary ? 'model' : 'template';
    const notHappenedMistakesSrc: 'model' | 'template' | 'модель → fallback' =
      parsed.operator_mistakes !== undefined || (parsed.audit && parsed.audit.mistakes !== undefined)
        ? 'model'
        : 'модель → fallback';
    const notHappenedFeedbackReason = isClassAShortNoTopic
      ? 'короткий вызов без темы записи (Класс A)'
      : 'разговор не состоялся (диалог отсутствует)';
    const notHappenedSummaryTag =
      summarySrc === 'model'
        ? '[Summary source: model]'
        : `[Summary source: template (причина: ${notHappenedFeedbackReason})]`;
    console.log(`${notHappenedSummaryTag} [Mistakes source: ${notHappenedMistakesSrc}] [Feedback source: template (причина: ${notHappenedFeedbackReason})]`);
    return {
      is_conversation: false,
      transcript_summary:
        modelShortSummary ||
        'Разговор не состоялся: живой диалог между сторонами отсутствует.',
      booking_status: 'не применимо',
      formatted_transcript: formattedTranscript || 'Разговор не состоялся (диалог отсутствует)',
      structured_summary: notHappenedStruct,
      evaluation: emptyEval,
      criteria_scores: [],
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: modelGoal,
        service: null,
        date: null,
        time: null,
        master: null,
        call_purpose: notHappenedStruct.call_purpose,
        requested_service: notHappenedStruct.requested_service,
        offered_master: notHappenedStruct.offered_master,
        offered_price: notHappenedStruct.offered_price,
        offered_date_time: notHappenedStruct.offered_date_time,
        is_booked_text: notHappenedStruct.booking_status_text,
        unbooked_reason: notHappenedStruct.unbooked_reason,
        manager_next_steps: notHappenedStruct.manager_next_steps,
        structured_summary: notHappenedStruct,
        evaluation: emptyEval,
        criteria_scores: [],
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: 'Разговор не состоялся (диалог отсутствует).',
      recommendations: [nextStepText],
      missed_opportunities: [],
      summary_source: summarySrc,
      mistakes_source: notHappenedMistakesSrc,
      feedback_source: 'template',
      feedback_reason: notHappenedFeedbackReason,
    };
  }

  // --- Ветка «разговор состоялся»: явный словарь маппинга статуса Stage 2 -> legacy (booking_status, call_outcome) ---
  const BOOKING_STATUS_DICT: Record<
    string,
    {
      booking_status: 'согласие' | 'консультация' | 'отказ' | 'не применимо';
      call_outcome: 'запись' | 'перезвон' | 'отказ' | 'консультация' | 'не состоялся';
    }
  > = {
    'запись состоялась': { booking_status: 'согласие', call_outcome: 'запись' },
    'запись состоялась (перенесена)': { booking_status: 'согласие', call_outcome: 'запись' },
    'запись подтверждена': { booking_status: 'согласие', call_outcome: 'запись' },
    'подтверждена': { booking_status: 'согласие', call_outcome: 'запись' },
    'согласие': { booking_status: 'согласие', call_outcome: 'запись' },
    'отсрочка': { booking_status: 'консультация', call_outcome: 'перезвон' },
    'консультация / отказ': { booking_status: 'отказ', call_outcome: 'отказ' },
    'консультация/отказ': { booking_status: 'отказ', call_outcome: 'отказ' },
    'отказ': { booking_status: 'отказ', call_outcome: 'отказ' },
    'частичный контакт': { booking_status: 'консультация', call_outcome: 'перезвон' },
    'справочный запрос': { booking_status: 'консультация', call_outcome: 'консультация' },
    'консультация': { booking_status: 'консультация', call_outcome: 'консультация' },
    'не применимо': { booking_status: 'не применимо', call_outcome: 'не состоялся' },
    'не состоялся / короткий вызов': { booking_status: 'не применимо', call_outcome: 'не состоялся' },
  };

  let bookingStatus: string = rawBooking;
  let outcomeFromStage2: string | null = null;
  const exactDictMatch = BOOKING_STATUS_DICT[rawBooking];
  if (exactDictMatch) {
    bookingStatus = exactDictMatch.booking_status;
    outcomeFromStage2 = exactDictMatch.call_outcome;
  } else if (
    rawBooking.includes('запись состоялась') ||
    rawBooking.includes('запись подтверждена') ||
    rawBooking.includes('подтвержден') ||
    rawBooking.includes('соглас')
  ) {
    bookingStatus = BOOKING_STATUS_DICT['запись состоялась'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['запись состоялась'].call_outcome;
  } else if (rawBooking.includes('отсроч')) {
    bookingStatus = BOOKING_STATUS_DICT['отсрочка'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['отсрочка'].call_outcome;
  } else if (rawBooking.includes('отказ') || rawOutcome === 'отказ') {
    bookingStatus = BOOKING_STATUS_DICT['отказ'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['отказ'].call_outcome;
  } else if (rawBooking.includes('не применим')) {
    if (liveDialoguePresent) {
      bookingStatus = dialogueCtx.isConfirmedBooking
        ? BOOKING_STATUS_DICT['запись состоялась'].booking_status
        : dialogueCtx.isDeclined
        ? BOOKING_STATUS_DICT['отказ'].booking_status
        : BOOKING_STATUS_DICT['консультация'].booking_status;
      outcomeFromStage2 = dialogueCtx.isConfirmedBooking
        ? BOOKING_STATUS_DICT['запись состоялась'].call_outcome
        : dialogueCtx.isDeclined
        ? BOOKING_STATUS_DICT['отказ'].call_outcome
        : BOOKING_STATUS_DICT['консультация'].call_outcome;
    } else {
      bookingStatus = BOOKING_STATUS_DICT['не применимо'].booking_status;
      outcomeFromStage2 = BOOKING_STATUS_DICT['не применимо'].call_outcome;
    }
  } else if (rawBooking.includes('консультац')) {
    bookingStatus = BOOKING_STATUS_DICT['консультация'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['консультация'].call_outcome;
  } else if (rawOutcome === 'запись') {
    bookingStatus = BOOKING_STATUS_DICT['запись состоялась'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['запись состоялась'].call_outcome;
  } else {
    bookingStatus = BOOKING_STATUS_DICT['консультация'].booking_status;
    outcomeFromStage2 = BOOKING_STATUS_DICT['консультация'].call_outcome;
  }

  // Если в звонке подтверждается существующая запись (исходящий или входящий звонок: «вы/я записаны на/к...», «подтвердить запись», «подтверждаю», «да, я буду») — это «Запись состоялась»
  const isExistingBookingConfirmation =
    /(?:(?:вы|я)\s+(?:к\s+нам\s+|к\s+вам\s+)?записан[аы]?\s+(?:на|к)|(?:ваша|моя)\s+запись\s+(?:на|к)|напомина(?:ем|ю)\s+о\s+(?:вашей\s+)?записи|подтверд[а-яё]*\s+(?:свою\s+|вашу\s+)?(?:запис|визит)|подтвержда(?:ю|ем|ете))/iu.test(dialogueCtx.cleanTranscript) &&
    !/(?:отмен[а-яё]*\s+запис|не\s+смогу\s+прийти|не\s+приду)/iu.test(dialogueCtx.cleanTranscript);

  const hasVerifiedModelBookingMarker =
    Array.isArray(parsed.facts?.booking_markers) &&
    parsed.facts.booking_markers.some(
      (bm: any) => bm?.quote && isQuotePresentInTranscript(formattedTranscript || originalTranscript || '', String(bm.quote))
    );

  // Защита от ложного статуса «согласие» на основе IVR или при явном отказе/партнёрском звонке,
  // а также сохранение/восстановление статуса «согласие» при подтверждённой записи
  if (dialogueCtx.isUnavailableServiceRefusal || dialogueCtx.isDeclined) {
    bookingStatus = 'отказ';
  } else if (dialogueCtx.isNonClient) {
    bookingStatus = 'консультация';
  } else if (dialogueCtx.isConfirmedBooking || (isExistingBookingConfirmation && bookingStatus === 'согласие')) {
    bookingStatus = 'согласие';
  } else if (dialogueCtx.isLateWarning) {
    bookingStatus = bookingStatus === 'согласие' && (isExistingBookingConfirmation || hasVerifiedModelBookingMarker) ? 'согласие' : 'консультация';
  } else if (bookingStatus === 'согласие' && !dialogueCtx.isRescheduleOrCheck && !hasVerifiedModelBookingMarker && !isExistingBookingConfirmation) {
    bookingStatus = 'консультация';
  }

  const validOutcomes = ['запись', 'отказ', 'консультация', 'перезвон', 'отмена', 'не состоялся'];
  let outcome = outcomeFromStage2 || (validOutcomes.includes(rawOutcome) ? rawOutcome : 'консультация');
  if (bookingStatus === 'согласие') {
    outcome = 'запись';
  } else if (bookingStatus === 'не применимо') {
    outcome = 'не состоялся';
  } else if (bookingStatus === 'отказ' && outcome !== 'отмена') {
    outcome = 'отказ';
  } else if (dialogueCtx.isNonClient || (dialogueCtx.isLateWarning && bookingStatus !== 'согласие')) {
    outcome = 'консультация';
  } else if (rawBooking.includes('отсроч')) {
    outcome = 'перезвон';
  } else if (bookingStatus === 'консультация' && outcome === 'запись') {
    outcome = 'консультация';
  }

  const fullTranscript = formattedTranscript || originalTranscript || '';

  // Программная проверка цитат без повторного запроса к API (Требование 5)
  const rawSummaryObj = parsed.summary && typeof parsed.summary === 'object' ? parsed.summary : null;
  if (rawSummaryObj && Array.isArray(rawSummaryObj.quotes_support)) {
    const validQuotes: string[] = [];
    for (const q of rawSummaryObj.quotes_support) {
      const qs = String(q || '').trim();
      if (!qs) continue;
      if (isQuotePresentInTranscript(fullTranscript, qs)) {
        validQuotes.push(qs);
      } else {
        console.warn(`[GigaChat Facts] Цитата из summary.quotes_support не найдена в стенограмме: "${qs.slice(0, 60)}"`);
      }
    }
    rawSummaryObj.quotes_support = validQuotes;
  }

  const rawFacts = parsed.facts && typeof parsed.facts === 'object' ? parsed.facts : null;
  const validBookingMarkersQuotes: string[] = [];
  let validDateTimeOfferedQuote: string | null = null;
  if (rawFacts) {
    for (const key of ['client_name', 'desired_service', 'master', 'date_time_offered'] as const) {
      const entry = rawFacts[key];
      if (entry && typeof entry === 'object' && entry.quote) {
        if (!isQuotePresentInTranscript(fullTranscript, entry.quote)) {
          console.warn(`[GigaChat Facts] Цитата для facts.${key} не найдена в стенограмме — очищена без ретрая.`);
          entry.quote = null;
        } else if (key === 'date_time_offered') {
          validDateTimeOfferedQuote = String(entry.quote).trim();
        }
      }
    }
    if (Array.isArray(rawFacts.booking_markers)) {
      for (const bm of rawFacts.booking_markers) {
        const q = typeof bm === 'string' ? bm.trim() : String(bm?.quote || bm?.value || '').trim();
        if (q && isQuotePresentInTranscript(fullTranscript, q)) {
          validBookingMarkersQuotes.push(q);
        }
      }
    }
  }

  const rawAudit = parsed.audit && typeof parsed.audit === 'object' ? parsed.audit : null;

  let score: number | null = null;
  const candidateScore = parsed.operator_score ?? rawAudit?.overall_score;
  if (typeof candidateScore === 'number' && !isNaN(candidateScore)) {
    score = Math.max(1, Math.min(10, Math.round(candidateScore)));
  }
  if (score === null) {
    score = 7;
  }

  // Извлечение конкретных ошибок оператора из json ответа модели (поддерживает audit.mistakes и operator_mistakes)
  const hasModelMistakesField =
    parsed.operator_mistakes !== undefined || (rawAudit !== null && rawAudit.mistakes !== undefined);
  let rawMistakes: string[] = [];
  const sourceMistakes = parsed.operator_mistakes !== undefined ? parsed.operator_mistakes : rawAudit?.mistakes;
  if (Array.isArray(sourceMistakes)) {
    rawMistakes = sourceMistakes.map((m: any) => String(m ?? '').trim()).filter(Boolean);
  } else if (typeof sourceMistakes === 'string' && sourceMistakes.trim().length > 0) {
    rawMistakes = [sourceMistakes.trim()];
  }

  const rawSummary =
    parsed.transcript_summary ||
    (rawSummaryObj?.short_summary ? String(rawSummaryObj.short_summary) : null) ||
    (typeof parsed.summary === 'string' ? parsed.summary : null) ||
    'Краткое содержание диалога с результатом обращения.';

  // Извлекаем суть обращения: услуга, дата, время, мастер
  const extracted = extractEssenceDetails(fullTranscript, rawSummary, salon);

  const isMeaningful = (v: any) =>
    v &&
    typeof v === 'string' &&
    !v.toLowerCase().includes('не указан') &&
    !v.toLowerCase().includes('не выбран') &&
    !v.toLowerCase().includes('не озвуч') &&
    !v.toLowerCase().includes('не применимо') &&
    !v.toLowerCase().includes('студио') &&
    v.trim().length > 0;

  const parsedKeyFacts = parsed.key_facts || {};
  const rawMaster =
    cleanFactValue(rawFacts?.master?.value) ||
    cleanFactValue(rawSummaryObj?.master) ||
    parsedKeyFacts.master ||
    parsed.master;

  const service =
    cleanFactValue(rawFacts?.desired_service?.value) ||
    cleanFactValue(rawSummaryObj?.service) ||
    (isMeaningful(parsedKeyFacts.service) ? parsedKeyFacts.service : null) ||
    (isMeaningful(parsed.service) ? parsed.service : null) ||
    extracted.service;

  const rawDateTimeFromFacts =
    cleanFactValue(rawFacts?.date_time_offered?.value) ||
    cleanFactValue(rawSummaryObj?.date_time);

  // Пытаемся выделить дату и время из date_time_offered / summary.date_time, дополняя extractEssenceDetails
  let factsDate: string | null = null;
  let factsTime: string | null = null;
  if (rawDateTimeFromFacts) {
    const dtTimeMatch =
      rawDateTimeFromFacts.match(/\b([012]?\d)[:.\s]([0-5]\d)\b/) ||
      rawDateTimeFromFacts.match(/(?:^|[\s,])(?:в\s+)?([012]?\d)(?:\s*(?:час|ч\b)|$)/i);
    if (dtTimeMatch) {
      const h = parseInt(dtTimeMatch[1], 10);
      const m = dtTimeMatch[2] ? dtTimeMatch[2] : '00';
      if (h >= 7 && h <= 22) {
        factsTime = `${String(h).padStart(2, '0')}:${m}`;
      }
    }
    const dtDateMatch = rawDateTimeFromFacts.match(
      /(сегодня|завтра|послезавтра|в\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)|\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря))/i
    );
    if (dtDateMatch) {
      factsDate = dtDateMatch[1].replace(/^в\s+/i, '').trim().toLowerCase();
    }
  }

  const date =
    (isMeaningful(parsedKeyFacts.date) ? parsedKeyFacts.date : null) ||
    (isMeaningful(parsed.date) ? parsed.date : null) ||
    extracted.date ||
    factsDate;

  const rawTime =
    (isMeaningful(parsedKeyFacts.time) ? parsedKeyFacts.time : null) ||
    (isMeaningful(parsed.time) ? parsed.time : null) ||
    extracted.time ||
    factsTime;
  const time = rawTime
    ? rawTime.replace(
        /\b([012]?\d)\s+([0-5]\d|0\s+0)\b/gi,
        (_: any, h: string, m: string) =>
          `${h.padStart(2, '0')}:${m.replace(/\s+/g, '') === '0' || m.replace(/\s+/g, '') === '00' ? '00' : m}`
      )
    : null;

  const master =
    (isMasterNameValid(rawMaster) ? normalizeMasterName(rawMaster) : null) ||
    extracted.master;

  let comment =
    parsed.operator_comment && parsed.operator_comment.trim().length > 0
      ? parsed.operator_comment
      : `Администратор обработал обращение по регламенту салона «${salon}».`;
  // Ищем рекомендации модели во всех поддерживаемых полях ответа (recommendations, audit.recommendations, summary.recommendations, advice)
  const rawRecCandidate =
    parsed.recommendations !== undefined && parsed.recommendations !== null
      ? parsed.recommendations
      : rawAudit?.recommendations !== undefined && rawAudit?.recommendations !== null
      ? rawAudit.recommendations
      : rawSummaryObj?.recommendations !== undefined && rawSummaryObj?.recommendations !== null
      ? rawSummaryObj.recommendations
      : parsed.advice !== undefined && parsed.advice !== null
      ? parsed.advice
      : rawAudit?.advice !== undefined && rawAudit?.advice !== null
      ? rawAudit.advice
      : undefined;

  let hasValidModelRecommendations = false;
  let modelFeedbackInvalidReason: string | undefined;
  let rawModelRecommendations: string[] = [];

  if (rawRecCandidate === undefined || rawRecCandidate === null) {
    hasValidModelRecommendations = false;
    modelFeedbackInvalidReason = 'поле recommendations отсутствует в ответе модели';
  } else if (Array.isArray(rawRecCandidate)) {
    rawModelRecommendations = rawRecCandidate
      .map((r: any) => (typeof r === 'string' || typeof r === 'number' ? String(r).trim() : ''))
      .filter(Boolean);
    // Валидный массив от модели (в том числе [] для идеальных/подтверждающих звонков) — приоритет модели!
    hasValidModelRecommendations = true;
  } else if (typeof rawRecCandidate === 'string') {
    const trimmedRec = rawRecCandidate.trim();
    if (trimmedRec.length > 0 && trimmedRec.toLowerCase() !== 'null') {
      rawModelRecommendations = [trimmedRec];
      hasValidModelRecommendations = true;
    } else {
      hasValidModelRecommendations = false;
      modelFeedbackInvalidReason = 'пустая строка recommendations в ответе модели';
    }
  } else {
    hasValidModelRecommendations = false;
    modelFeedbackInvalidReason = `невалидный тип поля recommendations (${typeof rawRecCandidate})`;
  }

  const recommendations = hasValidModelRecommendations
    ? rawModelRecommendations
    : [`Соблюдать стандарты сервиса салона «${salon}».`];

  // Оценка звонка по 10 критериям (принимает как criteria_scores[], так и audit.criteria[])
  let rawCriteria: any[] = Array.isArray(parsed.criteria_scores)
    ? parsed.criteria_scores.map((c: any) => ({
        ...c,
        id: mapAuditCriterionId(c?.id || c?.name || '') || normalizeCriterionId(c?.id),
      }))
    : Array.isArray(parsed.evaluation?.criteria)
    ? parsed.evaluation.criteria.map((c: any) => ({
        ...c,
        id: mapAuditCriterionId(c?.id || c?.name || '') || normalizeCriterionId(c?.id),
      }))
    : Array.isArray(rawAudit?.criteria)
    ? rawAudit.criteria.map((c: any) => {
        const mappedId = mapAuditCriterionId(c?.id || c?.name || '');
        const canonicalDef = mappedId
          ? EVALUATION_CRITERIA_DEFINITIONS.find(d => d.id === mappedId)
          : undefined;
        const russianName =
          canonicalDef?.name ||
          (typeof c?.name === 'string' && /[а-яё]/i.test(c.name) ? c.name.trim() : c?.name);
        const quoteStr = c?.quote && String(c.quote).trim();
        const isValidQuote =
          quoteStr &&
          quoteStr.toLowerCase() !== 'не применимо' &&
          quoteStr.toLowerCase() !== 'null' &&
          isQuotePresentInTranscript(fullTranscript, quoteStr);
        const applicable =
          c?.applicable !== undefined
            ? Boolean(c.applicable)
            : c?.is_applicable !== undefined
            ? Boolean(c.is_applicable)
            : c?.score !== null;
        return {
          id: mappedId || normalizeCriterionId(c?.id),
          name: russianName,
          score: applicable ? c?.score : null,
          is_applicable: applicable,
          explanation: c?.reasoning || c?.explanation || '',
          evidence_quote: isValidQuote ? quoteStr : null,
        };
      })
    : [];

  rawCriteria = rawCriteria.filter((c: any) => c && (c.id || c.name));
  let mergedCriteria = rawCriteria;
  if (rawCriteria.length >= 2 && rawCriteria.length < 10) {
    const recArr = Array.isArray(recommendations) ? recommendations : [recommendations].filter(Boolean) as string[];
    const baseEval = extractCallEvaluation(fullTranscript, rawSummary, null, score, rawMistakes, recArr, salon);
    const providedById = new Map<string, any>();
    for (const rc of rawCriteria) {
      const cid = rc.id || mapAuditCriterionId(rc.name || '');
      if (cid) providedById.set(cid, rc);
    }
    mergedCriteria = baseEval.criteria.map(defCrit => providedById.get(defCrit.id) || defCrit);
  }
  const parsedEvalObj = mergedCriteria.length >= 2 ? buildCallEvaluation(mergedCriteria) : null;
  const evaluation: CallEvaluation = extractCallEvaluation(
    fullTranscript,
    rawSummary,
    parsedEvalObj,
    score,
    rawMistakes,
    Array.isArray(recommendations) ? recommendations : [recommendations].filter(Boolean) as string[],
    salon
  );

  // Пробрасываем evidence_quote из Pass 1 в evaluation.criteria, если они подтверждены стенограммой
  if (rawCriteria.length > 0) {
    const quoteById = new Map<string, string>();
    for (const rc of rawCriteria) {
      const cid = rc.id || mapAuditCriterionId(rc.name || '');
      if (cid && rc.evidence_quote) {
        quoteById.set(cid, rc.evidence_quote);
      }
    }
    evaluation.criteria = evaluation.criteria.map(crit => ({
      ...crit,
      evidence_quote: crit.evidence_quote ?? quoteById.get(crit.id) ?? undefined,
    }));
  }

  // Итоговый балл оператора строго равен среднему баллу по применимым критериям (evaluation.overall_score)
  if (evaluation.overall_score !== null && !isNaN(evaluation.overall_score)) {
    score = evaluation.overall_score;
  }

  // Структурированное резюме от модели: маппинг как parsed.structured_summary, так и нового parsed.summary
  const rawModelStruct: Record<string, any> = parsed.structured_summary || (rawSummaryObj
    ? {
        call_purpose: rawSummaryObj.goal,
        requested_service: rawSummaryObj.service,
        offered_master: rawSummaryObj.master,
        offered_price: rawSummaryObj.price,
        offered_date_time: rawSummaryObj.date_time,
        booking_status_text: rawSummaryObj.booking_done,
        unbooked_reason: rawSummaryObj.reason_if_not,
        manager_next_steps: rawSummaryObj.manager_next_steps,
      }
    : {});

  const modelShortSummaryBeforeGuard =
    (typeof rawSummaryObj?.short_summary === 'string' && rawSummaryObj.short_summary.trim()) ||
    (typeof parsed.transcript_summary === 'string' && parsed.transcript_summary.trim()) ||
    (typeof parsed.summary === 'string' && parsed.summary.trim()) ||
    '';
  const modelNextStepsBeforeGuard: string[] | null = Array.isArray(rawModelStruct.manager_next_steps)
    ? rawModelStruct.manager_next_steps.map((s: any) => String(s ?? '').trim()).filter(Boolean)
    : null;

  // Контроль цитат в генераторе ПЕРЕД формированием полей резюме:
  // если цитата привязана к конкретному говорящему («клиент сказал X»), проверяем, что реплика с этой меткой роли действительно содержит X.
  const transcriptForQuoteRoleCheck =
    originalTranscript && extractRoleUtterances(originalTranscript).hasRoleLabels
      ? originalTranscript
      : rawFormattedTranscript && extractRoleUtterances(rawFormattedTranscript).hasRoleLabels
      ? rawFormattedTranscript
      : formattedTranscript || originalTranscript || '';

  const rawFieldQuotes: Partial<Record<string, string | null | undefined>> = {
    ...(rawSummaryObj?.field_quotes && typeof rawSummaryObj.field_quotes === 'object' ? rawSummaryObj.field_quotes : {}),
    ...(typeof rawSummaryObj?.goal_quote === 'string' ? { call_purpose: rawSummaryObj.goal_quote } : {}),
    ...(typeof rawFacts?.goal?.quote === 'string' ? { call_purpose: rawFacts.goal.quote } : {}),
    ...(typeof rawFacts?.desired_service?.quote === 'string' ? { requested_service: rawFacts.desired_service.quote } : {}),
    ...(typeof rawFacts?.master?.quote === 'string' ? { offered_master: rawFacts.master.quote } : {}),
    ...(typeof rawFacts?.date_time_offered?.quote === 'string' ? { offered_date_time: rawFacts.date_time_offered.quote } : {}),
    ...(typeof rawSummaryObj?.reason_quote === 'string' ? { unbooked_reason: rawSummaryObj.reason_quote } : {}),
  };

  const quoteRoleCheck = enforceSummaryQuoteRoleControl(
    {
      short_summary: modelShortSummaryBeforeGuard,
      call_purpose: typeof rawModelStruct.call_purpose === 'string' ? rawModelStruct.call_purpose : undefined,
      requested_service: typeof rawModelStruct.requested_service === 'string' ? rawModelStruct.requested_service : undefined,
      offered_master: typeof rawModelStruct.offered_master === 'string' ? rawModelStruct.offered_master : undefined,
      offered_price: typeof rawModelStruct.offered_price === 'string' ? rawModelStruct.offered_price : undefined,
      offered_date_time: typeof rawModelStruct.offered_date_time === 'string' ? rawModelStruct.offered_date_time : undefined,
      booking_status_text: typeof rawModelStruct.booking_status_text === 'string' ? rawModelStruct.booking_status_text : undefined,
      unbooked_reason: typeof rawModelStruct.unbooked_reason === 'string' ? rawModelStruct.unbooked_reason : undefined,
      manager_next_steps: modelNextStepsBeforeGuard,
      operator_comment: comment,
      field_quotes: rawFieldQuotes,
      skip_service_field_quote_check: isExistingBookingConfirmation,
    },
    transcriptForQuoteRoleCheck
  );

  // Контроль «интерес → отказ» и короткие исходящие обзвоны с отказом:
  // при наличии фразы отказа клиента без подтверждённой записи не формируем «желаемая услуга / дата / время» как подтверждённый факт
  const isInterestToRefusalInParser = Boolean(
    bookingStatus !== 'согласие' &&
      !dialogueCtx.isConfirmedBooking &&
      hasClientRefusalPhrase(fullTranscript)
  );
  const isShortOutboundRefusalInParser = Boolean(
    bookingStatus !== 'согласие' &&
      !dialogueCtx.isConfirmedBooking &&
      isShortOutboundRefusalCall(fullTranscript)
  );

  const modelStruct: Record<string, any> = {
    ...rawModelStruct,
    ...(quoteRoleCheck.fields.call_purpose !== undefined ? { call_purpose: quoteRoleCheck.fields.call_purpose } : {}),
    ...(quoteRoleCheck.fields.requested_service !== undefined ? { requested_service: quoteRoleCheck.fields.requested_service } : {}),
    ...(quoteRoleCheck.fields.offered_master !== undefined ? { offered_master: quoteRoleCheck.fields.offered_master } : {}),
    ...(quoteRoleCheck.fields.offered_price !== undefined ? { offered_price: quoteRoleCheck.fields.offered_price } : {}),
    ...(quoteRoleCheck.fields.offered_date_time !== undefined ? { offered_date_time: quoteRoleCheck.fields.offered_date_time } : {}),
    ...(quoteRoleCheck.fields.booking_status_text !== undefined ? { booking_status_text: quoteRoleCheck.fields.booking_status_text } : {}),
    ...(quoteRoleCheck.fields.unbooked_reason !== undefined ? { unbooked_reason: quoteRoleCheck.fields.unbooked_reason } : {}),
    ...(quoteRoleCheck.fields.manager_next_steps !== undefined ? { manager_next_steps: quoteRoleCheck.fields.manager_next_steps } : {}),
  };
  if (isInterestToRefusalInParser) {
    if (modelStruct.requested_service !== NEEDS_VERIFICATION_LABEL) {
      modelStruct.requested_service = 'не озвучено';
    }
    if (modelStruct.offered_date_time !== NEEDS_VERIFICATION_LABEL) {
      modelStruct.offered_date_time = 'не озвучено';
    }
  }
  if (isShortOutboundRefusalInParser) {
    if (
      !modelStruct.booking_status_text ||
      /^не\s+(?:применимо|озвучено|указано)$/i.test(String(modelStruct.booking_status_text).trim())
    ) {
      modelStruct.booking_status_text = 'Консультация / отказ';
    }
    if (
      !modelStruct.unbooked_reason ||
      /^не\s+(?:применимо|озвучено|указано)$/i.test(String(modelStruct.unbooked_reason).trim())
    ) {
      modelStruct.unbooked_reason = 'клиент отказался / не смогла разговаривать';
    }
    if (!Array.isArray(modelStruct.manager_next_steps) || modelStruct.manager_next_steps.length === 0) {
      modelStruct.manager_next_steps = ['Запланировать повторный обзвон'];
    }
  }
  if (typeof quoteRoleCheck.fields.operator_comment === 'string') {
    comment = quoteRoleCheck.fields.operator_comment;
  }

  const modelShortSummaryRaw = quoteRoleCheck.fields.short_summary ?? modelShortSummaryBeforeGuard;
  const modelBookingDoneRaw =
    typeof modelStruct.booking_status_text === 'string' ? modelStruct.booking_status_text.trim() : '';
  const modelNextStepsRaw: string[] | null = Array.isArray(modelStruct.manager_next_steps)
    ? modelStruct.manager_next_steps.map((s: any) => String(s ?? '').trim()).filter(Boolean)
    : null;

  const hasValidModelSummary = Boolean(
    bookingStatus !== 'не применимо' &&
      (modelShortSummaryRaw.length > 0 || modelBookingDoneRaw.length > 0 || (modelNextStepsRaw && modelNextStepsRaw.length > 0))
  );

  const summarySource: 'model' | 'template' = hasValidModelSummary ? 'model' : 'template';

  const recArray: string[] = recommendations.map((r) => String(r ?? '').trim()).filter(Boolean);
  const visitDateContext = [date, rawDateTimeFromFacts, modelStruct.offered_date_time].filter(Boolean).join(' ');

  let formattedSummary: string;
  let essence: EssenceDetails;
  let finalStructuredSummary: StructuredCallSummary;
  let finalMistakes: string[];
  let finalAdvice: string[];
  let mistakesSource: 'model' | 'template' | 'модель → fallback' = 'модель → fallback';
  let feedbackSource: 'model' | 'template' = 'template';
  let feedbackReason: string | undefined;

  if (hasValidModelSummary) {
    // ПРИОРИТЕТ МОДЕЛИ: сохраняем summary.short_summary, summary.booking_done, summary.manager_next_steps,
    // а также audit.mistakes / operator_mistakes и recommendations КАК ЕСТЬ.
    // Шаблоны buildContextGroundedSummary, extractStructuredCallSummary и harmonizeMistakesAndEvaluation
    // НЕ перезаписывают валидный ответ модели и применяются ТОЛЬКО как fallback при отсутствии поля.
    essence = {
      service: isInterestToRefusalInParser ? null : service || null,
      date: isInterestToRefusalInParser ? null : date || null,
      time: isInterestToRefusalInParser ? null : time || null,
      master: isInterestToRefusalInParser ? null : master || null,
    };

    let lazyHarmonized: { mistakes: string[]; advice: string[] } | null = null;
    const getLazyHarmonized = () => {
      if (!lazyHarmonized) {
        lazyHarmonized = harmonizeMistakesAndEvaluation(
          rawMistakes,
          rawModelRecommendations,
          evaluation,
          fullTranscript,
          callTimestamp,
          visitDateContext
        );
      }
      return lazyHarmonized;
    };

    const usedModelMistakes = hasModelMistakesField;

    if (usedModelMistakes) {
      finalMistakes = filterOutdatedReminderMistakes(rawMistakes, callTimestamp, visitDateContext, fullTranscript);
    } else {
      finalMistakes = filterOutdatedReminderMistakes(
        getLazyHarmonized().mistakes,
        callTimestamp,
        visitDateContext,
        fullTranscript
      );
    }

    // Согласованность аудита (приоритет критериев): если среди применимых критериев есть оценки < 7,
    // блок mistakes не должен быть пустым или содержать «грубых ошибок не допущено».
    const reconciledModelMistakes = reconcileMistakesWithCriteria(
      finalMistakes,
      evaluation.criteria,
      callTimestamp,
      visitDateContext,
      fullTranscript
    );
    finalMistakes = reconciledModelMistakes.mistakes;

    // Feedback: строгий приоритет «модель → fallback»
    if (hasValidModelRecommendations) {
      finalAdvice = rawModelRecommendations;
      feedbackSource = 'model';
      feedbackReason = undefined;
    } else {
      finalAdvice = getLazyHarmonized().advice;
      feedbackSource = 'template';
      feedbackReason = modelFeedbackInvalidReason || 'поле recommendations отсутствует в ответе модели';
    }

    mistakesSource = usedModelMistakes ? 'model' : 'модель → fallback';

    const serviceStr = essence.service || 'не указана';
    const dateStr = essence.date || 'не указана';
    const timeStr = essence.time || 'не указано';
    const masterStr = essence.master || 'не выбран';
    const essencePrefix = `Суть обращения: услуга — ${serviceStr}, дата — ${dateStr}, время — ${timeStr}, мастер — ${masterStr}.`;

    const mistakesFormatted = finalMistakes.length > 0 ? finalMistakes.join('; ') : 'не выявлены';
    const adviceFormatted = finalAdvice.length > 0 ? finalAdvice.join('; ') : 'не требуются';
    const managerEvaluationBlock = `Разбор работы менеджера (оценка ${score}/10):\n- Ошибки и недочеты: ${mistakesFormatted}\n- Советы по оптимизации: ${adviceFormatted}`;

    // Сохраняем summary.short_summary модели verbatim (не подменяем шаблонным пересказом)
    const cleanedModelShort = modelShortSummaryRaw
      .replace(/(?:разбор работы менеджера(?:\s*\([^)]*\))?|оценка и разбор работы менеджера|разбор работы оператора)\s*:[\s\S]*$/i, '')
      .trim();

    if (cleanedModelShort) {
      const hasRetellingLabel = /(?:пересказ диалога|краткий пересказ(?: разговора)?|пересказ разговора)\s*:/i.test(cleanedModelShort);
      const hasEssenceLabel = /^суть обращения\s*:/i.test(cleanedModelShort);
      const hasConclusionLabel = /(?:^|\s)вывод\s*:/i.test(cleanedModelShort);

      if (hasRetellingLabel) {
        const body = hasEssenceLabel ? cleanedModelShort : `${essencePrefix} ${cleanedModelShort}`;
        formattedSummary = `${body}\n${managerEvaluationBlock}`;
      } else if (hasConclusionLabel) {
        const conclusionIdx = cleanedModelShort.search(/вывод\s*:/i);
        const beforeConc = cleanedModelShort.slice(0, conclusionIdx).replace(/^суть обращения\s*:[^.]*\.?\s*/i, '').trim();
        const concPart = cleanedModelShort.slice(conclusionIdx).trim();
        const body = beforeConc
          ? `${essencePrefix} Пересказ диалога: ${beforeConc} ${concPart}`
          : `${essencePrefix} ${concPart}`;
        formattedSummary = `${body}\n${managerEvaluationBlock}`;
      } else {
        const conclusionPart = modelBookingDoneRaw ? ` Вывод: ${modelBookingDoneRaw}` : '';
        formattedSummary = `${essencePrefix} Пересказ диалога: ${cleanedModelShort}${conclusionPart}\n${managerEvaluationBlock}`;
      }
    } else {
      const conclusionPart = modelBookingDoneRaw ? ` Вывод: ${modelBookingDoneRaw}` : '';
      formattedSummary = `${essencePrefix}${conclusionPart}\n${managerEvaluationBlock}`;
    }

    // Ленивый fallback ТОЛЬКО для отдельных незаполненных полей, если модель их вообще не прислала
    let lazyFallbackStruct: StructuredCallSummary | null = null;
    const getLazyFallbackStruct = (): StructuredCallSummary => {
      if (!lazyFallbackStruct) {
        lazyFallbackStruct = extractStructuredCallSummary(
          fullTranscript,
          cleanedModelShort || rawSummary,
          {
            service: essence.service,
            date: essence.date,
            time: essence.time,
            master: essence.master,
          },
          salon,
          bookingStatus
        );
      }
      return lazyFallbackStruct;
    };

    const pickModelFieldAsIs = (val: unknown, fallbackGetter: () => string): string => {
      if (typeof val === 'string' && val.trim().length > 0 && val.trim().toLowerCase() !== 'null') {
        return val.trim();
      }
      return fallbackGetter();
    };

    const resolveModelMasterField = (): string => {
      const rawOffered = typeof modelStruct.offered_master === 'string' ? modelStruct.offered_master.trim() : '';
      if (rawOffered === NEEDS_VERIFICATION_LABEL) {
        return NEEDS_VERIFICATION_LABEL;
      }
      if (!rawOffered || rawOffered.toLowerCase() === 'null') {
        return essence.master || 'не озвучено';
      }
      if (/^(?:не\s+озвучено|не\s+указан[ао]?|не\s+выбран[ао]?|не\s+применимо)$/i.test(rawOffered)) {
        return essence.master || rawOffered;
      }
      if (isMasterNameValid(rawOffered)) {
        return normalizeMasterName(rawOffered) || rawOffered;
      }
      // Защита от глаголов движения вроде «иду» в поле мастера
      return essence.master || 'не озвучено';
    };

    finalStructuredSummary = {
      call_purpose: pickModelFieldAsIs(modelStruct.call_purpose, () => getLazyFallbackStruct().call_purpose),
      requested_service: pickModelFieldAsIs(modelStruct.requested_service, () => getLazyFallbackStruct().requested_service),
      offered_master: resolveModelMasterField(),
      offered_price: pickModelFieldAsIs(modelStruct.offered_price, () => getLazyFallbackStruct().offered_price),
      offered_date_time: pickModelFieldAsIs(modelStruct.offered_date_time, () => getLazyFallbackStruct().offered_date_time),
      booking_status_text: pickModelFieldAsIs(modelStruct.booking_status_text, () => getLazyFallbackStruct().booking_status_text),
      unbooked_reason: pickModelFieldAsIs(modelStruct.unbooked_reason, () => getLazyFallbackStruct().unbooked_reason),
      manager_next_steps:
        modelNextStepsRaw !== null
          ? modelNextStepsRaw
          : getLazyFallbackStruct().manager_next_steps,
    };
  } else {
    // FALLBACK НА ШАБЛОНЫ: модель не вернула валидных текстовых полей резюме или статус «Не применимо»
    const templateFormatted = formatSummaryWithEssence(
      rawSummary,
      fullTranscript,
      {
        service: service || null,
        date: date || null,
        time: time || null,
        master: master || null,
      },
      salon,
      score,
      rawMistakes,
      recommendations,
      comment,
      evaluation,
      callTimestamp
    );
    formattedSummary = templateFormatted.formattedSummary;
    essence = templateFormatted.essence;
    finalStructuredSummary = templateFormatted.structuredSummary;
    finalMistakes = reconcileMistakesWithCriteria(
      templateFormatted.mistakes && templateFormatted.mistakes.length > 0 ? templateFormatted.mistakes : [],
      evaluation.criteria,
      callTimestamp,
      visitDateContext,
      fullTranscript
    ).mistakes;
    mistakesSource = hasModelMistakesField ? 'model' : 'модель → fallback';

    // Даже если summary ушёл в fallback, валидные рекомендации модели имеют приоритет (кроме «не применимо»)
    if (bookingStatus !== 'не применимо' && hasValidModelRecommendations) {
      finalAdvice = rawModelRecommendations;
      feedbackSource = 'model';
      feedbackReason = undefined;
    } else {
      finalAdvice =
        templateFormatted.advice && templateFormatted.advice.length > 0
          ? templateFormatted.advice
          : recArray;
      feedbackSource = 'template';
      feedbackReason =
        bookingStatus === 'не применимо'
          ? 'статус звонка «не применимо»'
          : modelFeedbackInvalidReason || 'поле recommendations отсутствует в ответе модели';
    }

    // Синхронизируем строки «Ошибки и недочеты» и «Советы по оптимизации» в formattedSummary после reconcileMistakesWithCriteria
    formattedSummary = formattedSummary
      .replace(
        /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
        `$1${finalMistakes.length > 0 ? finalMistakes.join('; ') : 'не выявлены'}`
      )
      .replace(
        /(-\s*Советы по оптимизации:\s*)[^\n]*/i,
        `$1${finalAdvice.length > 0 ? finalAdvice.join('; ') : 'не требуются'}`
      );
  }

  const summaryFallbackReason =
    bookingStatus === 'не применимо'
      ? 'статус звонка «не применимо»'
      : 'модель не вернула валидных текстовых полей summary';
  const summaryLogTag =
    summarySource === 'model'
      ? '[Summary source: model]'
      : `[Summary source: template (причина: ${summaryFallbackReason})]`;
  const feedbackLogTag =
    feedbackSource === 'model'
      ? '[Feedback source: model]'
      : `[Feedback source: template (причина: ${feedbackReason || 'не указана'})]`;
  console.log(`${summaryLogTag} [Mistakes source: ${mistakesSource}] ${feedbackLogTag}`);

  const rawGreetingCheck = parsed.facts?.greeting_check && typeof parsed.facts.greeting_check === 'object'
    ? parsed.facts.greeting_check
    : null;
  const greetingCheckQuote =
    typeof rawGreetingCheck?.quote === 'string' && rawGreetingCheck.quote.trim()
      ? rawGreetingCheck.quote.trim()
      : null;
  const modelAdminNameRaw =
    typeof rawGreetingCheck?.administrator_name === 'string' && !isGenericAtsOperatorLabel(rawGreetingCheck.administrator_name)
      ? normalizeAdministratorFirstName(rawGreetingCheck.administrator_name, { requireKnownName: false })
      : null;
  const transcriptAdminIntro = extractAdministratorIntroNameFromTranscript(
    formattedTranscript || fullTranscript,
    greetingCheckQuote
  );
  const spokenOperatorName = modelAdminNameRaw || transcriptAdminIntro.name || null;

  const result: AnalysisResult = {
    is_conversation: true,
    transcript_summary: formattedSummary,
    booking_status: bookingStatus,
    formatted_transcript: formattedTranscript,
    structured_summary: finalStructuredSummary,
    evaluation,
    criteria_scores: evaluation.criteria,
    key_facts: {
      is_dispute: Boolean(parsed.key_facts?.is_dispute),
      dispute_reason: parsed.key_facts?.dispute_reason || null,
      tone_client: parsed.key_facts?.tone_client || 'нейтральный',
      tone_manager: parsed.key_facts?.tone_manager || 'нейтральный',
      call_outcome: outcome,
      booking_status: bookingStatus,
      client_issue:
        parsed.key_facts?.client_issue ||
        cleanFactValue(rawSummaryObj?.goal) ||
        (essence.service ? `Запись на ${essence.service}` : `Обращение в салон «${salon}»`),
      call_datetime:
        (typeof parsed.facts?.call_datetime === 'string' && parsed.facts.call_datetime.trim()) ||
        (typeof parsed.facts?.call_datetime?.value === 'string' && parsed.facts.call_datetime.value.trim()) ||
        formatCallDateTimeInSalonTz(callTimestamp) ||
        null,
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master,
      administrator_name: spokenOperatorName,
      call_purpose: finalStructuredSummary.call_purpose,
      requested_service: finalStructuredSummary.requested_service,
      offered_master: finalStructuredSummary.offered_master,
      offered_price: finalStructuredSummary.offered_price,
      offered_date_time: finalStructuredSummary.offered_date_time,
      is_booked_text: finalStructuredSummary.booking_status_text,
      unbooked_reason: finalStructuredSummary.unbooked_reason,
      manager_next_steps: finalStructuredSummary.manager_next_steps,
      structured_summary: finalStructuredSummary,
      evaluation,
      criteria_scores: evaluation.criteria,
      ...(validBookingMarkersQuotes.length > 0 ? { booking_markers_quotes: validBookingMarkersQuotes } : {}),
      ...(validDateTimeOfferedQuote ? { date_time_offered_quote: validDateTimeOfferedQuote } : {}),
    },
    operator_score: score,
    spoken_operator_name: spokenOperatorName,
    operator_mistakes: finalMistakes,
    operator_comment: comment,
    recommendations: finalAdvice,
    missed_opportunities: [],
    ...(quoteRoleCheck.flaggedFields.length > 0 ? { verification_flags: quoteRoleCheck.flaggedFields } : {}),
    summary_source: summarySource,
    mistakes_source: mistakesSource,
    feedback_source: feedbackSource,
    ...(feedbackReason ? { feedback_reason: feedbackReason } : {}),
  };

  // Прокидывание упущенных возможностей из ответа модели (ШАГ 7 системного промпта)
  let missedOpportunities: { type: string; evidence: string; what_to_say: string }[] = [];
  const rawMissed = (parsed as any).missed_opportunities;
  if (Array.isArray(rawMissed)) {
    missedOpportunities = rawMissed
      .map((m: any) => {
        if (m && typeof m === 'object') {
          const item = {
            type: String(m.type || m.category || '').trim(),
            evidence: String(m.evidence || m.reason || '').trim(),
            what_to_say: String(m.what_to_say || m.suggestion || '').trim(),
          };
          return item.type ? item : null;
        }
        if (typeof m === 'string' && m.trim()) {
          return { type: m.trim(), evidence: '', what_to_say: '' };
        }
        return null;
      })
      .filter((m: any): m is { type: string; evidence: string; what_to_say: string } => m !== null);
  }
  result.missed_opportunities = missedOpportunities;

  // Программная проверка согласованности + безусловная синхронизация mistakes <-> критерии < 7 (приоритет критериев)
  const check = validateResult(result, fullTranscript);
  if (!check.valid) {
    console.warn(`[GigaChat] Обнаружены несоответствия в ответе модели: ${check.errors.join('; ')}`);
  }

  if (result.booking_status !== 'не применимо' && Array.isArray(result.evaluation?.criteria)) {
    const fixed = reconcileMistakesWithCriteria(
      result.operator_mistakes || [],
      result.evaluation.criteria,
      callTimestamp,
      visitDateContext,
      fullTranscript
    );
    if (
      fixed.fixedFromCriteria ||
      JSON.stringify(result.operator_mistakes || []) !== JSON.stringify(fixed.mistakes)
    ) {
      result.operator_mistakes = fixed.mistakes;
      if (result.transcript_summary) {
        result.transcript_summary = result.transcript_summary.replace(
          /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
          `$1${fixed.mistakes.length > 0 ? fixed.mistakes.join('; ') : 'не выявлены'}`
        );
      }
    }
  }

  return result;
}


export function generateLocalFallbackAnalysis(
  transcript: string,
  _model: GigaChatModel,
  callDurationSeconds?: number,
  customSalonName?: string,
  fallbackReason?: string,
  callTimestamp?: string
): AnalysisResult {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();
  const rawClean = (transcript || '').trim();
  const rawLower = rawClean.toLowerCase();
  const explicitReason = (fallbackReason || '').trim();

  // Вспомогательный конструктор строго по формату ПРИМЕРа 1 для всех несостоявшихся звонков (is_conversation = false):
  // без оценки качества (null), без списка ошибок ([]), только рекомендация перезвонить.
  const buildExample1NotHappenedFallback = (
    reason: string,
    summaryText: string,
    formattedTr: string,
    clientIssue: string,
    commentText: string
  ): AnalysisResult => {
    console.warn(`[GigaChat FALLBACK] Анализ выполнен локальным резервом. Причина: ${reason}`);
    console.log(`[Summary source: template (причина: ${reason})] [Mistakes source: template (причина: ${reason})] [Feedback source: template (причина: ${reason})]`);
    const nextStepText = `Повторить попытку дозвона клиенту в рабочее время салона «${salon}».`;
    const emptyEval: CallEvaluation = {
      overall_score: null,
      max_score: 10,
      applicable_count: 0,
      total_criteria_count: 10,
      criteria: [],
      summary_verdict: 'Звонок не состоялся: оценка качества оператора не производится.',
    };
    const failedStruct: StructuredCallSummary = {
      call_purpose: 'Разговор не состоялся',
      requested_service: 'не озвучено',
      offered_master: 'не озвучено',
      offered_price: 'не озвучено',
      offered_date_time: 'не озвучено',
      booking_status_text: 'Разговор не состоялся (диалог отсутствует)',
      unbooked_reason: 'Диалог отсутствует',
      manager_next_steps: [nextStepText],
    };
    return {
      is_conversation: false,
      transcript_summary: summaryText,
      booking_status: 'не применимо',
      formatted_transcript: formattedTr,
      structured_summary: failedStruct,
      evaluation: emptyEval,
      criteria_scores: [],
      key_facts: {
        is_dispute: false,
        dispute_reason: null,
        tone_client: 'нейтральный',
        tone_manager: 'нейтральный',
        call_outcome: 'не состоялся',
        booking_status: 'не применимо',
        client_issue: clientIssue,
        service: null,
        date: null,
        time: null,
        master: null,
        call_purpose: failedStruct.call_purpose,
        requested_service: failedStruct.requested_service,
        offered_master: failedStruct.offered_master,
        offered_price: failedStruct.offered_price,
        offered_date_time: failedStruct.offered_date_time,
        is_booked_text: failedStruct.booking_status_text,
        unbooked_reason: failedStruct.unbooked_reason,
        manager_next_steps: failedStruct.manager_next_steps,
        structured_summary: failedStruct,
        evaluation: emptyEval,
        criteria_scores: [],
      },
      operator_score: null,
      operator_mistakes: [],
      operator_comment: commentText,
      recommendations: [nextStepText],
      missed_opportunities: [],
      summary_source: 'template',
      mistakes_source: 'template',
      feedback_source: 'template',
      feedback_reason: reason,
      fallback_reason: reason,
    };
  };

  // 1. Жёсткий предохранитель: звонки менее 10 секунд без реального диалога
  if (callDurationSeconds !== undefined && callDurationSeconds < 10 && !hasSubstantiveLiveDialogue(rawClean)) {
    return buildExample1NotHappenedFallback(
      explicitReason || `длительность звонка < 10 сек (${callDurationSeconds} сек)`,
      `Разговор не состоялся: длительность вызова ${callDurationSeconds} сек (менее 10 секунд), живой диалог между сторонами отсутствует.`,
      rawClean || 'Разговор не состоялся (диалог отсутствует)',
      'Звонок менее 10 секунд / диалог отсутствует',
      `Оценка не выставляется: разговор не состоялся (длительность ${callDurationSeconds} сек менее 10 секунд).`
    );
  }

  // 2. Пустой транскрипт, тишина/гудки/сброс или заглушка (ожидание STT)
  const strippedNoiseOnly = rawClean
    .replace(/\[(?:тишина|гудки|сброс|шум|музыка|нет\s+речи|автоответчик|нрзб)\]/giu, '')
    .replace(/[\s.,!?;:\-–—]+/g, ' ')
    .trim();
  const isPlaceholderOrEmpty =
    !rawClean ||
    strippedNoiseOnly.length < 4 ||
    rawLower.includes('стенограмма ожидает') ||
    rawLower.includes('запись разговора и стенограмма отсутствуют');

  if (isPlaceholderOrEmpty) {
    const durLabel = callDurationSeconds !== undefined ? ` (длительность ${callDurationSeconds} сек.)` : '';
    return buildExample1NotHappenedFallback(
      explicitReason || 'пустая стенограмма / отсутствует разборчивая речь',
      `Разговор не состоялся: аудиозапись${durLabel} не содержит разборчивой речи (зафиксированы только гудки/тишина или сброс линии).`,
      rawClean || 'Разговор не состоялся (диалог отсутствует)',
      'Отсутствует разборчивая речь в аудиозаписи',
      `Оценка не выставляется: аудиозапись${durLabel} не содержит разборчивого диалога оператора и клиента.`
    );
  }

  // 3. Очистка от эха, выделение IVR («Автоинформатор») и точное определение ролей («Менеджер» / «Клиент»)
  const formattedTranscript = refineTranscriptRoles(fixDuplicatedTranscript(rawClean));
  const ctx = classifyCallContext(formattedTranscript);

  // Проверка наличия речи менеджера / живого двустороннего диалога
  const managerUtteranceText = formattedTranscript
    .split('\n')
    .filter((l) => /^(?:менеджер|администратор|оператор)\s*:/i.test(l.trim()))
    .map((l) => l.replace(/^(?:менеджер|администратор|оператор)\s*:\s*/i, '').trim())
    .join(' ')
    .trim();
  const rawAfterIvr = stripIvrFromTranscript(rawClean);
  const rawHasClientLabel = /^(?:клиент|гость)\s*:/im.test(rawAfterIvr);
  const rawHasManagerLabel = /^(?:менеджер|администратор|оператор)\s*:/im.test(rawAfterIvr);
  const cleanAfterIvr = stripIvrFromTranscript(formattedTranscript);
  const managerDidNotSpeak =
    (rawHasClientLabel && !rawHasManagerLabel) ||
    (cleanAfterIvr.length > 0 &&
      /^(?:клиент|гость)\s*:/i.test(cleanAfterIvr) &&
      managerUtteranceText.length === 0);

  // 4. Несостоявшийся разговор / автоответчик / очередь без менеджера / Класс A -> строгий формат ПРИМЕРа 1 / 13 / 14
  const callWithoutLiveManager = isCallWithoutLiveManager(rawClean);
  const shortNoTopicClassA = isShortNoTopicCall(rawClean, callDurationSeconds);
  if (callWithoutLiveManager || shortNoTopicClassA || ctx.category === 'not_happened' || managerDidNotSpeak) {
    return buildExample1NotHappenedFallback(
      explicitReason ||
        (callWithoutLiveManager
          ? 'звонок не дошёл до менеджера (очередь/автоответчик без реплик менеджера)'
          : shortNoTopicClassA
          ? 'короткий вызов без темы записи/услуги (Класс A)'
          : managerDidNotSpeak
          ? 'разговор не состоялся (менеджер не вступил в диалог)'
          : 'разговор не состоялся (автоответчик или обрыв)'),
      callWithoutLiveManager
        ? 'Разговор не состоялся: звонок не дошёл до менеджера (зафиксированы только фразы очереди или автоответчика без живого диалога с администратором).'
        : shortNoTopicClassA
        ? 'Звонок не состоялся (короткий вызов без содержательного диалога и темы записи). Оценка качества оператора не производится.'
        : 'Разговор не состоялся: живой диалог между сторонами отсутствует (автоответчик, тишина или односторонняя связь).',
      formattedTranscript || rawClean || 'Разговор не состоялся (диалог отсутствует)',
      callWithoutLiveManager
        ? 'Звонок не дошёл до менеджера (очередь / автоответчик)'
        : shortNoTopicClassA
        ? 'Не состоялся / короткий вызов'
        : 'Звонок не состоялся / диалог отсутствует',
      callWithoutLiveManager
        ? 'Оценка не выставляется: звонок не дошёл до менеджера (живых реплик администратора не зафиксировано).'
        : shortNoTopicClassA
        ? 'Звонок не состоялся: оценка качества оператора не производится.'
        : 'Разговор не состоялся: зафиксирован автоответчик или отсутствие диалога (оценка не выставляется).'
    );
  }

  const finalFallbackReason = explicitReason || 'локальный резервный генератор (причина не передана)';
  console.warn(`[GigaChat FALLBACK] Анализ выполнен локальным резервом. Причина: ${finalFallbackReason}`);

  // 5. Состоявшийся разговор — классифицированный строго по очищенной стенограмме (без IVR)
  const essence = extractEssenceDetails(formattedTranscript, undefined, salon);
  const { conclusion } = buildContextGroundedSummary(ctx, essence, salon);

  let bookingStatus: 'согласие' | 'отказ' | 'консультация' = 'консультация';
  let outcome: 'запись' | 'отказ' | 'консультация' | 'перезвон' | 'отмена' = 'консультация';

  if (ctx.category === 'confirmed_booking') {
    bookingStatus = 'согласие';
    outcome = 'запись';
  } else if (ctx.category === 'refusal_unavailable_service' || ctx.category === 'declined') {
    bookingStatus = 'отказ';
    outcome = 'отказ';
  } else if (ctx.category === 'dispute') {
    bookingStatus = 'консультация';
    outcome = 'перезвон';
  } else if (ctx.category === 'reschedule_or_cancel') {
    bookingStatus = /отмен/i.test(ctx.cleanTranscript) ? 'отказ' : 'согласие';
    outcome = /отмен/i.test(ctx.cleanTranscript) ? 'отмена' : 'запись';
  } else {
    // non_client, late_or_visit_update, consultation
    bookingStatus = 'консультация';
    outcome = 'консультация';
  }

  // Фактологическая оценка по 10 критериям (определяет применимость, баллы, ошибки и рекомендации)
  const evaluation: CallEvaluation = extractCallEvaluation(
    formattedTranscript,
    conclusion,
    null,
    undefined,
    undefined,
    undefined,
    salon
  );

  const score =
    evaluation.overall_score !== null && !isNaN(evaluation.overall_score)
      ? evaluation.overall_score
      : 8;

  const { formattedSummary, structuredSummary, mistakes, advice } = formatSummaryWithEssence(
    conclusion,
    formattedTranscript,
    essence,
    salon,
    score,
    undefined,
    undefined,
    undefined,
    evaluation,
    callTimestamp
  );

  const CANNED_FALLBACK_MISTAKE_RE =
    /^(?:администратор\s+не\s+назвал\s+собственное\s+имя|не\s+заданы\s+уточняющие\s+вопросы\s+для\s+выявления\s+потребностей|особенности\s+услуги\s+и\s+квалификация\s+мастера\s+не\s+раскрыты|в\s+ходе\s+диалога\s+специалист\s+и\s+особенности\s+услуги\s+подробно\s+не\s+презентовались|администратор\s+не\s+предложил\s+сопутствующие\s+процедуры|сопутствующие\s+процедуры\s+к\s+основной\s+услуге\s+администратором\s+не\s+предлагались)/i;

  const cleanedFallbackMistakes = filterOutdatedReminderMistakes(
    mistakes && mistakes.length > 0 ? mistakes : [],
    callTimestamp,
    essence.date,
    formattedTranscript
  ).filter((m) => !CANNED_FALLBACK_MISTAKE_RE.test(String(m || '').trim()));

  const finalMistakes = reconcileMistakesWithCriteria(
    cleanedFallbackMistakes,
    evaluation.criteria || [],
    callTimestamp,
    essence.date,
    formattedTranscript
  ).mistakes;

  const finalFormattedSummary = formattedSummary.replace(
    /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
    `$1${finalMistakes.length > 0 ? finalMistakes.join('; ') : 'не выявлены'}`
  );
  const finalAdvice = advice && advice.length > 0 ? advice : [`Соблюдать стандарты сервиса салона «${salon}».`];

  let comment = `Администратор обработал обращение по регламенту салона «${salon}».`;
  if (ctx.category === 'non_client') {
    comment = 'Нецелевой/партнёрский звонок: администратор вежливо принял информацию без лишней нагрузки по скрипту продаж.';
  } else if (ctx.category === 'late_or_visit_update') {
    comment = 'Клиент предупредил об опоздании: администратор вежливо принял информацию и подтвердил ожидание гостя.';
  } else if (ctx.category === 'refusal_unavailable_service') {
    comment = 'Запрошенная услуга в салоне не представлена; администратор предложил доступную альтернативу, но клиент отказался.';
  } else if (ctx.category === 'dispute') {
    comment = 'Зафиксировано обращение со спорным вопросом — требуется контроль со стороны управляющего.';
  } else if (ctx.category === 'declined') {
    comment = 'Запись не оформлена: клиент отклонил предложенные условия или время визита.';
  } else if (ctx.category === 'confirmed_booking') {
    comment = `Администратор согласовал и подтвердил запись по стандартам салона «${salon}».`;
  }

  const clientIssue = ctx.category === 'non_client'
    ? (ctx.nonClientTopic || 'Организационный / партнёрский вопрос')
    : ctx.category === 'late_or_visit_update'
    ? `Предупреждение об опоздании${ctx.lateMinutes ? ` на ${ctx.lateMinutes}` : ''}`
    : ctx.category === 'refusal_unavailable_service'
    ? `Запрос отсутствующей услуги (${essence.service || 'услуга не представлена'})`
    : ctx.category === 'dispute'
    ? 'Вопрос / претензия по обслуживанию'
    : essence.service
    ? `Обращение по услуге: ${essence.service}`
    : 'Консультация / обращение в салон';

  console.log(`[Summary source: template (причина: ${finalFallbackReason})] [Mistakes source: template (причина: ${finalFallbackReason})] [Feedback source: template (причина: ${finalFallbackReason})]`);
  return {
    is_conversation: true,
    transcript_summary: finalFormattedSummary,
    booking_status: bookingStatus,
    formatted_transcript: formattedTranscript,
    structured_summary: structuredSummary,
    evaluation,
    criteria_scores: evaluation.criteria,
    key_facts: {
      is_dispute: ctx.isDispute,
      dispute_reason: ctx.isDispute ? 'Зафиксирован спорный вопрос или отмена в тексте разговора' : null,
      tone_client: ctx.isDispute ? 'негативный' : 'нейтральный',
      tone_manager: 'позитивный',
      call_outcome: outcome,
      booking_status: bookingStatus,
      client_issue: clientIssue,
      service: essence.service,
      date: essence.date,
      time: essence.time,
      master: essence.master,
      call_purpose: structuredSummary.call_purpose,
      requested_service: structuredSummary.requested_service,
      offered_master: structuredSummary.offered_master,
      offered_price: structuredSummary.offered_price,
      offered_date_time: structuredSummary.offered_date_time,
      is_booked_text: structuredSummary.booking_status_text,
      unbooked_reason: structuredSummary.unbooked_reason,
      manager_next_steps: structuredSummary.manager_next_steps,
      structured_summary: structuredSummary,
      evaluation,
      criteria_scores: evaluation.criteria,
    },
    operator_score: score,
    operator_mistakes: finalMistakes,
    operator_comment: comment,
    recommendations: finalAdvice,
    summary_source: 'template',
    mistakes_source: 'template',
    feedback_source: 'template',
    feedback_reason: finalFallbackReason,
    fallback_reason: finalFallbackReason,
  };
}

/**
 * Локальный генератор следующих шагов (Next Steps) для администратора
 */
export function generateLocalNextSteps(call: CallRecord, customSalonName?: string): string[] {
  const salon = (customSalonName || process.env.SALON_NAME || 'Fashion Look Studio').trim();
  const struct = extractStructuredCallSummary(
    call.transcript || '',
    call.summary || '',
    call.key_facts,
    salon,
    call.booking_status
  );

  const steps: string[] = [...struct.manager_next_steps];
  const kf: Partial<KeyFacts> = call.key_facts || {};
  if (Array.isArray(kf.promises) && kf.promises.length > 0) {
    kf.promises.forEach(p => {
      if (p && typeof p === 'string' && p.trim()) {
        steps.push(`Выполнить зафиксированное обещание: ${p.trim()}`);
      }
    });
  }
  return steps;
}

