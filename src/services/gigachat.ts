/**
 * Программная проверка согласованности ответа модели.
 * Базовые проверки: оценка при несостоявшемся звонке и статус «не состоялся» при реальном диалоге.
 * Дополнительные проверки (согласованность разделов): call_outcome<->booking_status,
 * operator_score<->среднее применимых критериев, оценка в резюме<->operator_score,
 * «фантомные» ошибки допродаж при пустом missed_opportunities,
 * санитарная проверка мастера, синхронизация критерия цены с offered_price.
 */
/**
 * Проверяет, содержит ли стенограмма живой диалог:
 * минимум 2 содержательные реплики сторон (не считая меток АТС/IVR, шумовых заглушек
 * и односложных междометий вроде «угу», «ага», «алло»).
 */
export function hasSubstantiveLiveDialogue(transcript?: string | null): boolean {
  if (!transcript || typeof transcript !== 'string') return false;
  const trimmed = transcript.trim();
  if (!trimmed || trimmed === 'Разговор не состоялся (диалог отсутствует)') return false;
  if (isCallWithoutLiveManager(trimmed) || isShortNoTopicCall(trimmed)) return false;

  // Убираем фразы АТС / IVR до проверки
  const rawWithoutIvr = stripIvrFromTranscript(trimmed);
  if (!rawWithoutIvr) return false;

  // Явные односторонние звонки (в исходном тексте есть только Клиент: и ни одной реплики Менеджера:)
  const rawHasClient = /^(?:клиент|гость)\s*:/im.test(rawWithoutIvr);
  const rawHasManager = /^(?:менеджер|администратор|оператор)\s*:/im.test(rawWithoutIvr);
  if (rawHasClient && !rawHasManager) {
    return false;
  }

  const normalized = stripIvrFromTranscript(refineTranscriptRoles(trimmed));
  if (!normalized) return false;

  const lines = normalized
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);

  const AUTO_RESPONDER_ONLY_RE =
    /^(?:разговор не состоялся|звонок не состоялся|диалог отсутствует|автоответчик|автоинформатор|голосовая почта|оставьте\s+(?:голосовое\s+)?сообщение|после\s+сигнала|абонент\s+(?:временно\s+)?недоступен|абонент\s+не\s+отвечает|абонент\s+занят|все\s+операторы\s+заняты|номер\s+не\s+обслуживается)$/i;

  const FILLER_WORDS = new Set([
    'угу',
    'ага',
    'мгм',
    'хм',
    'эм',
    'ээ',
    'мм',
    'ну',
    'алло',
    'ало',
    'ау',
    'ок',
    'окей',
    'да',
    'нет',
    'а',
  ]);

  let substantiveCount = 0;
  let managerSubstantive = 0;
  let clientSubstantive = 0;

  for (const line of lines) {
    if (/^автоинформатор\s*:/i.test(line)) continue;
    const isManager = /^(?:менеджер|администратор|оператор)\s*:/i.test(line);
    const isClient = /^(?:клиент|гость)\s*:/i.test(line);

    const body = line
      .replace(/^(?:менеджер|клиент|администратор|оператор|гость|собеседник|неизвестный)\s*:\s*/i, '')
      .replace(/\[(?:тишина|гудки|сброс|шум|музыка|нет\s+речи|автоответчик|нрзб)\]/giu, ' ')
      .replace(/[^\p{L}\p{N}\s]/gu, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase();

    if (!body || AUTO_RESPONDER_ONLY_RE.test(body)) continue;

    const allWords = body.split(' ').filter(Boolean);
    const meaningfulWords = allWords.filter((w) => !FILLER_WORDS.has(w));

    // Содержательной считается реплика, где есть >= 2 значимых слова (или 1 информативное слово при длине >= 4 и наличии контекста, не равного междометию)
    const isSubstantive =
      meaningfulWords.length >= 2 ||
      (meaningfulWords.length === 1 && allWords.length >= 2 && meaningfulWords[0].length >= 4);

    if (isSubstantive) {
      substantiveCount++;
      if (isManager) managerSubstantive++;
      else if (isClient) clientSubstantive++;
    }
  }

  if (substantiveCount < 2) return false;

  // Защита от автоответчика без реплик обеих сторон
  const hasAutoresponderText =
    /автоответчик|голосовая почта|оставьте\s+(?:голосовое\s+)?сообщение|после\s+сигнала|абонент\s+(?:временно\s+)?недоступен|абонент\s+занят|все\s+операторы\s+заняты/iu.test(
      rawWithoutIvr
    );
  if (hasAutoresponderText && (managerSubstantive === 0 || clientSubstantive === 0)) {
    return false;
  }

  return true;
}

export function validateResult(result: AnalysisResult, transcript?: string): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  const outcomeLower = String(result.key_facts?.call_outcome || '').toLowerCase().trim();
  const modelSaidNotHappened =
    result.is_conversation === false ||
    outcomeLower === 'не состоялся' ||
    outcomeLower === 'автоответчик' ||
    outcomeLower.includes('не состоялся') ||
    result.booking_status === 'не применимо';

  const effectiveTranscript = transcript || result.formatted_transcript || '';
  const isClassANoTopic = Boolean(effectiveTranscript && isShortNoTopicCall(effectiveTranscript));
  const hasLiveDialogue = effectiveTranscript && !isClassANoTopic ? hasSubstantiveLiveDialogue(effectiveTranscript) : false;

  let notHappened = modelSaidNotHappened || isClassANoTopic;
  if (modelSaidNotHappened && hasLiveDialogue) {
    console.warn('[GigaChat Repair] Стенограмма содержит живой диалог — вердикт модели «не состоялся» переопределён.');
    result.is_conversation = true;
    notHappened = false;
    const repairCtx = classifyCallContext(effectiveTranscript);
    if (result.booking_status === 'не применимо' || !result.booking_status) {
      result.booking_status = repairCtx.isConfirmedBooking
        ? 'согласие'
        : repairCtx.isDeclined
        ? 'отказ'
        : 'консультация';
    }
    if (result.key_facts) {
      if (
        !result.key_facts.call_outcome ||
        /не\s*состоял|автоответчик/i.test(String(result.key_facts.call_outcome))
      ) {
        result.key_facts.call_outcome =
          result.booking_status === 'согласие'
            ? 'запись'
            : result.booking_status === 'отказ'
            ? 'отказ'
            : 'консультация';
      }
      if (result.key_facts.booking_status === 'не применимо' || !result.key_facts.booking_status) {
        result.key_facts.booking_status = result.booking_status;
      }
    }
  }

  // A.1: Обнулять аудит по признаку «не состоялся» можно ТОЛЬКО если стенограмма
  // действительно пуста или состоит из тишины / автоинформатора (нет живого диалога).
  if (notHappened) {
    const prevScore =
      result.operator_score ??
      result.evaluation?.overall_score ??
      result.key_facts?.evaluation?.overall_score ??
      null;
    const hadAuditArtifacts =
      result.operator_score !== null ||
      (result.evaluation &&
        result.evaluation.overall_score !== null &&
        result.evaluation.overall_score !== undefined) ||
      (Array.isArray(result.criteria_scores) && result.criteria_scores.length > 0) ||
      (Array.isArray(result.evaluation?.criteria) && result.evaluation!.criteria.length > 0) ||
      (Array.isArray(result.operator_mistakes) && result.operator_mistakes.length > 0);

    if (hadAuditArtifacts) {
      console.warn(
        `[GigaChat Repair] Аудит обнулён: звонок не состоялся (была модельная ошибка operator_score${
          prevScore !== null ? `: ${prevScore}` : ''
        }).`
      );
    }

    result.criteria_scores = [];
    result.operator_score = null;
    result.operator_mistakes = [];
    result.booking_status = 'не применимо';
    if (result.evaluation) {
      result.evaluation = {
        ...result.evaluation,
        overall_score: null,
        applicable_count: 0,
        criteria: [],
        summary_verdict: 'Звонок не состоялся: оценка качества оператора не производится.',
      };
    }
    if (result.key_facts) {
      result.key_facts.call_outcome = 'не состоялся';
      result.key_facts.booking_status = 'не применимо';
      result.key_facts.criteria_scores = [];
      if (result.key_facts.evaluation) {
        result.key_facts.evaluation = {
          ...result.key_facts.evaluation,
          overall_score: null,
          applicable_count: 0,
          criteria: [],
          summary_verdict: 'Звонок не состоялся: оценка качества оператора не производится.',
        };
      }
    }
    result.recommendations = ['Повторить попытку дозвона клиенту в рабочее время салона.'];
  } else {
    if (typeof result.operator_score !== 'number') {
      errors.push('Разговор состоялся, но operator_score не число');
    }
    if (result.booking_status === 'не применимо') {
      errors.push('Разговор состоялся, но booking_status = "не применимо"');
    }
  }

  if (!notHappened && result.booking_status !== result.key_facts.booking_status) {
    errors.push('booking_status не совпадает с key_facts.booking_status');
  }

  // 1. call_outcome <-> booking_status
  const outcomeBookingMap: Record<string, string[]> = {
    'запись': ['согласие'],
    'отказ': ['отказ'],
    'консультация': ['консультация'],
    'перезвон': ['консультация'],
    'отмена': ['отказ', 'согласие', 'консультация'],
  };
  if (!notHappened) {
    const allowed = outcomeBookingMap[result.key_facts.call_outcome];
    if (allowed && result.booking_status && !allowed.includes(result.booking_status)) {
      errors.push(`call_outcome «${result.key_facts.call_outcome}» не согласован с booking_status «${result.booking_status}»`);
    }
  }

  // A.1.5: Авто-ремонт критериев 8 (альтернативы) и 9 (исходящее подтверждение) до проверки среднего балла и противоречий аудита
  if (!notHappened) {
    const repairCtx = effectiveTranscript ? classifyCallContext(effectiveTranscript) : null;
    const cleanTextForRepair = repairCtx?.cleanTranscript || effectiveTranscript;

    const collectCriteriaLists = (): any[][] => {
      const lists: any[][] = [];
      if (Array.isArray(result.criteria_scores)) lists.push(result.criteria_scores);
      if (result.evaluation && Array.isArray(result.evaluation.criteria) && result.evaluation.criteria !== result.criteria_scores) {
        lists.push(result.evaluation.criteria);
      }
      const kfObj = result.key_facts as any;
      if (kfObj && Array.isArray(kfObj.criteria_scores) && !lists.includes(kfObj.criteria_scores)) {
        lists.push(kfObj.criteria_scores);
      }
      if (kfObj?.evaluation && Array.isArray(kfObj.evaluation.criteria) && !lists.includes(kfObj.evaluation.criteria)) {
        lists.push(kfObj.evaluation.criteria);
      }
      return lists;
    };

    const criteriaLists = collectCriteriaLists();
    let criteriaMutated = false;

    // Авто-ремонт Критерия 1 («Приветствие и представление») при ASR-искажении названия салона («лис 28», «от, а, 28», «лик 28», «liq28»):
    // НЕ штрафовать менеджера за отсутствие названия салона, если оно озвучено, но распознано с фонетическим искажением.
    const openingSnippetForC1 = (cleanTextForRepair || '').slice(0, 220);
    const hasRecognizedOrDistortedSalonInOpening =
      /(?:студи|салон|fashion|фешен|фэшн|лук\s*студ|ли[кqс](?:\s*28)?|liq\s*28|от[,\s]+а[,\s]+28)/iu.test(
        openingSnippetForC1
      );
    const hasGreetingWordInOpening =
      /(?:добрый\s+(?:день|вечер)|доброе\s+утро|здравствуйте|приветствую|алло)/iu.test(openingSnippetForC1);
    const FALSE_MISSING_SALON_PENALTY_RE =
      /(?:не\s+(?:назвал[а]?|указал[а]?|озвучил[а]?|упомянул[а]?)\s+(?:название\s+)?(?:салона|бренда|студии)|отсутств\w*\s+(?:названи[ея]\s+)?салона)/iu;

    if (hasRecognizedOrDistortedSalonInOpening && hasGreetingWordInOpening && criteriaLists.length > 0) {
      let c1Repaired = false;
      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit1 = c.id === 'greeting_intro' || /приветствие/i.test(String(c.name || ''));
          if (!isCrit1) continue;
          const hasFalseSalonComplaint = FALSE_MISSING_SALON_PENALTY_RE.test(String(c.explanation || ''));
          const isPenalizedScore = typeof c.score === 'number' && !isNaN(c.score) && c.score < 8;
          if (hasFalseSalonComplaint || (isPenalizedScore && /лис\s*28|от[,\s]+а[,\s]+28|ли[кq]\s*28|liq\s*28/iu.test(openingSnippetForC1))) {
            c.is_applicable = true;
            if ('applicable' in c) {
              (c as any).applicable = true;
            }
            c.score = Math.max(typeof c.score === 'number' && !isNaN(c.score) ? c.score : 8, 9);
            c.explanation =
              'Приветствие выполнено корректно: название салона озвучено (учтено фонетическое искажение ASR).';
            c1Repaired = true;
            criteriaMutated = true;
          }
        }
      }
      if (Array.isArray(result.operator_mistakes)) {
        const cleanedC1Mistakes = result.operator_mistakes.filter(
          (m: string) => !FALSE_MISSING_SALON_PENALTY_RE.test(String(m || ''))
        );
        if (cleanedC1Mistakes.length !== result.operator_mistakes.length) {
          result.operator_mistakes = cleanedC1Mistakes;
          c1Repaired = true;
          if (result.transcript_summary) {
            const nextMistakesText = cleanedC1Mistakes.length > 0 ? cleanedC1Mistakes.join('; ') : 'не выявлены';
            result.transcript_summary = result.transcript_summary.replace(
              /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
              `$1${nextMistakesText}`
            );
          }
        }
      }
      if (c1Repaired) {
        console.warn(
          '[GigaChat Repair] Критерий 1 исправлен: название салона присутствует в приветствии (с учётом ASR-искажений «лис 28» / «от, а, 28» -> LIQ28).'
        );
      }
    }

    // Авто-ремонт Критерия 8 («Предложение альтернативных вариантов»):
    // если критерий 8 применим с низким баллом, а в стенограмме нет отказа или несогласия клиента — переводим в applicable: false
    const CLIENT_REFUSAL_OR_DISAGREEMENT_RE =
      /(?:не\s+подходит|не\s+удобно|неудобно|не\s+смогу|не\s+получится|не\s+получается|не\s+успею|не\s+успева[юе]|не\s+приду|не\s+подойду|не\s+интерес|не\s+нужно|не\s+надо|дорого|слишком\s+дорого|дороговато|передумал|отмен[а-яё]*\s+запис|отказываюсь|отказ|подумаю|перезвоню\s+позже|не\s+будет\s+в\s+городе|нет,\s*спасибо|пораньше\s+нельзя|нет\s+свободн|нет\s+мест|занят[аоы]?|не\s+работает|мы\s+не\s+(?:делаем|выполняем)|такой\s+услуги\s+нет|нет\s+такой\s+услуги|(?:^|[^\p{L}])нет,\s+[^\n.!?]{1,50}(?:надо|нужно|хотелось|друго[йе]|позже|раньше|не\s+))/iu;
    const hasClientRefusalOrDisagreement = Boolean(
      repairCtx?.isDeclined ||
        repairCtx?.isUnavailableServiceRefusal ||
        repairCtx?.isDispute ||
        (cleanTextForRepair && CLIENT_REFUSAL_OR_DISAGREEMENT_RE.test(cleanTextForRepair))
    );

    if (!hasClientRefusalOrDisagreement && criteriaLists.length > 0) {
      let c8Repaired = false;
      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit8 = c.id === 'alternatives' || /альтернатив/i.test(String(c.name || ''));
          const isApplicable = c.is_applicable === true || (c as any).applicable === true;
          const hasLowScore = typeof c.score === 'number' && !isNaN(c.score) && c.score < 8;
          if (isCrit8 && isApplicable && hasLowScore) {
            c.is_applicable = false;
            if ('applicable' in c) {
              (c as any).applicable = false;
            }
            c.score = null;
            c.explanation = 'Не применимо: в стенограмме отсутствует отказ или несогласие клиента.';
            if ('evidence_quote' in c) {
              c.evidence_quote = undefined;
            }
            c8Repaired = true;
            criteriaMutated = true;
          }
        }
      }
      if (c8Repaired) {
        console.warn(
          '[GigaChat Repair] Критерий 8 («Предложение альтернативных вариантов») переведён в applicable: false (score: null) — в стенограмме нет отказа или несогласия клиента.'
        );
        if (Array.isArray(result.operator_mistakes)) {
          const filtered = result.operator_mistakes.filter(
            (m: string) => !/(?:альтернативн|предложение альтернатив|лист ожидания)/i.test(String(m || ''))
          );
          if (filtered.length !== result.operator_mistakes.length) {
            result.operator_mistakes = filtered;
            if (result.transcript_summary) {
              const nextMistakesText = filtered.length > 0 ? filtered.join('; ') : 'не выявлены';
              result.transcript_summary = result.transcript_summary.replace(
                /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
                `$1${nextMistakesText}`
              );
            }
          }
        }
      }
    }

    // Авто-ремонт Критерия 9 (закрытие на запись — по сути, не по формулировке):
    // для класса «подтверждение существующей записи» (входящий и исходящий звонок) и любой подтверждённой записи:
    // если booking_status = «запись подтверждена» / «запись состоялась» / «согласие» и клиент подтвердил визит («да, я буду», «подтверждаю») —
    // оценка 9–10; формулировки «бронь не оформлена» и «попытка закрытия отсутствовала» запрещены независимо от балла.
    const CLIENT_VISIT_CONFIRM_RE =
      /(?:^|[\s,!.?«»"—\-])(?:да,?\s*я\s+буду|да,?\s*буду|я\s+буду|подтверждаю|обязательно\s+буду|конечно\s+буду|да,?\s*приду|да,?\s*подойду|да|буду|подойду|хорошо|спасибо|до\s+свидания|угу|ага|конечно)(?:$|[\s,!.?«»"—\-])/iu;
    const EXISTING_BOOKING_MENTION_RE =
      /(?:(?:вы|я)\s+(?:к\s+нам\s+|к\s+вам\s+)?записан[аы]?(?:\s+(?:на|к))?|(?:ваша|моя)\s+запись\s+(?:на|к)|напомина(?:ем|ю)\s+о\s+(?:вашей\s+)?записи|перенес[а-яё]*\s+(?:вашу\s+)?запись|подтверд[а-яё]*\s+(?:свою\s+|вашу\s+)?(?:запис|визит)|подтвержда(?:ю|ем|ете)\s+(?:свою\s+|вашу\s+)?(?:запис|визит)|подтверждение\s+(?:ранее\s+сделанной|существующей)\s+записи)/iu;
    const hasCancelOrRefusal = Boolean(
      repairCtx?.isDeclined ||
        (cleanTextForRepair && /(?:отмен[а-яё]*\s+запис|не\s+смогу\s+прийти|не\s+приду|не\s+подойду)/iu.test(cleanTextForRepair))
    );
    const hasClientVisitConfirmation = Boolean(
      cleanTextForRepair && !hasCancelOrRefusal && CLIENT_VISIT_CONFIRM_RE.test(cleanTextForRepair)
    );
    const bookingStatusRawStr = String(result.booking_status || '');
    const bookingDoneRawStr = String(
      result.structured_summary?.booking_status_text || (result.key_facts as any)?.is_booked_text || ''
    );
    const isDraftBookingConfirmedStatus = Boolean(
      result.booking_status === 'согласие' ||
        /запись\s+(?:подтверждена|состоялась)|подтверждение\s+(?:ранее\s+сделанной|существующей)\s+записи/i.test(
          `${bookingStatusRawStr} ${bookingDoneRawStr}`
        ) ||
        result.key_facts?.call_outcome === 'запись'
    );
    const isExistingConfirmationWithAgreement = Boolean(
      !hasCancelOrRefusal &&
        hasClientVisitConfirmation &&
        (isDraftBookingConfirmedStatus ||
          (cleanTextForRepair && EXISTING_BOOKING_MENTION_RE.test(cleanTextForRepair)))
    );
    const isBookingConfirmedOverall = Boolean(
      isExistingConfirmationWithAgreement ||
        isDraftBookingConfirmedStatus ||
        repairCtx?.isConfirmedBooking
    );
    const FORBIDDEN_CONFIRM_CLOSING_RE =
      /(?:бронь\s+не\s+оформлена|запись\s+не\s+оформлена|попытка\s+закрытия(?:\s+диалога)?(?:\s+на\s+запись)?\s+отсутствовала|визит\s+не\s+согласован)/iu;

    if (isBookingConfirmedOverall) {
      let c9Repaired = false;
      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit9 = c.id === 'closing' || /закрытие\s+на\s+запись/i.test(String(c.name || ''));
          if (!isCrit9) continue;
          const hasForbiddenText = FORBIDDEN_CONFIRM_CLOSING_RE.test(String(c.explanation || ''));
          const isLowOrInvalid =
            (isExistingConfirmationWithAgreement || c.is_applicable !== false) &&
            (c.is_applicable !== true || typeof c.score !== 'number' || isNaN(c.score) || c.score < 9);
          // Запрещённые формулировки вычищаем НЕЗАВИСИМО от балла; при низком балле или подтверждённом визите поднимаем до 9–10
          if (hasForbiddenText || isLowOrInvalid) {
            c.is_applicable = true;
            if ('applicable' in c) {
              (c as any).applicable = true;
            }
            c.score = typeof c.score === 'number' && c.score >= 9 && c.score <= 10 ? c.score : 10;
            c.explanation = isExistingConfirmationWithAgreement
              ? 'Существующая запись успешно подтверждена клиентом в ходе звонка-подтверждения (бронь существовала до звонка).'
              : 'Запись успешно согласована и подтверждена по итогам диалога.';
            c9Repaired = true;
            criteriaMutated = true;
          }
        }
      }
      if (Array.isArray(result.operator_mistakes)) {
        const cleanedC9Mistakes = result.operator_mistakes.filter(
          (m: string) => !FORBIDDEN_CONFIRM_CLOSING_RE.test(String(m || ''))
        );
        if (cleanedC9Mistakes.length !== result.operator_mistakes.length) {
          result.operator_mistakes = cleanedC9Mistakes;
          c9Repaired = true;
          if (result.transcript_summary) {
            const nextMistakesText = cleanedC9Mistakes.length > 0 ? cleanedC9Mistakes.join('; ') : 'не выявлены';
            result.transcript_summary = result.transcript_summary.replace(
              /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
              `$1${nextMistakesText}`
            );
          }
        }
      }
      if (Array.isArray(result.recommendations)) {
        const cleanedRecs = result.recommendations.filter(
          (r: string) => !FORBIDDEN_CONFIRM_CLOSING_RE.test(String(r || ''))
        );
        if (cleanedRecs.length !== result.recommendations.length) {
          result.recommendations = cleanedRecs;
          c9Repaired = true;
          if (result.transcript_summary) {
            const nextRecsText = cleanedRecs.length > 0 ? cleanedRecs.join('; ') : 'не требуются';
            result.transcript_summary = result.transcript_summary.replace(
              /(-\s*Советы по оптимизации:\s*)[^\n]*/i,
              `$1${nextRecsText}`
            );
          }
        }
      }
      if (typeof result.operator_comment === 'string' && FORBIDDEN_CONFIRM_CLOSING_RE.test(result.operator_comment)) {
        result.operator_comment = result.operator_comment
          .replace(new RegExp(FORBIDDEN_CONFIRM_CLOSING_RE.source, 'giu'), 'существующая запись подтверждена')
          .trim();
        c9Repaired = true;
      }
      if (c9Repaired) {
        console.warn(
          '[GigaChat Repair] Критерий 9 исправлен при подтверждённой записи (оценка 9–10, удалены запрещённые формулировки «бронь не оформлена» / «попытка закрытия отсутствовала»).'
        );
      }
    }

    // Авто-ремонт «интерес → отказ»: при фразе отказа клиента («нет», «не могу», «не сейчас») без подтверждённой записи
    // не формируем «желаемая услуга / дата / время» как подтверждённый факт и не выставляем оценку за «выявление потребности».
    const isClientRefusalNoBooking = Boolean(
      cleanTextForRepair &&
        !isBookingConfirmedOverall &&
        result.booking_status !== 'согласие' &&
        hasClientRefusalPhrase(cleanTextForRepair)
    );
    const isShortOutboundRefusal = Boolean(
      cleanTextForRepair &&
        !isBookingConfirmedOverall &&
        result.booking_status !== 'согласие' &&
        isShortOutboundRefusalCall(cleanTextForRepair)
    );

    if (isClientRefusalNoBooking) {
      let c2Disabled = false;
      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit2 =
            c.id === 'needs_identification' || /выявлени[ея]\s+потребност/i.test(String(c.name || ''));
          if (!isCrit2) continue;
          const isApplicable = c.is_applicable === true || (c as any).applicable === true || typeof c.score === 'number';
          if (isApplicable) {
            c.is_applicable = false;
            if ('applicable' in c) {
              (c as any).applicable = false;
            }
            c.score = null;
            c.explanation = 'Не применимо: в стенограмме зафиксирован отказ клиента (контроль «интерес → отказ»).';
            if ('evidence_quote' in c) {
              c.evidence_quote = undefined;
            }
            c2Disabled = true;
            criteriaMutated = true;
          }
        }
      }

      // Не выдаём «желаемая услуга / дата / время» как подтверждённый факт при отказе клиента
      if (result.key_facts) {
        result.key_facts.service = null;
        result.key_facts.date = null;
        result.key_facts.time = null;
        if (result.key_facts.requested_service !== NEEDS_VERIFICATION_LABEL) {
          result.key_facts.requested_service = 'не озвучено';
        }
        if (result.key_facts.offered_date_time !== NEEDS_VERIFICATION_LABEL) {
          result.key_facts.offered_date_time = 'не озвучено';
        }
      }
      if (result.structured_summary) {
        if (result.structured_summary.requested_service !== NEEDS_VERIFICATION_LABEL) {
          result.structured_summary.requested_service = 'не озвучено';
        }
        if (result.structured_summary.offered_date_time !== NEEDS_VERIFICATION_LABEL) {
          result.structured_summary.offered_date_time = 'не озвучено';
        }
      }
      if (result.key_facts?.structured_summary) {
        if (result.key_facts.structured_summary.requested_service !== NEEDS_VERIFICATION_LABEL) {
          result.key_facts.structured_summary.requested_service = 'не озвучено';
        }
        if (result.key_facts.structured_summary.offered_date_time !== NEEDS_VERIFICATION_LABEL) {
          result.key_facts.structured_summary.offered_date_time = 'не озвучено';
        }
      }

      if (c2Disabled) {
        if (Array.isArray(result.operator_mistakes)) {
          const filteredC2 = result.operator_mistakes.filter(
            (m: string) => !/(?:выявлени[ея]\s+потребност|не\s+выявил[а]?\s+потребност|не\s+задал[а]?\s+уточняющ)/i.test(String(m || ''))
          );
          if (filteredC2.length !== result.operator_mistakes.length) {
            result.operator_mistakes = filteredC2;
            if (result.transcript_summary) {
              const nextMistakesText = filteredC2.length > 0 ? filteredC2.join('; ') : 'не выявлены';
              result.transcript_summary = result.transcript_summary.replace(
                /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
                `$1${nextMistakesText}`
              );
            }
          }
        }
        console.warn(
          '[GigaChat Repair] Контроль «интерес → отказ»: Критерий 2 («Выявление потребности гостя») переведён в applicable: false (score: null), поля услуги/даты/времени сброшены как неподтверждённые.'
        );
      }
    }

    // Авто-ремонт для коротких исходящих звонков-обзвонов с быстрым отказом:
    // без жёсткого штрафа за «не оформленную запись», причина отказа и шаг «Запланировать повторный обзвон».
    if (isShortOutboundRefusal) {
      let outboundRepaired = false;
      const OUTBOUND_CLOSING_PENALTY_RE =
        /(?:бронь\s+не\s+оформлена|запись\s+не\s+оформлена|не\s+оформлен\w*\s+запис|попытка\s+закрытия(?:\s+диалога)?(?:\s+на\s+запись)?\s+отсутствовала|не\s+закрыл[а]?\s+на\s+запись|визит\s+не\s+согласован)/iu;

      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit9 = c.id === 'closing' || /закрытие\s+на\s+запись/i.test(String(c.name || ''));
          if (!isCrit9) continue;
          const hasHarshPenalty =
            (c.is_applicable === true || (c as any).applicable === true) &&
            ((typeof c.score === 'number' && !isNaN(c.score) && c.score < 7) ||
              OUTBOUND_CLOSING_PENALTY_RE.test(String(c.explanation || '')));
          if (hasHarshPenalty) {
            c.is_applicable = false;
            if ('applicable' in c) {
              (c as any).applicable = false;
            }
            c.score = null;
            c.explanation =
              'Короткий исходящий обзвон: клиент отказался / не смогла разговаривать, жёсткий штраф за неоформленную запись не применяется.';
            outboundRepaired = true;
            criteriaMutated = true;
          }
        }
      }

      if (Array.isArray(result.operator_mistakes)) {
        const cleanedOutboundMistakes = result.operator_mistakes.filter(
          (m: string) => !OUTBOUND_CLOSING_PENALTY_RE.test(String(m || ''))
        );
        if (cleanedOutboundMistakes.length !== result.operator_mistakes.length) {
          result.operator_mistakes = cleanedOutboundMistakes;
          outboundRepaired = true;
          if (result.transcript_summary) {
            const nextMistakesText =
              cleanedOutboundMistakes.length > 0 ? cleanedOutboundMistakes.join('; ') : 'не выявлены';
            result.transcript_summary = result.transcript_summary.replace(
              /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
              `$1${nextMistakesText}`
            );
          }
        }
      }

      if (result.structured_summary) {
        if (
          !result.structured_summary.unbooked_reason ||
          /^не\s+(?:применимо|озвучено|указано)$/i.test(result.structured_summary.unbooked_reason.trim())
        ) {
          result.structured_summary.unbooked_reason = 'клиент отказался / не смогла разговаривать';
        }
        if (
          !Array.isArray(result.structured_summary.manager_next_steps) ||
          result.structured_summary.manager_next_steps.length === 0
        ) {
          result.structured_summary.manager_next_steps = ['Запланировать повторный обзвон'];
        }
      }

      if (outboundRepaired) {
        console.warn(
          '[GigaChat Repair] Короткий исходящий обзвон с отказом: снят жёсткий штраф по Критерию 9 за неоформленную запись.'
        );
      }
    }

    // Авто-ремонт для Класса B («Частичный контакт» / «Справочный запрос»):
    // без штрафа по Критерию 9 за неоформленную бронь и без вердикта «требуется обучение».
    const classBRepairType =
      cleanTextForRepair && !isBookingConfirmedOverall
        ? classifyPartialOrInquiryCall(cleanTextForRepair)
        : null;
    if (classBRepairType) {
      let classBRepaired = false;
      const CLASS_B_CLOSING_PENALTY_RE =
        /(?:бронь\s+не\s+оформлена|запись\s+не\s+оформлена|не\s+оформлен\w*\s+запис|попытка\s+закрытия(?:\s+диалога)?(?:\s+на\s+запись)?\s+отсутствовала|не\s+закрыл[а]?\s+на\s+запись|визит\s+не\s+согласован)/iu;

      for (const list of criteriaLists) {
        for (const c of list) {
          if (!c) continue;
          const isCrit9 = c.id === 'closing' || /закрытие\s+на\s+запись/i.test(String(c.name || ''));
          if (!isCrit9) continue;
          const hasHarshPenalty =
            (c.is_applicable === true || (c as any).applicable === true) &&
            ((typeof c.score === 'number' && !isNaN(c.score) && c.score < 8) ||
              CLASS_B_CLOSING_PENALTY_RE.test(String(c.explanation || '')));
          if (hasHarshPenalty) {
            c.is_applicable = false;
            if ('applicable' in c) {
              (c as any).applicable = false;
            }
            c.score = null;
            c.explanation =
              classBRepairType === 'master_inquiry'
                ? 'Справочный запрос о наличии мастера: оформление брони не предполагалось, штраф по Критерию 9 не применяется.'
                : 'Частичный контакт (связь прервалась): оформление брони не состоялось не по вине оператора, штраф по Критерию 9 не применяется.';
            classBRepaired = true;
            criteriaMutated = true;
          }
        }
      }

      if (Array.isArray(result.operator_mistakes)) {
        const cleanedClassBMistakes = result.operator_mistakes.filter(
          (m: string) => !CLASS_B_CLOSING_PENALTY_RE.test(String(m || ''))
        );
        if (cleanedClassBMistakes.length !== result.operator_mistakes.length) {
          result.operator_mistakes = cleanedClassBMistakes;
          classBRepaired = true;
          if (result.transcript_summary) {
            const nextMistakesText =
              cleanedClassBMistakes.length > 0 ? cleanedClassBMistakes.join('; ') : 'не выявлены';
            result.transcript_summary = result.transcript_summary.replace(
              /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
              `$1${nextMistakesText}`
            );
          }
        }
      }

      const safeClassBVerdict =
        classBRepairType === 'master_inquiry'
          ? 'Справочный запрос обработан корректно; оформление записи не требовалось.'
          : 'Частичный контакт: диалог прервался до оформления записи, требуется повторный дозвон.';

      if (result.evaluation && /требуется\s+обучение/i.test(String(result.evaluation.summary_verdict || ''))) {
        result.evaluation.summary_verdict = safeClassBVerdict;
        classBRepaired = true;
      }
      const kfEvalObj = (result.key_facts as any)?.evaluation;
      if (kfEvalObj && /требуется\s+обучение/i.test(String(kfEvalObj.summary_verdict || ''))) {
        kfEvalObj.summary_verdict = safeClassBVerdict;
        classBRepaired = true;
      }
      if (typeof result.operator_comment === 'string' && /требуется\s+обучение/i.test(result.operator_comment)) {
        result.operator_comment = safeClassBVerdict;
        classBRepaired = true;
      }

      if (result.structured_summary) {
        if (
          !Array.isArray(result.structured_summary.manager_next_steps) ||
          result.structured_summary.manager_next_steps.length === 0
        ) {
          result.structured_summary.manager_next_steps =
            classBRepairType === 'master_inquiry'
              ? ['Перезвонить клиенту, когда мастер будет доступен.']
              : ['Повторить дозвон клиенту и отметить обращение в журнале.'];
        }
      }

      if (classBRepaired) {
        console.warn(
          `[GigaChat Repair] Класс B (${classBRepairType}): снят штраф по Критерию 9 и запрещённый вердикт «требуется обучение».`
        );
      }
    }

    if (criteriaMutated) {
      const primaryCriteria = criteriaLists[0] || [];
      const recalculatedScores = primaryCriteria
        .filter((c: any) => c && c.is_applicable === true && typeof c.score === 'number' && !isNaN(c.score))
        .map((c: any) => c.score as number);
      if (recalculatedScores.length > 0) {
        const recalculatedOverall = Math.round(
          recalculatedScores.reduce((s, v) => s + v, 0) / recalculatedScores.length
        );
        result.operator_score = recalculatedOverall;
        if (result.evaluation) {
          result.evaluation.applicable_count = recalculatedScores.length;
          result.evaluation.overall_score = recalculatedOverall;
        }
        const kfObj = result.key_facts as any;
        if (kfObj?.evaluation) {
          kfObj.evaluation.applicable_count = recalculatedScores.length;
          kfObj.evaluation.overall_score = recalculatedOverall;
        }
        if (result.transcript_summary) {
          result.transcript_summary = result.transcript_summary.replace(
            /(оценка\s*)\d{1,2}(\s*\/\s*10)/i,
            `$1${recalculatedOverall}$2`
          );
        }
      }
    }
  }

  // 2. operator_score <-> среднее применимых критериев (допуск ±1)
  const kfAny = result.key_facts as any;
  const criteria: any[] =
    (Array.isArray(result.criteria_scores) ? result.criteria_scores : null) ||
    ((result as any).evaluation && Array.isArray((result as any).evaluation.criteria)
      ? (result as any).evaluation.criteria
      : null) ||
    (Array.isArray(kfAny?.criteria_scores) ? kfAny.criteria_scores : []);
  const applicableScores = criteria
    .filter((c: any) => c && c.is_applicable === true && typeof c.score === 'number' && !isNaN(c.score))
    .map((c: any) => c.score as number);
  if (!notHappened && applicableScores.length > 0 && typeof result.operator_score === 'number') {
    const avg = Math.round(applicableScores.reduce((s, v) => s + v, 0) / applicableScores.length);
    if (Math.abs(result.operator_score - avg) > 1) {
      errors.push(`operator_score (${result.operator_score}) расходится со средним применимых критериев (${avg})`);
    }
  }

  // 3. Оценка в тексте резюме <-> operator_score (допуск ±1)
  if (!notHappened && typeof result.operator_score === 'number') {
    const m = String(result.transcript_summary || '').match(/оценка\s*(\d{1,2})\s*\/\s*10/i);
    if (m) {
      const summaryScore = parseInt(m[1], 10);
      if (!isNaN(summaryScore) && Math.abs(summaryScore - result.operator_score) > 1) {
        errors.push(`оценка в transcript_summary (${summaryScore}/10) расходится с operator_score (${result.operator_score})`);
      }
    }
  }

  // A.2. Фантомные ошибки допродаж: missed_opportunities пуст — чиним, удаляя формулировки про допродажи/дополнительные услуги
  const missed = (result as any).missed_opportunities;
  const PHANTOM_UPSELL_RE =
    /(?:не\s+предлож[а-яё]*\s+(?:сопутств|доп(?:олнительн)?|альтернатив|параллель|другого\s+специалиста|мастера\s+другой)|допродаж|дополнительн(?:ые|ых|ую)\s+услуг)/i;
  if (Array.isArray(missed) && missed.length === 0 && Array.isArray(result.operator_mistakes)) {
    const beforeLen = result.operator_mistakes.length;
    const cleanedMistakes = result.operator_mistakes.filter(
      (mm: string) => !PHANTOM_UPSELL_RE.test(String(mm || ''))
    );
    if (cleanedMistakes.length < beforeLen) {
      result.operator_mistakes = cleanedMistakes;
      if (result.transcript_summary) {
        const nextMistakesText = cleanedMistakes.length > 0 ? cleanedMistakes.join('; ') : 'не выявлены';
        result.transcript_summary = result.transcript_summary.replace(
          /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
          `$1${nextMistakesText}`
        );
      }
      console.warn(
        `[GigaChat Repair] Удалены формулировки о допродажах/дополнительных услугах (${beforeLen - cleanedMistakes.length}) при пустом missed_opportunities.`
      );
    }
  }

  // 5. Санитарная проверка мастера: поле не может быть не-именем
  const mVal = String(result.key_facts?.master || '').trim();
  if (mVal && /окошечк|окошк|слот|время|секунд|расписан|студио/i.test(mVal)) {
    errors.push(`в key_facts.master записано «${mVal}» — это не ФИО мастера`);
  }

  // 6. Цена: критерий применим, но суммы в offered_price нет
  const priceCrit = criteria.find((c: any) => c?.id === 'price_presentation');
  if (!notHappened && priceCrit?.is_applicable === true) {
    const priceText = String(result.key_facts?.offered_price || '');
    const hasPrice = /\d/.test(priceText) && !/не озвуч|не применимо/i.test(priceText);
    if (!hasPrice) {
      errors.push('price_presentation применим, но offered_price без суммы — стоимость в диалоге не озвучивалась');
    }
  }

  // 7. Согласованность аудита: пустой/безошибочный mistakes при критериях ниже 7 баллов — противоречие
  if (!notHappened) {
    const lowCriteria = criteria.filter(
      (c: any) => c && c.is_applicable !== false && typeof c.score === 'number' && !isNaN(c.score) && c.score < 7
    );
    if (lowCriteria.length > 0) {
      const mistakesArr = Array.isArray(result.operator_mistakes) ? result.operator_mistakes : [];
      const hasSubstantiveMistake = mistakesArr.some((m) => !isErrorFreeMistakeStatement(String(m || '')));
      if (!hasSubstantiveMistake) {
        const listStr = lowCriteria.map((c: any) => `${c.name || c.id}: ${c.score}/10`).join(', ');
        errors.push(
          `противоречие аудита: есть сниженные критерии ниже 7 баллов (${listStr}), но operator_mistakes пуст или утверждает отсутствие ошибок`
        );
      }
    }
  }

  return { valid: errors.length === 0, errors };
}

/**
 * Очередь запросов к GigaChat (FIFO) с ограничением параллелизма = 1.
 * Гарантирует, что к GigaChat идёт не более 1 запроса одновременно,
 * а остальные запросы последовательно ожидают в очереди.
 */
interface QueueTask<T> {
  id: string;
  description: string;
  fn: () => Promise<T>;
  resolve: (value: T | PromiseLike<T>) => void;
  reject: (reason?: any) => void;
  enqueuedAt: number;
}

export class GigaChatQueue {
  private queue: QueueTask<any>[] = [];
  private isProcessing = false;
  private currentTaskId: string | null = null;
  private totalProcessed = 0;
  private minIntervalMs = 400; // Минимальная пауза между запросами (защита от burst-лимитов)
  private lastRequestEndTime = 0;

  /**
   * Добавляет асинхронную задачу в очередь FIFO.
   */
  public enqueue<T>(fn: () => Promise<T>, description = 'Запрос к GigaChat'): Promise<T> {
    return new Promise<T>((resolve, reject) => {
      const id = `giga-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
      const task: QueueTask<T> = {
        id,
        description,
        fn,
        resolve,
        reject,
        enqueuedAt: Date.now(),
      };

      this.queue.push(task);
      const position = this.queue.length;

      if (this.isProcessing) {
        console.log(`[GigaChat Очередь] «${description}» [${id}] добавлен в очередь (позиция: ${position})`);
      }

      this.processNext();
    });
  }

  private async processNext(): Promise<void> {
    if (this.isProcessing || this.queue.length === 0) {
      return;
    }

    this.isProcessing = true;
    const item = this.queue.shift()!;
    this.currentTaskId = item.id;
    const waitTimeMs = Date.now() - item.enqueuedAt;

    try {
      // Соблюдение минимального интервала между последовательными запросами
      const elapsedSinceLast = Date.now() - this.lastRequestEndTime;
      if (this.lastRequestEndTime > 0 && elapsedSinceLast < this.minIntervalMs) {
        await new Promise(r => setTimeout(r, this.minIntervalMs - elapsedSinceLast));
      }

      if (waitTimeMs > 150) {
        console.log(`[GigaChat Очередь] Выполнение [${item.id}] «${item.description}» (ожидание в очереди: ${waitTimeMs} мс, осталось: ${this.queue.length})`);
      }

      const result = await item.fn();
      this.totalProcessed++;
      item.resolve(result);
    } catch (err) {
      item.reject(err);
    } finally {
      this.lastRequestEndTime = Date.now();
      this.currentTaskId = null;
      this.isProcessing = false;
      // Переход к следующему элементу в очереди
      setImmediate(() => this.processNext());
    }
  }

  public getStatus() {
    return {
      pending: this.queue.length,
      isProcessing: this.isProcessing,
      currentTaskId: this.currentTaskId,
      totalProcessed: this.totalProcessed,
    };
  }
}

export const gigaChatQueue = new GigaChatQueue();

export function getGigaChatQueueStatus() {
  return gigaChatQueue.getStatus();
}

const MAX_RETRIES = 4;
const BASE_DELAY_MS = 2000;
const MAX_DELAY_MS = 32000;

export type GigaChatLogCallback = (
  type: 'info' | 'warning' | 'error' | 'success',
  message: string
) => void;

/**
 * Выполняет анализ через GigaChat с очередью FIFO (параллелизм = 1)
 * и экспоненциальной задержкой retry (особенно при ошибках 429 Too Many Requests).
 */
export interface AnalyzeWithRetryOptions {
  throwOnUnavailable?: boolean;
  _timestampWarned?: boolean;
}

export async function analyzeWithRetry(
  transcript: string,
  model?: GigaChatModel,
  onLog?: GigaChatLogCallback,
  callDurationSeconds?: number,
  customSalonName?: string,
  customSystemPrompt?: string,
  callTimestamp?: string,
  options?: AnalyzeWithRetryOptions
): Promise<AnalysisResult> {
  const modelName = model || (process.env.GIGACHAT_MODEL as GigaChatModel) || (process.env.GIGACHAT_DEFAULT_MODEL as GigaChatModel) || 'GigaChat:Ultra';
  let timestampWarned = false;
  if ((!callTimestamp || !String(callTimestamp).trim()) && transcript && transcript.trim().length > 0) {
    const warnMsg = '[GigaChat WARNING] call_timestamp отсутствует — временные правила next_steps не применяются';
    console.warn(warnMsg);
    onLog?.('warning', warnMsg);
    timestampWarned = true;
  }
  return gigaChatQueue.enqueue(async () => {
    return executeWithExponentialBackoff(
      transcript,
      modelName,
      onLog,
      callDurationSeconds,
      customSalonName,
      customSystemPrompt,
      callTimestamp,
      { ...options, _timestampWarned: timestampWarned }
    );
  }, `Анализ транскрипта (${modelName})`);
}

async function executeWithExponentialBackoff(
  transcript: string,
  model: GigaChatModel,
  onLog?: GigaChatLogCallback,
  callDurationSeconds?: number,
  customSalonName?: string,
  customSystemPrompt?: string,
  callTimestamp?: string,
  options?: AnalyzeWithRetryOptions
): Promise<AnalysisResult> {
  let lastError: any = null;
  const attemptJsonErrorPositions: Array<number | null> = [];

  for (let attempt = 1; attempt <= MAX_RETRIES; attempt++) {
    try {
      return await analyzeWithGigaChat(
        transcript,
        model,
        callDurationSeconds,
        customSalonName,
        customSystemPrompt,
        callTimestamp,
        options
      );
    } catch (error: any) {
      lastError = error;
      attemptJsonErrorPositions.push(
        typeof error?.jsonErrorPos === 'number' && !Number.isNaN(error.jsonErrorPos)
          ? error.jsonErrorPos
          : null
      );

      // Если ключ GigaChat вообще не задан — не тратим время на 4 ретрая, сразу пробрасываем причину наверх
      if (error?.isGigaChatUnavailable) {
        const unavailMsg = error.fallbackReason || error.message || 'GigaChat не настроен (ключ отсутствует)';
        console.error(`[GigaChat] ${unavailMsg}`);
        if (onLog) onLog('error', unavailMsg);
        throw error;
      }

      const status = error.response?.status;
      const responseData = error.response?.data;
      const responseMsg = responseData?.message || responseData?.description || error.message || String(error);

      // Проверка на ошибку лимита 429 (Too Many Requests / Rate Limit)
      const is429 = status === 429 ||
        /429|too many requests|rate limit|queries per second|quota exceeded/i.test(responseMsg);

      // При ошибках аутентификации 401/403 сбрасываем кэш токена
      if (status === 401 || status === 403) {
        invalidateGigaChatTokenCache();
        console.warn(`[GigaChat] Ошибка авторизации (HTTP ${status}). Сброс токена и повторная авторизация...`);
      }

      console.error(
        `[GigaChat] Попытка ${attempt}/${MAX_RETRIES} завершилась ошибкой (HTTP ${status || 'ERR'}): ${responseMsg}`
      );

      if (attempt < MAX_RETRIES) {
        // Экспоненциальная задержка: 2s, 4s, 8s, 16s...
        const expDelay = Math.min(BASE_DELAY_MS * Math.pow(2, attempt - 1), MAX_DELAY_MS);

        // Проверка заголовка Retry-After (если предоставлен сервисом Сбера в секундах)
        let retryAfterMs = 0;
        const retryHeader = error.response?.headers?.['retry-after'];
        if (retryHeader) {
          const parsedSeconds = parseInt(retryHeader, 10);
          if (!isNaN(parsedSeconds) && parsedSeconds > 0) {
            retryAfterMs = parsedSeconds * 1000;
          }
        }

        // Небольшой случайный джиттер (±10%) для устранения резонансных всплесков
        const jitter = Math.floor(Math.random() * (expDelay * 0.2)) - (expDelay * 0.1);
        const finalDelay = Math.max(1000, Math.max(expDelay + jitter, retryAfterMs));
        const delaySec = (finalDelay / 1000).toFixed(1);

        if (is429) {
          const logMsg = `GigaChat: превышен лимит запросов (HTTP 429 Too Many Requests). Экспоненциальная пауза ${delaySec} сек перед повтором (попытка ${attempt}/${MAX_RETRIES})...`;
          console.warn(`[GigaChat RateLimit 429] ${logMsg}`);
          if (onLog) onLog('warning', logMsg);
        } else {
          const logMsg = `GigaChat: временный сбой (${responseMsg}). Повтор через ${delaySec} сек (попытка ${attempt}/${MAX_RETRIES})...`;
          console.log(`[GigaChat Retry] ${logMsg}`);
          if (onLog) onLog('warning', logMsg);
        }

        await new Promise(r => setTimeout(r, finalDelay));
      }
    }
  }

  const nonNullJsonPositions = attemptJsonErrorPositions.filter((p): p is number => p !== null);
  if (
    attemptJsonErrorPositions.length === MAX_RETRIES &&
    nonNullJsonPositions.length === MAX_RETRIES &&
    nonNullJsonPositions.every((p) => p === nonNullJsonPositions[0])
  ) {
    const systematicPos = nonNullJsonPositions[0];
    const systematicWarn = `[GigaChat] Систематический дефект JSON в позиции ${systematicPos}`;
    console.warn(systematicWarn);
    if (onLog) onLog('warning', systematicWarn);
  }

  const rawErrMsg = lastError?.jsonErrorMessage || lastError?.message || String(lastError);
  const fallbackReason = lastError?.isJsonFormatError
    ? `ошибка формата после ${MAX_RETRIES} попыток: ${rawErrMsg}`
    : `ошибка после ${MAX_RETRIES} попыток: ${rawErrMsg}`;
  const failMsg = `GigaChat недоступен (${fallbackReason})`;
  console.error(`[GigaChat] ${failMsg}`);
  if (onLog) onLog('error', failMsg);
  const err: any = new Error(failMsg);
  err.fallbackReason = fallbackReason;
  if (lastError?.isJsonFormatError) {
    err.isJsonFormatError = true;
    err.jsonErrorPos = lastError.jsonErrorPos;
  }
  throw err;
}


export async function analyzeWithGigaChat(
  transcript: string,
  modelOverride?: GigaChatModel,
  callDurationSeconds?: number,
  customSalonName?: string,
  customSystemPrompt?: string,
  callTimestamp?: string,
  options?: AnalyzeWithRetryOptions
): Promise<AnalysisResult> {
  const model: GigaChatModel = modelOverride || (process.env.GIGACHAT_MODEL as GigaChatModel) || (process.env.GIGACHAT_DEFAULT_MODEL as GigaChatModel) || 'GigaChat:Ultra';

  // Жёсткий предохранитель: при длительности менее 10 секунд без живого диалога
  // ИЛИ при звонке Класса A (<= 30 сек, <= 4 реплик без темы записи/услуги/мастера/цены) LLM не вызываем —
  // возвращаем результат «Не состоялся / короткий вызов», чтобы исключить фантазии модели.
  if (
    (callDurationSeconds !== undefined && callDurationSeconds < 10 && !hasSubstantiveLiveDialogue(transcript)) ||
    isShortNoTopicCall(transcript, callDurationSeconds)
  ) {
    const classAReason =
      callDurationSeconds !== undefined && callDurationSeconds < 10
        ? `длительность звонка < 10 сек (${callDurationSeconds} сек)`
        : 'короткий вызов без темы записи/услуги (Класс A)';
    return generateLocalFallbackAnalysis(
      transcript,
      model,
      callDurationSeconds,
      customSalonName,
      classAReason,
      callTimestamp
    );
  }

  const hasCallTimestamp = Boolean(callTimestamp && String(callTimestamp).trim().length > 0);
  if (!hasCallTimestamp && !options?._timestampWarned && transcript && transcript.trim().length > 0) {
    console.warn('[GigaChat WARNING] call_timestamp отсутствует — временные правила next_steps не применяются');
  }

  if (!isGigaChatConfigured()) {
    const reason = 'GigaChat не настроен (ключ отсутствует)';
    if (options?.throwOnUnavailable) {
      const err: any = new Error(reason);
      err.isGigaChatUnavailable = true;
      err.fallbackReason = reason;
      throw err;
    }
    // Если GigaChat не настроен — возвращаем локальный резервный анализ с явным указанием причины.
    return generateLocalFallbackAnalysis(transcript, model, callDurationSeconds, customSalonName, reason, callTimestamp);
  }

  const token = await getGigaChatToken();
  const formattedCallDateTime = formatCallDateTimeInSalonTz(callTimestamp);
  console.log(
    `[GigaChat] Анализ моделью: ${model} (длительность звонка: ${callDurationSeconds ?? 'не указана'} сек., время звонка: ${formattedCallDateTime || 'не указано'})`
  );

  const gigachatApiUrl = process.env.GIGACHAT_API_URL || 'https://gigachat.devices.sberbank.ru/api/v1/chat/completions';

  // Системная часть: кастомный системный промпт из настроек администратора (если задан), иначе дефолтный шаблон с актуальным списком мастеров из CRM.
  // В обоих случаях динамический список мастеров из YClients имеет приоритет перед жёстко зафиксированным в промпте,
  // а блок МЕТАДАННЫЕ ЗВОНКА добавляется с датой и временем звонка в часовом поясе салона.
  const metadataBlock = buildCallMetadataBlock(callTimestamp);
  const { list: crmMasters, source: crmMastersSource } = await getCrmMastersWithSource();
  let systemPromptContent: string;
  if (customSystemPrompt && customSystemPrompt.trim().length > 30) {
    const trimmedCustom = customSystemPrompt.trim();
    const withDynamicMasters =
      crmMastersSource === 'yclients'
        ? injectDynamicMastersIntoPrompt(trimmedCustom, crmMasters, 'yclients')
        : trimmedCustom;
    systemPromptContent = withDynamicMasters.includes('МЕТАДАННЫЕ ЗВОНКА:')
      ? withDynamicMasters
      : `${withDynamicMasters}\n\n${metadataBlock}`;
  } else {
    systemPromptContent = getSystemPrompt(customSalonName, crmMasters, callTimestamp);
    if (!systemPromptContent.includes('МЕТАДАННЫЕ ЗВОНКА:')) {
      systemPromptContent = `${systemPromptContent}\n\n${metadataBlock}`;
    }
  }
  const messages = [
    { role: 'system', content: systemPromptContent },
    { role: 'user', content: buildUserPrompt(transcript, callDurationSeconds) },
  ];

  const res = await axios.post(
    gigachatApiUrl,
    {
      model,
      messages,
      temperature: 0,
      max_tokens: 4000,
    },
    {
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      timeout: 60000,
    }
  );

  const rawContent = res.data.choices?.[0]?.message?.content;
  if (!rawContent) {
    throw new Error('GigaChat вернул пустой ответ');
  }

  // Пытаемся распарсить JSON, при неудаче — просим модель исправить конкретное проблемное место.
  let draft: AnalysisResult;
  try {
    draft = parseGigaChatJson(rawContent, customSalonName, transcript, callTimestamp);
  } catch (parseErr: any) {
    const errMsg = parseErr?.jsonErrorMessage || parseErr?.message || String(parseErr);
    const errPos = parseErr?.jsonErrorPos;
    const errSnippet = parseErr?.jsonErrorSnippet || '';
    console.warn(
      `[GigaChat] Первый парсинг JSON не удался (${errMsg}${
        typeof errPos === 'number' ? `, позиция ${errPos}` : ''
      }), отправка запроса на исправление формата...`
    );
    const repairPrompt = [
      'Твой предыдущий ответ содержит ошибку синтаксиса JSON и не может быть распарсен.',
      `Текст ошибки JSON.parse: ${errMsg}${typeof errPos === 'number' ? ` (позиция ${errPos})` : ''}.`,
      errSnippet ? `Фрагмент сырого ответа вокруг ошибки (±200 символов):\n${errSnippet}` : '',
      'Исправь это конкретное место (убери десятичные запятые в числах, экранируй кавычки внутри строковых значений, убери хвостовые запятые) и верни ТОЛЬКО полный валидный JSON без пояснений и markdown-обёрток.',
    ]
      .filter(Boolean)
      .join('\n');

    const retryRes = await axios.post(
      gigachatApiUrl,
      {
        model,
        messages: [
          ...messages,
          { role: 'assistant', content: rawContent },
          { role: 'user', content: repairPrompt },
        ],
        temperature: 0,
        max_tokens: 4000,
      },
      {
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        timeout: 60000,
      }
    );

    const retryContent = retryRes.data.choices?.[0]?.message?.content || '';
    draft = parseGigaChatJson(retryContent, customSalonName, transcript, callTimestamp);
  }

  // Второй независимый проход верификации (Pass 2): проверяет ТОЛЬКО стенограмму и черновик
  if (draft.booking_status !== 'не применимо' && transcript.trim().length >= 15) {
    try {
      await new Promise((r) => setTimeout(r, 350)); // бережём RPS лимиты перед второй сессией
      const verified = await runTwoPassVerification(transcript, draft, {
        apiUrl: gigachatApiUrl,
        token,
        model,
      });
      const flagsCount = verified.verification_flags?.length || 0;
      const critFlagsCount = verified.verification_report?.criteria_flags?.length || 0;
      const caughtQuotes = verified.verification_report?.hallucinated_quotes_caught || 0;
      const disputedFieldDetails = (verified.verification_report?.fields || [])
        .filter((f) => verified.verification_flags?.includes(f.field))
        .map((f) => {
          const quoteDetail = f.rejected_quote
            ? `, цитата не найдена: "${f.rejected_quote.slice(0, 60)}"`
            : f.verdict === 'contradicts' && f.corrected_value
            ? `, исправлено на: "${f.corrected_value}"`
            : '';
          return `${f.field} (${f.verdict}${quoteDetail})`;
        });
      const disputedCriteriaDetails = (verified.verification_report?.criteria_flags || []).map((cid) => {
        const item = verified.verification_report?.criteria_items?.find((it) => it.id === cid);
        const quoteDetail = item?.rejected_quote ? `, цитата не найдена: "${item.rejected_quote.slice(0, 60)}"` : '';
        return `критерий:${cid} (${item?.verdict || 'unconfirmed'}${quoteDetail})`;
      });
      const disputedList = [...disputedFieldDetails, ...disputedCriteriaDetails];
      console.log(
        `[GigaChat Verifier] Фактчек завершён: вердикт="${verified.verification_report?.summary_verdict || 'ок'}", флагов полей=${flagsCount}, флагов критериев=${critFlagsCount}, отсечено фейковых цитат=${caughtQuotes}${
          disputedList.length > 0 ? ` | Спорные поля: ${disputedList.join('; ')}` : ''
        }`
      );
      return verified;
    } catch (verifyErr: any) {
      console.warn(
        `[GigaChat Verifier] Пропуск верификации из-за сбоя API (возвращаем черновик 1-го прохода): ${verifyErr.message || verifyErr}`
      );
    }
  }

  // Гарантируем согласованность блока ошибок с критериями оценки (< 7) и в обычном (не верифицированном) пайплайне
  if (draft.booking_status !== 'не применимо' && Array.isArray(draft.evaluation?.criteria)) {
    const visitDateCtx =
      draft.structured_summary?.offered_date_time ||
      draft.key_facts?.offered_date_time ||
      draft.key_facts?.date ||
      null;
    const reconciledDraft = reconcileMistakesWithCriteria(
      draft.operator_mistakes || [],
      draft.evaluation.criteria,
      callTimestamp || draft.key_facts?.call_datetime || null,
      visitDateCtx,
      draft.formatted_transcript || transcript
    );
    if (
      reconciledDraft.fixedFromCriteria ||
      JSON.stringify(draft.operator_mistakes || []) !== JSON.stringify(reconciledDraft.mistakes)
    ) {
      draft.operator_mistakes = reconciledDraft.mistakes;
      if (draft.transcript_summary) {
        draft.transcript_summary = draft.transcript_summary.replace(
          /(-\s*Ошибки и недочеты:\s*)[^\n]*/i,
          `$1${reconciledDraft.mistakes.length > 0 ? reconciledDraft.mistakes.join('; ') : 'не выявлены'}`
        );
      }
    }
  }

  return draft;
}

